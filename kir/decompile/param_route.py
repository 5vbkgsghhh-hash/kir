def route_skip(category: str) -> frozenset[str]:
    """Names not asked for this category. Empty means we ask everything.

    An unknown category yields an EMPTY set, not a refusal: the absence of
    evidence means "ask everything", and that is the only safe default
    answer.
    """
    return ROUTE.get(category, frozenset())


def verify_against_receipts(category: str, receipts) -> dict[str, str]:
    """A LOUD refusal if a cut name turns up anyway.

    The input is receipts from a SAMPLED full run. Returns `name -> reason`
    only for discrepancies; an empty dict means "the table holds".

    A discrepancy here is not a reason to "patch it on the fly": it means the
    table describes the wrong model, and that must be decided by a human, not
    a silent branch.
    """
    skip = route_skip(category)
    if not skip:
        return {}
    bad: dict[str, str] = {}
    for receipt in receipts or ():
        name = getattr(receipt, "parameter", None)
        if name is None and isinstance(receipt, dict):
            name = receipt.get("parameter")
        if name not in skip:
            continue
        def get(field):
            if isinstance(receipt, dict):
                return receipt.get(field) or 0
            return getattr(receipt, field, 0) or 0
        found = (get("instance_hit") + get("type_hit")
                 + get("no_value") + get("wrong_storage"))
        if found:
            bad[name] = (
                "маршрут отсекает имя, у которого СХЕМА ЕСТЬ: попаданий %d "
                "на категории %s — таблица описывает другую модель"
                % (found, category))
        elif get("exception"):
            bad[name] = (
                "выборочный прогон упал на %d элементах: держится таблица "
                "или нет — НЕИЗВЕСТНО" % get("exception"))
    return bad
