def _read_index(path) -> dict:
    """🔴 ONE READER FOR BOTH TESTS — BECAUSE THERE WERE TWO AND THEY DIVERGED.

    Measurement 2026-08-22, running the suite piece by piece: both tests
    in this file are red, from ONE cause in two forms. `snapshot_file_exists`
    was called by both, but imported only by the second — locally, inside
    its own body. The first failed with `NameError`. And both read
    `path.read_text()` raw, even though the cleanup job had compressed
    `sklnk_eom_r26_v7`: the guard sees `.json.gz` and says "exists," while
    a raw read looks for `.json` and says "no such file" — that is, OUR
    blindness disguised as a fact about the corpus. This is a recorded
    defect class ("reading a frozen copy with a raw open"), and here it
    was paid for again, by both halves at once.
    """
    with open_snapshot(path, "rt", encoding="utf-8") as handle:
        return json.load(handle)["family_placement_index"]


def _raw(element_id: str = "10", **overrides) -> dict:
    """A raw row WITHOUT a point — exactly the case this file is about."""
    row = {
        "element_id": element_id,
        "symbol_id": "800",
        "type_name": "С остеклением",
        "family_name": "Системная панель",
        "placement_type": "OneLevelBased",
        "in_place": False,
        "mirrored": False,
        "hand_flipped": False,
        "facing_flipped": False,
        "super_component_id": None,
        "group_id": None,
        "host_id": "900",
        "host_class": "Wall",
        "hand_orientation": [1.0, 0.0, 0.0],
        "facing_orientation": [0.0, 1.0, 0.0],
        "status": "ok",
    }
    row.update(overrides)
    return row


class TheAbsenceOfAPointNamesItself(unittest.TestCase):
    """An empty point is a typed reason, not silence."""

    def test_curtain_panel_absence_is_typed(self) -> None:
        record = FamilyPlacementRecord.from_raw(
            _raw(location_absence="curtain_grid_generated"))
        self.assertIs(
            record.location_absence, LocationAbsence.CURTAIN_GRID_GENERATED)
        self.assertFalse(record.placement_available)
        self.assertIsNone(record.point_mm)
        self.assertIsNone(record.rotation_deg)

    def test_every_absence_spelling_is_accepted(self) -> None:
        for spelling in ("curtain_grid_generated", "face_hosted",
                         "work_plane_based", "unreadable"):
            with self.subTest(spelling=spelling):
                record = FamilyPlacementRecord.from_raw(
                    _raw(location_absence=spelling))
                self.assertEqual(record.location_absence.value, spelling)

    def test_an_unknown_absence_is_refused(self) -> None:
        # An unfamiliar word is NOT "probably unreadable": a reason we do
        # not know how to read must fail, not be silently coarsened.
        with self.assertRaises(FamilyPlacementPayloadError):
            FamilyPlacementRecord.from_raw(
                _raw(location_absence="probably_fine"))

    def test_an_available_placement_explains_nothing(self) -> None:
        # There is a point — nothing to explain. A row carrying both
        # means the emitter contradicts itself.
        with self.assertRaises(FamilyPlacementPayloadError):
            FamilyPlacementRecord.from_raw(_raw(
                point_ft=[1.0, 2.0, 3.0], rotation_rad=0.0,
                location_absence="face_hosted"))

    def test_a_legacy_row_without_the_cause_still_loads(self) -> None:
        # A frozen copy of the corpus was taken with a schema that did
        # not read reasons. Such a row must load, and None here means
        # EXACTLY "did not look," not "there is no reason" — a
        # distinction the lift builds its wording on.
        record = FamilyPlacementRecord.from_raw(_raw())
        self.assertIsNone(record.location_absence)
        self.assertFalse(record.placement_available)


class ATransformIsNeverAnInsertionPoint(unittest.TestCase):
    """The file's main guard: a transform cannot become a point."""

    def test_transform_is_read_but_kept_out_of_the_point(self) -> None:
        record = FamilyPlacementRecord.from_raw(_raw(
            location_absence="face_hosted",
            transform_origin_ft=[1.0, -2.0, 3.5],
            transform_basis_x=[1.0, 0.0, 0.0],
            transform_basis_y=[0.0, 1.0, 0.0],
            transform_basis_z=[0.0, 0.0, 1.0],
        ))
        self.assertIsNotNone(record.transform_origin_mm)
        # RAW feet are converted to mm with the same factor as the point.
        self.assertAlmostEqual(record.transform_origin_mm[0], 304.8, places=6)
        # ...and did not become an insertion point in the process.
        self.assertIsNone(record.point_mm)
        self.assertIsNone(record.rotation_deg)
        self.assertFalse(record.placement_available)

    def test_a_row_cannot_carry_both_a_point_and_a_transform(self) -> None:
        # A structural prohibition on substitution: as long as these two
        # fields cannot stand side by side, no code branch can silently
        # promote a transform into a point — to do that it would first
        # have to break the invariant.
        with self.assertRaises(FamilyPlacementPayloadError):
            FamilyPlacementRecord(
                element_id="10", symbol_id="800", type_name="t",
                family_name="f",
                placement_type=FamilyPlacementType.ONE_LEVEL_BASED,
                in_place=False, mirrored=False, hand_flipped=False,
                facing_flipped=False, super_component_id=None, group_id=None,
                host_id=None, host_class=None,
                hand_orientation=(1.0, 0.0, 0.0),
                facing_orientation=(0.0, 1.0, 0.0),
                placement_available=True,
                point_mm=(1.0, 2.0, 3.0), rotation_deg=0.0,
                transform_origin_mm=(1.0, 2.0, 3.0),
                transform_basis_x=(1.0, 0.0, 0.0),
                transform_basis_y=(0.0, 1.0, 0.0),
                transform_basis_z=(0.0, 0.0, 1.0),
            )

    def test_an_origin_without_a_basis_is_refused(self) -> None:
        # Half a transform is not a transform: without a basis there is
        # nothing to recover the orientation from, and "there is an
        # origin, no rotation" looks like a point.
        with self.assertRaises(FamilyPlacementPayloadError):
            FamilyPlacementRecord.from_raw(_raw(
                location_absence="face_hosted",
                transform_origin_ft=[1.0, -2.0, 3.5]))

    def test_a_degenerate_basis_is_refused(self) -> None:
        with self.assertRaises(FamilyPlacementPayloadError):
            FamilyPlacementRecord.from_raw(_raw(
                location_absence="face_hosted",
                transform_origin_ft=[1.0, -2.0, 3.5],
                transform_basis_x=[1.0, 0.0, 0.0],
                transform_basis_y=[1.0, 0.0, 0.0],
                transform_basis_z=[0.0, 0.0, 1.0]))


class TheProbeReadsTheThirdSourceUnderItsOwnGuard(unittest.TestCase):
    """Every optional read is under ITS OWN guard."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.body = build_family_placement_extract_cs(["1", "2"])

    def test_the_transform_member_is_the_one_that_exists(self) -> None:
        # MEASURED against the member index (35,516 members, six
        # versions): ``FamilyInstance.GetTransform`` DOES NOT EXIST. The
        # member is declared on Autodesk.Revit.DB.Instance (all six
        # versions, since 2012). The test pins down the actual call, not
        # a name pulled from memory.
        self.assertIn("GetTransform()", self.body)

    def test_the_third_source_never_writes_the_point(self) -> None:
        # No row puts a transform into point_ft/rotation_rad.
        for forbidden in ('__row["point_ft"] = __fpRawPoint(__xf',
                          '__row["point_ft"] = __fpRawPoint(__transform',
                          '__row["rotation_rad"] = __xf'):
            with self.subTest(forbidden=forbidden):
                self.assertNotIn(forbidden, self.body)
        self.assertIn('__row["transform_origin_ft"]', self.body)

    def test_each_optional_read_has_its_own_catch(self) -> None:
        # A single try around the whole element is exactly the shape of
        # the bug (see 12,369 rooms, cb9c3b65). New reads must fail individually.
        for guarded in ("__fpTryHostFace", "__fpTryTransform",
                        "__fpTryLocation"):
            with self.subTest(guarded=guarded):
                self.assertIn(guarded, self.body)

    def test_the_curtain_panel_test_is_structural(self) -> None:
        # A curtain-wall panel is recognized by the CLASS
        # Autodesk.Revit.DB.Panel, not by the family name or the
        # category name: a name lies easily.
        self.assertIn("Autodesk.Revit.DB.Panel", self.body)
        self.assertNotIn("Системная панель", self.body)
        self.assertNotIn("System Panel", self.body)

    def test_the_probe_is_still_shippable(self) -> None:
        # 🔴 THE SKIP WAS WIRED UP ON 2026-08-28, AND THE MARKER HAD BEEN
        # WAITING FOR IT SINCE THE START. The file's header requires: "a
        # test that needs a host must be SKIPPED with a named reason,
        # not green by construction." `_НЕТ_ХОСТА` was set up and read
        # by NO ONE — without a host the test failed with
        # `TypeError: NoneType is not callable`, that is, a failure
        # about US, spoken in the voice of an assertion about the
        # probe's fitness. The requirement stood in the prose and did
        # not stand in the code — the second such case this shift.
        if wrap_user_code is None:
            self.skipTest("обёртка исполнения — у хоста: " + _НЕТ_ХОСТА)
        validate_code_safety(self.body)
        # The wrapper INDENTS every line of the body, so what is checked
        # is the first line, not the first forty characters: forty
        # characters now step over a line break (the body begins with
        # the source binding ``Document __src = ...``), and the test
        # would be measuring the indentation, not the delivery.
        self.assertIn(self.body.strip().splitlines()[0],
                      wrap_user_code(self.body))


