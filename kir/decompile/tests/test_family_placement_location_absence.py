"""Why an instance has NO insertion point — and why a transform will not become one.

MEASUREMENT 2026-07-29 (four documents, 55 saved decompiles,
``coverage_matrix_2026-07-29.json``). The reason "FamilyInstance has no
captured LocationPoint and rotation" stood against 7,083 elements, and
the theory "these are face-hosted / work-plane-based families, their
position lives in GetTransform()" was NOT confirmed. A by-name breakdown
of all four documents (the lift run live against frozen L0s):

    446 + 600 + 5880 + 157 = 7083 — and EVERY SINGLE ONE OST_CurtainWallPanels.

Not one face-hosted, not one work-plane-based. Moreover: in K2, all
5,060 ``WorkPlaneBased`` instances DO HAVE a point — meaning the class
the theory called a hole is, in fact, fully readable.

From this follow two obligations that this file guards:

1. A curtain-wall panel has no insertion point BY CONSTRUCTION: its
   position is generated by the host's cut grid, and it is placed not by
   ``NewFamilyInstance`` but by assigning a type to a cell. Substituting
   a free point from ``GetTransform()`` for it would mean passing off a
   silent loss of binding as success (§18.1).
2. The absence of a point must NAME ITSELF. "Failed to read" and "does
   not exist here" are different claims, and only the second says
   anything about the model.

That is why the transform is read as a THIRD SOURCE, but is placed into
fields that do not pretend to be an insertion point, and the record's
invariant forbids a row from carrying both a point and a transform at
the same time — one cannot be substituted for the other structurally.
"""

