def _tracked_files() -> frozenset | None:
    """Git-tracked files — the definition of the PRODUCT. `None` — git did not answer.

    🔴 WHY A SEPARATE DEFINITION, NOT "EVERYTHING THAT ISN'T SCRATCH". The
    product is what SHIPS, and what ships is the tracked set. Everything
    else (shift scratch, foreign environments, frozen copies of the tree)
    does not go into the license, and counting it together with the
    product means answering the wrong question. `None` is not replaced by
    a guess: the traversal then honestly says it split by PATH, not by
    git.
    """
    # `--cached --others --exclude-standard` — tracked PLUS new files not
    # yet added, but also not ignored. Plain `ls-files` would count a new
    # product file as scratch right up to the commit, meaning a leak in a
    # fresh file would miss the product count exactly when it is
    # introduced. Ignored paths (`.work/`, builds, environments) do not
    # enter here by construction.
    listed = _git("ls-files", "--cached", "--others", "--exclude-standard")
    if listed == "?" or not listed:
        return None
    return frozenset(line for line in listed.splitlines() if line)


