def build() -> str:
    parts: list[str] = [
        BEGIN, "",
        "## СОСТОЯНИЕ КОМПИЛЯТОРА — порождается, руками не править", "",
        "🔴 **Этот блок мутирует, а проза — нет.** Храповик "
        "`kir/tests/test_kir_canon_state_is_current.py` краснеет, когда блок "
        "разошёлся с кодом. Всё, что выше и ниже блока, — ФОРМЫ дефекта: они "
        "не гниют и порождению не подлежат. Всё, что несёт ЧИСЛО, — здесь.", "",
        "Снято прибором `tools/kir_canon_state.py`, интерпретатор **Python %s**, "
        "дерево **%s**. Число без дерева и без вызова — не число (форма 26)."
        % (_interpreter(), _tree_id()), "",
        "| что | сколько |", "|---|---|",
    ]
    for section in (_size(), _registry(), _refusals(), _atoms(),
                    _reachability(), _oss_boundary()):
        parts.extend(section)
    parts.extend(_machine_dependent())
    parts += ["", END]
    text = "\n".join(parts)
    if len(text) > CHAR_BUDGET:
        raise CanonStateError(
            "состояние не помещается в бюджет: %d символов при потолке %d. "
            "Сокращать надо ФОРМУ строки, а не список." % (len(text), CHAR_BUDGET))
    return text


def current_block(path: str = CANON) -> str | None:
    """The block as it currently sits in the file. `None` — there is no block at all.

    A missing block and a matching block are DIFFERENT facts, and the
    first must be visible as a refusal, not as a silent "no discrepancies"."""
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return None
    if BEGIN not in text or END not in text:
        return None
    return BEGIN + text.split(BEGIN, 1)[1].split(END, 1)[0] + END


def write_into(path: str = CANON) -> bool:
    """Write the block in. `True` — the file changed.

    🔴 THE DIFF IS READ BEFORE `--write` (NAKAZ point 17). Regeneration
    destroys edits made outside the source and kills the signal in one
    move: if what comes with a `+` sign is something YOU measured TODAY,
    that is not a discrepancy, it is your loss.
    """
    block = build()
    with open(path, encoding="utf-8") as handle:
        text = handle.read()
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _old, tail = rest.split(END, 1)
        new = head + block + tail
    else:
        # The first insertion is IMMEDIATELY AFTER the file header, before
        # RULE ZERO: state is read before the forms, and it must stand
        # where people look first.
        anchor = "\n---\n"
        if anchor in text:
            head, tail = text.split(anchor, 1)
            new = head + anchor + "\n" + block + "\n" + anchor + tail
        else:
            new = block + "\n\n" + text
    if new == text:
        return False
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(new)
    return True


def main(argv: list[str]) -> int:
    if "--write" in argv:
        changed = write_into()
        print("состояние вписано" if changed else "состояние уже совпадает")
        return 0
    print(build())
    return 0


