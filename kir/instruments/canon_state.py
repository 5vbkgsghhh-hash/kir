def _size() -> list[str]:
    """Size of the compiler. It is computed, not rewritten.

    The definition is the same as the canon's before the split, with the
    root swapped: it used to be
    `find kukai/ir -name '*.py' -not -path '*/tests/*'`, now it is the same
    over `kir/`. A definition of its own would give a number of its own,
    and "did it grow" would become indistinguishable from "we measured
    differently".
    """
    lines = files = tests = 0
    for base, dirs, names in os.walk(PKG):
        dirs[:] = [d for d in dirs if d != "__pycache__"]
        in_tests = os.sep + "tests" + os.sep in base + os.sep
        for name in names:
            if not name.endswith(".py"):
                continue
            if in_tests:
                tests += 1
                continue
            files += 1
            with open(os.path.join(base, name), encoding="utf-8",
                      errors="replace") as handle:
                lines += sum(1 for _ in handle)
    # 🔴 THE GRAIN IS DELIBERATELY COARSE. The exact line changes with EVERY
    # edit — and a ratchet that turns red on any edit teaches people to
    # regenerate the block WITHOUT READING it, and thereby kills itself.
    # The signal here is the ORDER OF MAGNITUDE and the NUMBER OF FILES;
    # both survive an edit and turn red on the appearance of a module.
    return ["| размер `kir/` | **~%d тыс. строк** в %d нетестовых `.py`, "
            "плюс %d тестовых (зерно грубое намеренно: точная строка красила "
            "бы храповик на каждую правку) |"
            % (round(lines / 1000), files, tests)]


