"""Content coverage: a denominator that does not lie in either direction.

Document coverage (§18.1) counts ops against ALL elements of the file: on
the RD tower, 29,848 of 310,558 = 9.61%. The number is honest, but it
answers a question nobody asked. Those 310 thousand contain 61,520 zone
boundaries, 38,093 sketch lines, and 19,547 auto-dimensions — traces of
construction that Revit generates ITSELF and that nobody ever "creates".
Counting them in the denominator is the same as measuring a compiler by
the number of temporary variables its own output generates.

You can err here in either direction, and both are expensive:

* leave the whole document as the denominator — and we understate
  ourselves fourfold, and worse, we get an incentive to "raise coverage"
  by starting to read garbage: read 61,520 zone boundaries, passed them
  off as ops — the number grew, the compiler did not move;
* throw everything inconvenient out of the denominator — and get whatever
  percentage you want. This is exactly how a "98% coverage" is born, one
  that later has to be publicly retracted.

So the classification here is a CLOSED TABLE IN CODE, one line per
category, and everything not in it falls LOUDLY into ``UNKNOWN`` (a
separate list with numbers in the report), instead of dissolving into a
convenient class. Disagree with a specific line — fix it and recompute;
you can argue with the classification, but you cannot fail to notice it.

    python tools/content_coverage.py backend/data/decompile/k2_ar_rd_v6
    python tools/content_coverage.py <dir> --json out.json

Three numbers come out, and each answers its OWN question:

* ``model_pct``    — of what IS the building, how much we express;
* ``content_pct``  — of the building and its annotation (both authorial);
* ``document_pct`` — of the whole file (the existing §18.1 metric, for
  cross-checking).

And separately — a breakdown of the gap into two FUNDAMENTALLY different
causes: what we do NOT READ (categories outside the table) and what we
read but CANNOT express. The first is fixed by a line in the category
table, the second by a lifter and an op. Mixing them into one percentage
means not knowing what to do tomorrow.
"""
