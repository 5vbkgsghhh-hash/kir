#: 🔴 THE SNAPSHOT IS READ THROUGH `snapshot_io`, NOT A BARE `open`
#: (2026-08-19). The cleaner compresses SIX names
#: (`snapshot_janitor.SNAPSHOT_FILES`): `L0.jsonl` and five side indexes.
#: `status.json` and `tree.json` are NOT among them, so they are read as
#: before — a fix by the cleaner's list, not by habit.
#:
#: THE COST HERE IS WORSE THAN A REFUSAL, AND THAT IS WHY THIS IS NOT
#: COSMETIC. A compressed `L0.jsonl` would crash the instrument with a
#: `FileNotFoundError` — loudly. But a compressed SIDE INDEX would read as
#: ABSENT, that is, quietly: `side_indexes` is a condition for the
#: comparability of runs, and `comparable()` would declare two identical
#: runs incomparable, and an incomplete one complete. Exactly the disease
#: these conditions were set up against: 27 points of facade were a
#: difference in RUN COMPLETENESS, read as a compiler win.
#:
#: `touch=False`: by default `open_snapshot` writes `.last_access` into
#: the decompile directory, meaning the measurement would date the thing
#: being measured. Two of our censuses are already poisoned by this — the
#: scene cache and the corpus dating.
def _snap_open(path: pathlib.Path):
    from kir.decompile.snapshot_io import open_snapshot
    return open_snapshot(path, "rt", encoding="utf-8", touch=False)


def _snap_exists(path: pathlib.Path) -> bool:
    from kir.decompile.snapshot_io import snapshot_file_exists
    return snapshot_file_exists(path)


def _header(directory: pathlib.Path) -> dict[str, Any]:
    with _snap_open(directory / "L0.jsonl") as handle:
        return json.loads(handle.readline())


def _census(header: dict[str, Any], directory: pathlib.Path) -> list[dict[str, Any]]:
    census = header.get("document", {}).get("census")
    if not census:
        raise SystemExit(
            f"{directory.name}: переписи нет — слепок снят до §18.1, "
            "содержательное покрытие для него не определено")
    return census


def _extracted_by_collector(directory: pathlib.Path) -> dict[str, int]:
    """How many elements are actually read, by collector."""
    counts: collections.Counter[str] = collections.Counter()
    with _snap_open(directory / "L0.jsonl") as handle:
        handle.readline()
        for line in handle:
            # A cheap check before parsing: there are tens of thousands of
            # lines here.
            if '"record": "element"' not in line and '"record":"element"' not in line:
                continue
            record = json.loads(line)
            if record.get("record") != "element":
                continue
            counts[record.get("collector") or "no_category"] += 1
    return dict(counts)


