"""КАДР ОКНА РАЗДЕЛЯЕТ ОСНОВНОЕ ЗДАНИЕ И НОВОЕ — И ЭТО ВИДНО В SVG.

🔴 ЧЕМ КУПЛЕНО (13.09.2026, слово владельца дословно): «должно работать так,
что построилось какое-то здание во вьюере и он показывает нам типа превью. у
нас должно быть так, что всё остальное здание становится полупрозрачным, и
когда мы тыкаем во вьюере одобрить, то оно грамотно мержится в основное
здание».

ЧТО ЗДЕСЬ СТЕРЕЖЁТСЯ И ПОЧЕМУ ИМЕННО ЭТО. Различие «тусклое / подсвеченное»
существовало ТОЛЬКО как прозрачность внутри картинки. Картинку нельзя
посчитать: окно не могло ни назвать новые элементы словами, ни сказать,
сколько контекста стоит за тусклыми линиями, — а молчание о контексте читается
как «на этаже больше ничего нет». Поэтому оба множества едут полем, и тест
держит ТРИ утверждения разом:

  1. `fresh` и `ground` НЕ ПЕРЕСЕКАЮТСЯ и вместе покрывают нарисованное —
     иначе элемент оказался бы одновременно новым и старым либо не попал бы
     никуда;
  2. в САМОМ SVG они различимы: у каждого `ground` стоит `data-context="1"`,
     ни у одного `fresh` его нет. Поле, разошедшееся с картинкой, хуже
     отсутствующего поля: оно врёт уверенно;
  3. `fresh_ru` называет новое ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ и не называет
     объявлений: уровень — не элемент, и «построено: уровень 1» было бы той
     же ложью, что «2 операции» на куб.

КОНТРОЛЬ ВНУТРИ КАЖДОГО АКТА. Утверждения о разности множеств зеленеют на
пустоте, поэтому каждое сначала доказывает, что мерить ЕСТЬ ЧТО: лист нарисовал
контекст И нарисовал свежее. Без этого «не пересекаются» — правда о пустом
множестве.
"""
from __future__ import annotations

import re

from kir.live.plan_stream import _render_frame

LEVEL = {"op": "create_level", "id": "L1", "name": "Уровень 1",
         "elevation_mm": 0}


def _wall(oid: str, x: float) -> dict:
    return {"op": "create_wall", "id": oid,
            "level": {"by": "ref", "value": "L1"},
            "p0_mm": [x, 0.0, 0.0], "p1_mm": [x, 4000.0, 0.0],
            "height_mm": 3000.0}


def _frame() -> dict:
    """Этаж из четырёх стен, из которых ДВЕ — свежая программа."""
    старые = [_wall("old1", 0.0), _wall("old2", 2000.0)]
    свежие = [_wall("new1", 8000.0), _wall("new2", 10000.0)]
    return _render_frame([LEVEL] + старые + свежие, "Уровень 1", fresh=свежие)


def _context_ids(svg: str) -> set[str]:
    """Адреса, которые лист нарисовал ТУСКЛО, — прочитаны из самого файла."""
    out: set[str] = set()
    for group in re.findall(r"<g[^>]*>", svg):
        if 'data-context="1"' not in group:
            continue
        m = re.search(r'data-el="([^"]+)"', group)
        if m:
            out.add(m.group(1))
    return out


def _drawn_ids(svg: str) -> set[str]:
    return set(re.findall(r'data-el="([^"]+)"', svg))


def test_the_frame_splits_what_is_drawn_into_ground_and_fresh():
    frame = _frame()
    fresh = set(frame["fresh"])
    ground = set(frame["ground"])

    # КОНТРОЛЬ ПЕРВЫМ: мерить есть что.
    assert fresh, "контроль негоден: свежего в кадре нет вовсе"
    assert ground, "контроль негоден: контекста в кадре нет вовсе"

    assert not (fresh & ground), (
        "элемент назван и новым, и стоящим сразу: "
        f"{sorted(fresh & ground)}")
    нарисовано = _drawn_ids(frame["svg"])
    assert нарисовано, "контроль негоден: лист пуст"
    assert нарисовано <= (fresh | ground), (
        "лист рисует адреса, которых кадр не назвал ни новыми, ни стоящими: "
        f"{sorted(нарисовано - (fresh | ground))}")


def test_the_two_sets_are_distinguishable_in_the_svg_itself():
    """Поле, разошедшееся с картинкой, врёт уверенно — поэтому сверяем."""
    frame = _frame()
    fresh = set(frame["fresh"])
    ground = set(frame["ground"])
    тусклые = _context_ids(frame["svg"])
    нарисовано = _drawn_ids(frame["svg"])

    assert тусклые, "контроль негоден: в SVG нет ни одного тусклого элемента"
    assert not (тусклые & fresh), (
        "новое нарисовано тускло — человек не найдёт свой предмет: "
        f"{sorted(тусклые & fresh)}")
    assert тусклые == (ground & нарисовано), (
        "поле `ground` разошлось с тем, что лист погасил.\n"
        f"  в поле:    {sorted(ground & нарисовано)}\n"
        f"  на листе:  {sorted(тусклые)}")


def test_fresh_ru_names_the_new_elements_in_words_and_skips_declarations():
    свежие = [_wall("new1", 8000.0), LEVEL]
    frame = _render_frame([LEVEL, _wall("old1", 0.0)] + [_wall("new1", 8000.0)],
                          "Уровень 1", fresh=свежие)
    имена = {row["id"]: row["ru"] for row in frame["fresh_ru"]}

    assert имена, "контроль негоден: имён не пришло вовсе"
    assert "new1" in имена, f"свежая стена не названа: {имена}"
    assert "м" in имена["new1"], (
        "имя элемента не в единицах модели — человеку нечего прочесть: "
        f"{имена['new1']!r}")
    assert "L1" not in имена, (
        "объявление уровня названо построенным элементом: уровень — "
        "утверждение о здании, а не вещь в нём")


def test_the_frame_says_out_loud_what_the_dim_shapes_are():
    """Молчание об источнике фона читается как «на этаже больше ничего нет»."""
    frame = _frame()
    ru = frame["ground_source_ru"]
    assert "журнал" in ru.lower(), ru
    assert "до сессии" in ru, (
        "кадр не говорит, что элементы документа, существовавшие ДО сессии, "
        f"на листе не показаны: {ru!r}")


def test_no_op_of_the_registry_is_printed_to_a_human_as_latin():
    """🔴 НИ ОДНА ОПЕРАЦИЯ НЕ ПОКАЗЫВАЕТСЯ ЧЕЛОВЕКУ СЫРЫМ ИДЕНТИФИКАТОРОМ.

    ЧЕМ КУПЛЕНО (13.09.2026, живой ход владельца «построй коробку»): в списке
    того, что сейчас построится, он прочёл `create_extrusion_roof` среди своих
    стен. Словарь имён был НАРОЧНО неполным — «незнакомую операцию печатаем её
    собственным именем, чтобы не выдумывать обобщение». Для прибора это верно,
    для лица продукта — это отказ говорить.

    Пин держит обе половины решения:
      1. ни одно имя операции реестра не выходит к человеку латиницей ЦЕЛИКОМ;
      2. «не выдумывать» сохранено: у незнакомого опа род выводится из его
         ПРЕФИКСА (`create_` → «элемент»), а точное имя уходит в скобки — для
         агента, а не вместо слова.
    """
    from kir import spec
    from kir.preview import _OP_RU, _op_kind_ru

    ops = sorted(spec.OPS)
    assert ops, "контроль негоден: реестр пуст"

    сырые = [name for name in ops if _op_kind_ru(name) == name]
    assert not сырые, (
        f"операции печатаются человеку латиницей: {сырые}")

    creates = [name for name in ops if name.startswith("create_")]
    assert creates, "контроль негоден: строящих операций в реестре нет"
    безымянные = [name for name in creates if name not in _OP_RU]
    assert not безымянные, (
        "у строящей операции нет русского имени — человек прочтёт род вместо "
        f"предмета: {безымянные}")

    # КОНТРОЛЬ: прибор обязан ловить сырое имя, а не зеленеть на пустоте.
    выдуманный = "create_something_nobody_named"
    род = _op_kind_ru(выдуманный)
    assert род != выдуманный, "запасной путь вернул латиницу"
    assert род.startswith("элемент"), род
    assert выдуманный in род, (
        "точное имя операции потеряно — агенту нечем её назвать")
