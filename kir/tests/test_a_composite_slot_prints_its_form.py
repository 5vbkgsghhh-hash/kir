"""СОСТАВНОЙ СЛОТ НИКОГДА НЕ ПЕЧАТАЕТ ГОЛОЕ ИМЯ РОДА — ни в справке, ни в отказе.

🔴 ЦЕНА ЗАМЕРЕНА ЖИВОЙ МОДЕЛЬЮ 13.09.2026, а не выведена из вкуса
(`.work/prod-20260913/rq7-prep/deepseek_sdk/`, кассета `shed-D.json`).
DeepSeek со срезом раздела АР собрал программу сарая со ВСЕМИ нужными опами
и три попытки из трёх потратил на перебор имени ОДНОГО ключа слоя стены:

    попытка 1   thickness_mm   KIR-T001 «лишние ключи слоя»
    попытка 2   thickness      то же
    попытка 3   width          то же — попытки кончились

Принято `width_mm`. Отказ называл, какие ключи ЛИШНИЕ, и молчал о ПРИНЯТЫХ;
хвост отказа при этом говорил «приведи layers к виду выше», а вида выше в
сообщении не было. Так же умерла и рука со всеми 83 опами. Сарай не собрался
ни у одной руки со справкой.

🔴 ЭТО ПИН НА ЗАКОН, А НЕ НА ОДИН СЛУЧАЙ. До правки форму печатал РОВНО ОДИН
вид из двадцати девяти — `region`, которому её однажды написали руками
(заявка 003). Остальные двадцать восемь печатали имя рода. Перечисление
«починить wall_layers» оставило бы двадцать семь, и следующий вид родился бы
голым молча. Перепись ниже идёт по ВСЕМУ реестру: вид, у которого схема есть,
а формы нет, красит этот тест сам.
"""
from __future__ import annotations

import unittest

from kir import dsl, spec
from kir.course import LESSON_CAP, _contract_within_channel, _spec_parts


def _составные() -> dict[str, list[tuple[str, str]]]:
    """Виды, у которых СХЕМА ЕСТЬ и она НЕ скаляр, — по реестру, не списком."""
    найдено: dict[str, list[tuple[str, str]]] = {}
    for имя, ospec in sorted(spec.OPS.items()):
        схема = dsl._schema_of(ospec)
        for p in ospec.params:
            узел = схема.get(p.name)
            if not isinstance(узел, dict):
                continue
            составной = ("oneOf" in узел or "anyOf" in узел
                         or узел.get("type") in ("object", "array"))
            if составной:
                найдено.setdefault(p.kind, []).append((имя, p.name))
    return найдено


class СоставнойСлотПечатаетФорму(unittest.TestCase):

    def test_перепись_не_пуста(self) -> None:
        """КОНТРОЛЬ НА САМ ТЕСТ: перепись по нулю видов зелена по построению."""
        составные = _составные()
        self.assertGreaterEqual(
            len(составные), 20,
            f"составных видов в переписи {len(составные)} — тест проверяет пустоту")

    def test_ни_один_составной_слот_не_печатает_голое_имя_рода(self) -> None:
        голые = []
        for вид, места in sorted(_составные().items()):
            имя_опа, имя_слота = места[0]
            ospec = spec.OPS[имя_опа]
            p = next(x for x in ospec.params if x.name == имя_слота)
            текст = str(dsl._annotation(ospec, p))
            if текст == вид:
                голые.append(f"{вид} ({имя_опа}.{имя_слота})")
        self.assertEqual(голые, [], "составные слоты печатают ГОЛОЕ имя рода: "
                                    + ", ".join(голые))

    def test_пирог_стены_называет_принятые_ключи_с_единицами(self) -> None:
        """ТОТ САМЫЙ СЛОТ, НА КОТОРОМ УМЕРЛИ ТРИ ПОПЫТКИ.

        Проверяется не «текст изменился», а что в нём есть ровно то, чего не
        хватало модели: имя принятого ключа с единицей, словарь функции слоя
        и НЕОБЯЗАТЕЛЬНОСТЬ материала.
        """
        ospec = spec.OPS["create_wall_type"]
        p = next(x for x in ospec.params if x.name == "layers")
        текст = str(dsl._annotation(ospec, p))
        for нужное in ("width_mm", "function", "material?", "Structure"):
            self.assertIn(нужное, текст, f"в форме слоя нет «{нужное}»: {текст}")
        # И ни одной из трёх догадок модели — иначе форма подтверждала бы ошибку.
        self.assertNotIn("thickness", текст)

    def test_строгая_граница_названа_строгой(self) -> None:
        """ВКЛЮЧИТЕЛЬНАЯ ЗАПИСЬ СТРОГОЙ ГРАНИЦЫ — ЛОЖНОЕ РАЗРЕШЕНИЕ.

        Замер после починки (`cassettes-after-fix/shed-D.json`, попытка 1):
        форма уклона печаталась как `0..90`, в схеме стоит
        `exclusiveMinimum: 0`, и модель написала `slopes=[30, 0, 30, 0]` — по
        значению на ребро, как и просили. Отказ: ровный скат обозначается
        `null`, а не нулём. Форма называла законным ровно то значение, которым
        оп отказывает.
        """
        ospec = spec.OPS["create_roof"]
        p = next(x for x in ospec.params if x.name == "slopes")
        текст = str(dsl._annotation(ospec, p))
        self.assertIn(">0", текст, f"строгий низ не назван строгим: {текст}")
        self.assertIn("<90", текст, f"строгий верх не назван строгим: {текст}")
        self.assertIn("null", текст)

    def test_форма_доезжает_в_хвосте_отказа(self) -> None:
        """ОТКАЗ, А НЕ ТОЛЬКО СПРАВКА. «Приведи к виду выше» обязано иметь вид.

        Хвост собирает `authoring_validation._slot_tail`, и он печатает
        `dsl._annotation`. Значит одна правка закрывает оба места — это и
        проверяется, чтобы никто не завёл второй носитель.
        """
        from kir.authoring_validation import _slot_tail
        from kir.diag import Diagnostic
        d = Diagnostic(code="KIR-T001", op_index=0, op_id="t1",
                       field_name="layers[0]", got=["thickness_mm"],
                       message_ru="лишние ключи слоя: thickness_mm")
        хвост = _slot_tail("create_wall_type", d, with_roster=True)
        self.assertIn("width_mm", хвост)
        self.assertIn("СЛЕДУЮЩИЙ ХОД", хвост)

    def test_регион_остался_своим_носителем(self) -> None:
        """МЕХАНИЗМ ОДИН, У НЕГО ОДНА НАЗВАННАЯ ВЕТКА.

        `region` продолжает брать слова у `kir.contour` — там единственный
        носитель обёртки `{outer, holes?}`, и пин N держит именно его. Если
        кто-то заменит регион на вывод из схемы, обёртка исчезнет молча.
        """
        from kir.contour import REGION_FORM_RU
        ospec = spec.OPS["create_ceiling"]
        p = next(x for x in ospec.params if x.kind == "region")
        self.assertIn(REGION_FORM_RU.split(" —")[0][:12],
                      str(dsl._annotation(ospec, p)))

    def test_канал_контракта_держится_у_каждого_опа(self) -> None:
        """ФОРМЫ НЕ СЪЕДАЮТ ХВОСТ — ПРОВЕРЕНО ПО ВСЕМУ РЕЕСТРУ.

        Форма стоит в СЕРЕДИНЕ контракта, а канал 3300 знаков режет КОНЕЦ, где
        границы параметров и допуски свидетеля. Цена уже была заплачена один
        раз (13.09, `create_solid_blend`: 3143 без прозы против 3300), и
        повторять её нельзя. Здесь тот же вопрос задан ВСЕМ 83 опам сразу.
        """
        потеряли = []
        for имя, ospec in sorted(spec.OPS.items()):
            голова, тело = _spec_parts(ospec)
            текст = голова + тело
            выдано = _contract_within_channel(ospec, текст, lambda _k: "")
            if текст[-120:] not in выдано:
                потеряли.append(f"{имя} ({len(текст)} знаков)")
        self.assertEqual(потеряли, [], "хвост контракта НЕ ДОЕХАЛ: "
                                       + ", ".join(потеряли))

    def test_одинаковая_форма_внутри_опа_печатается_один_раз(self) -> None:
        """ДВА СЛОТА ОДНОГО РОДА — ОДНА ФОРМА И ССЫЛКА ВВЕРХ.

        `create_wall` берёт две точки `pt_xy`; полная форма точки весит около
        сотни знаков, и печатать её дважды значит платить каналом за то же
        самое. Свёртка обязана быть ПОБУКВЕННОЙ: если схемы двух слотов
        разошлись, «как у X выше» стало бы ложью, и тогда печатаются обе.
        """
        текст = dsl._docstring(spec.OPS["create_wall"])
        self.assertIn("как у `p0_mm` выше", текст)
        self.assertEqual(текст.count("at_grid"), 1,
                         "форма точки напечатана дважды — канал платит зря")


if __name__ == "__main__":
    unittest.main()
