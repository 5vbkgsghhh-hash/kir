def tetra() -> tuple[list, list]:
    return ([[0, 0, 0], [3000, 0, 0], [1500, 2600, 0], [1500, 900, 2400]],
            [[0, 1, 2], [0, 1, 3], [1, 2, 3], [0, 2, 3]])


def twisted_tower(sides=16, storeys=12, r0=6000.0, r1=3500.0,
                  h=36000.0, twist=140.0) -> tuple[list, list]:
    """A twisted tower generated by mathematics (see artifacts/twisted_tower.py)."""
    verts, tris = [], []
    for k in range(storeys + 1):
        f = k / storeys
        r = r0 + (r1 - r0) * f
        a0 = math.radians(twist * f)
        for j in range(sides):
            a = a0 + 2 * math.pi * j / sides
            verts.append([r * math.cos(a), r * math.sin(a), h * f])
    for k in range(storeys):
        for j in range(sides):
            a, b = k * sides + j, k * sides + (j + 1) % sides
            c, d = (k + 1) * sides + j, (k + 1) * sides + (j + 1) % sides
            tris += [[a, b, d], [a, d, c]]
    bot = len(verts); verts.append([0.0, 0.0, 0.0])
    top = len(verts); verts.append([0.0, 0.0, h])
    for j in range(sides):
        tris.append([bot, (j + 1) % sides, j])
        tris.append([top, storeys * sides + j,
                     storeys * sides + (j + 1) % sides])
    return verts, tris


def _prog(verts, tris, category="generic_model", name="меш", oid="D1"):
    return {"ir_version": "1.0", "intent": "t",
            "ops": [{"op": "create_directshape", "id": oid,
                     "mesh": {"vertices_mm": verts, "triangles": tris},
                     "category": category, "name": name}]}


def _codes(mesh, **contract) -> list:
    """The law's verdict. `contract` is passed into `validate_mesh` as-is: the caller's
    contract is part of the subject, not a detail of the helper."""
    diags: list = []
    out = validate_mesh(mesh, "D1", "mesh", diags, **contract)
    return [out, [d.code for d in diags]]


def _diags(mesh, **contract) -> list:
    diags: list = []
    validate_mesh(mesh, "D1", "mesh", diags, **contract)
    return diags


def склеенные_тела() -> dict:
    """A SEAM BUILT BY PROD CODE, NOT BY HAND.

    Two `extrude` calls stacked on each other are exactly what our own decompile step
    does — «combined multiple geometry parts through their exact Gm fallbacks»:
    the same plane arrives twice, each time facing OUT of its OWN solid, i.e. with
    opposing winding. A hand-written fixture would be guarding itself here: it
    reproduces the shape the test's author invented, not the one the
    product produces.
    """
    from kir.mesh import extrude
    низ = extrude([[0, 0], [1000, 0], [1000, 1000], [0, 1000]], 1000,
                  base_z_mm=0)
    верх = extrude([[0, 0], [1000, 0], [1000, 1000], [0, 1000]], 1000,
                   base_z_mm=1000)
    сдвиг = len(низ["vertices_mm"])
    return {"vertices_mm": низ["vertices_mm"] + верх["vertices_mm"],
            "triangles": низ["triangles"]
                         + [[i + сдвиг for i in t] for t in верх["triangles"]]}


