        # SAME list `t`. The old `len(t) == len(t)` proved the silence of the
        # face-count witness by the absence of a competitor — that is, it
        # proved nothing. What must be asserted here is the test's premise:
        # the vertex ACTUALLY moved, otherwise the silence is trivial.
