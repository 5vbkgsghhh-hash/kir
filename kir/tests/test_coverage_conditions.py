"""THE COVERAGE PERCENTAGE TRAVELS WITH ITS OWN CONDITIONS, OR IT IS
UNINTERPRETABLE.

THE OCCASION IS THE MEASUREMENT OF 12.08.2026, AND IT HITS THE PROJECT'S
MAIN SHOWCASE. Two revisions of ONE façade, with the compiler not changed
by a single line between them:

    sob62_fas_r23_v12   63.80%      read 5 095, scanned 14 categories
    sob62_fas_r23_v19   91.23%      read 5 218, scanned 15

27 points. What makes them is NOT expressiveness and not the volume of
reading in the naive sense (+2.4% of elements). One extra category read —
122 curtain-wall grids — let the lifter RECOGNIZE 1 264 panels and mullions
as children generated by the curtain wall; `generator_child` is excluded
from the honest figure, so the DENOMINATOR dropped (4 205 -> 2 942), while
the numerator barely moved (2 683 -> 2 806). **123 read elements
reclassified 1 264 others.**

NOT ONE EXISTING FLAG CAUGHT THIS: both runs have `census_balanced: true`,
`errors: []`, `done: 1`, `is_partial_read: false`,
`generator_children_assumption_broken: false`. The only thing that told
them apart was `categories_scanned`, which was never compared against
anything.

THE CONSEQUENCE THAT MATTERS MORE THAN THE CASE ITSELF: the published
96.13% was taken WITHOUT these conditions alongside it. The number is not
"wrong" — it is UNINTERPRETABLE, and the difference between those two
words is exactly the project's honesty.

THE SIGNAL WAS NOT INVENTED FROM SCRATCH, BUT ASKED OF THE AUTHORITIES: the
extraction table knows what we're able to read; the §18.1 census knows
what's in the document; `L0` knows what was read. `category_outside_table`
is deliberately NOT included in the conditions: it's a known gap, and the
metric exists to describe exactly it.
"""
