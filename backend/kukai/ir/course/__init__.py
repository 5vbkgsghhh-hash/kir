# зовёт `revit_ir` пофазно. Он писался до того, как появился `program_py`, и
# сегодня вторая дверь повторила бы историю `sdk.py`: 493 строки, пять недель,
# недостижимо, потому что двери к нему не было. У фаз дверь уже есть — тот же
# авторский скрипт, в котором модель уже пишет здание. Поэтому фаза — не
# инструмент, а КОНТЕКСТ, родной брат `unit()`: тот собирает написанное внутрь
# в одну ГРУППУ, этот — в одну ПРОГРАММУ (одну транзакцию, один чекпойнт).
#
# ЧТО ЭТОТ ФАЙЛ ДЕЛАЕТ И ЧЕГО НЕ ДЕЛАЕТ. Делает: размечает границы, проверяет
# их ДО всякого эффекта и превращает ссылку, пересёкшую границу, в метку,
# которую можно подставить. НЕ делает: не исполняет пофазно и не режет
# программу — это ШАГ 2, и он сделан 09.08н в другом месте, потому что
# исполнение не принадлежит языку. Резать план на пачку умеет
# `compiler.split_phases`, подставлять метку — `compiler.substitute_phase_
# results`, вести звенья по одному — `serving._run_plan`. Сюда исполнение не
# переезжает никогда: песочница исполняет скрипт ДВАЖДЫ (`replay_check`), и
# запись, живущая в ней, случилась бы дважды.
#
# ПОСЛЕДНИЙ РУБЕЖ ОСТАЁТСЯ FAIL-CLOSED. Программа с `phases`, отданная
# `plan_program` целиком, по-прежнему отказывает (KIR-P003) — и это не остаток
# вчерашнего дня, а закон: `plan_program` исполняет ОДНУ транзакцию, а фаза
# обещает чекпойнт между ними. Тихо склеить фазы значило бы объявить чекпойнт,
# которого нет. Изменился только текст отказа: он называет план и говорит,
# чем его резать, вместо «неизвестное поле конверта».

#: КАК ВЫГЛЯДИТ ССЫЛКА, ПЕРЕСЁКШАЯ ГРАНИЦУ ФАЗЫ. На этом имени стоит шаг 2:
#: он подставляет вместо метки `{"by": "element_id", "value": <id из СВИДЕТЕЛЯ
#: произведшей фазы>}` — и это единственное, что ему нужно знать отсюда.
#:
#:     {"by": "phase_result", "value": "<id опа-производителя>", "phase": <N>}
#:
#: ПОЧЕМУ НЕ `by=ref`. `{"by": "ref"}` адресует оп ЭТОЙ ЖЕ программы и
#: разрешается компилятором до эмиссии. К моменту исполнения следующей фазы
#: произведший элемент уже закоммичен ОТДЕЛЬНОЙ транзакцией, и ссылки на него
#: внутри программы больше не существует. Тот же факт система уже говорит в
#: другом месте: `design_check._merge_bundle` отказывает кросс-программному
#: `by=ref` словами «соседняя программа — отдельная транзакция, и к её
#: исполнению id уже не существует». Метка — тот же факт ДО отказа: форма,
#: которую можно подставить, вместо формы, которую остаётся запретить.
#:
#: `value` — id опа-ПРОИЗВОДИТЕЛЯ, а не имя элемента: свидетель адресует опы
#: по id (`op_outcomes`), значит подстановка шага 2 — это поиск по ключу, а не
#: угадывание по имени. `phase` — номер произведшей фазы; имя фазы лежит в
#: таблице конверта, и повторять его в каждой метке значило бы завести второй
#: источник правды о названии.
#:
#: ИМЯ ПЕРЕЕХАЛО В РЕЕСТР (`spec.CROSS_PHASE_BY`), и здесь остался псевдоним.
#: Причина — шаг 2 сделан: подставляет метку `compiler.substitute_phase_results`,
#: а компилятор не имеет права импортировать курс (курс импортирует его ради
#: бюджета — было бы цикл). Литерал в двух местах разъехался бы молча, как уже
#: разъехался `SOLO_OPS` в двух местах из трёх.
CROSS_PHASE_BY = _spec.CROSS_PHASE_BY


class Phase:
    """Что осталось от `with phase(...)`: имя, номер и адреса опов фазы."""

    __slots__ = ("name", "index", "op_ids", "line")

    def __init__(self, name: str, index: int, line: int | None) -> None:
        self.name = name
        self.index = index
        #: строка скрипта, на которой фаза открыта. В программу НЕ едет:
        #: исполнению она не нужна, а отказу нужна — им и пользуется.
        self.line = line
        self.op_ids: list[str] = []

    def __repr__(self) -> str:
        return (f"Phase({self.index}, {self.name!r}, "
                f"опов {len(self.op_ids)})")

    def as_dict(self) -> dict:
        """Строка таблицы `phases` конверта — ровно то, что уедет в JSON."""
        return {"index": self.index, "name": self.name,
                "op_ids": list(self.op_ids)}

    def at(self) -> str:
        """Адрес фазы для ОТКАЗА: имя, номер и строка, на которой она открыта."""
        return f"«{self.name}» (№{self.index}" + (
            f", строка {self.line})" if self.line else ")")


class _PhaseLedger:
    """Фазы ОДНОЙ программы: их порядок, чей оп чей, докуда всё разнесено."""

    __slots__ = ("phases", "owner", "watermark", "open_name")

    def __init__(self) -> None:
        self.phases: list[Phase] = []
        #: id опа -> номер его фазы. Только ЗАКРЫТЫЕ фазы: пока фаза открыта,
        #: её опы отсутствуют здесь намеренно — на этом стоит правило «ссылка
        #: внутри фазы остаётся `by=ref`» (см. `_mark_cross_phase`).
        self.owner: dict[str, int] = {}
        #: сколько опов программы уже разнесено по фазам. Расхождение с
        #: `len(program.ops)` и есть «оп написан вне фазы».
        self.watermark = 0
        self.open_name: str | None = None


#: Книга фаз ЖИВЁТ ПРИ ПРОГРАММЕ, а не в модуле. Модульная книга пережила бы
#: `dsl.reset()` и приписала бы фазы прошлого скрипта следующему — в песочнице
#: этого не видно (интерпретатор свежий на скрипт), а в одном процессе (тесты,
#: стенд) видно сразу. Слабые ключи: книга умирает вместе со своей программой,
#: и обнулять её вручную некому и незачем.
_LEDGERS: "weakref.WeakKeyDictionary[Any, _PhaseLedger]" = \
    weakref.WeakKeyDictionary()


def _author_line() -> int | None:
    """Номер строки АВТОРА, если мы внутри исполнения скрипта.

    Кадры нашего конвейера пропускаются: модели чинить надо СВОЙ код, и это
    тот же отбор, что делает песочница (`script_frames`)."""
    frame: Any = sys._getframe(1)
    while frame is not None:
        if frame.f_code.co_filename == SCRIPT_FILENAME:
            return frame.f_lineno
        frame = frame.f_back
    return None


def _refuse_phase(code: str, message: str, **fields: Any) -> Exception:
    """Типизированный отказ фазы — В СЛОВАРЕ КОМПИЛЯТОРА, а не текстом.

    Поднимается ИЗ ТЕЛА СКРИПТА намеренно: только там песочница видит кадр
    `<kir-script>` и кладёт в отказ НОМЕР СТРОКИ и саму строку (KIR-B006
    оборачивает текст `DslRefusal`). Отказ, поднятый ПОСЛЕ скрипта — на сливе
    программы, — строки уже не получит; поэтому всё, что можно проверить внутри
    блока `with`, проверяется внутри него, и вне блока остаётся ровно одна
    проверка (хвост, `_refuse_tail`), которой блока не досталось.
    """
    from kukai.ir import dsl
    return dsl.DslRefusal([Diagnostic(code=code, message_ru=message, **fields)])


def _ref_targets(value: Any) -> list[str]:
    """Все адресаты `{"by": "ref"}` внутри значения, как угодно вложенные.

    Обход РОДОВОЙ, а не по именам полей: хозяин зовётся `host` у проёма,
    `target` у марки и `members` у группы, и список имён разошёлся бы со схемой
    на первой же новой операции.

    ПОЧЕМУ СВОЙ, А НЕ `design_check._ref_targets`. Тот живёт в модуле вердикта,
    который тянет shapely/numpy/networkx: замер 03.08 — +536 мс и +43 МБ к
    запуску, и песочница исполняет скрипт ДВАЖДЫ (`replay_check`). Импорт ради
    двенадцати строк обхода стоил бы этого КАЖДОМУ скрипту с фазами, включая
    те, что вердикт не зовут вовсе (ровно поэтому прогрев в `language.py`
    условный). Обход — структурный, не семантический: расходиться ему не с чем.
    """
    if isinstance(value, Mapping):
        if value.get("by") == "ref":
            return [str(value.get("value"))]
        out: list[str] = []
        for item in value.values():
            out.extend(_ref_targets(item))
        return out
    if isinstance(value, (list, tuple)):
        out = []
        for item in value:
            out.extend(_ref_targets(item))
        return out
    return []


def _mark_cross_phase(value: Any, owner: Mapping[str, int]) -> Any:
    """`{"by": "ref"}` на оп ЗАКРЫТОЙ фазы -> метка `CROSS_PHASE_BY`.

    `owner` несёт только закрытые фазы, поэтому ссылка на соседа ПО ТОЙ ЖЕ фазе
    в него не попадает и остаётся `by=ref` нетронутой — ровно как сегодня.
    Ссылка на неизвестный id тоже остаётся: висячая ссылка — это разбор
    программы (KIR-L003 на плане), а не факт о фазах, и подменять один диагноз
    другим значило бы увести ремонт.
    """
    if isinstance(value, Mapping):
        if value.get("by") == "ref":
            producer = owner.get(str(value.get("value")))
            if producer is None:
                return dict(value)
            return {"by": CROSS_PHASE_BY, "value": str(value.get("value")),
                    "phase": producer}
        return {key: _mark_cross_phase(item, owner)
                for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_mark_cross_phase(item, owner) for item in value]
    return value


def _census(ops: Iterable[Mapping]) -> str:
    """Что за опы, по родам. Строка для ОТКАЗА: резать модель будет по ней."""
    tally: dict[str, int] = {}
    for op in ops:
        name = str(op.get("op", "?"))
        tally[name] = tally.get(name, 0) + 1
    return ", ".join(f"{name} {count}" for name, count
                     in sorted(tally.items(), key=lambda kv: (-kv[1], kv[0])))


class _PhaseContext:
    """Контекст, объявляющий написанное внутрь ОДНИМ звеном плана.

    ЧТО ЭТО НЕ ДЕЛАЕТ. Не исполняет, не режет программу на части и не трогает
    ни одного опа, кроме ссылок, пересёкших границу. Программа наружу выходит
    ТА ЖЕ, плюс таблица `phases` в конверте.

    ЧТО ЭТО ДЕЛАЕТ. Помнит, на какой позиции программы фаза открылась,
    забирает написанный за это время кусок и проверяет о нём четыре вещи, ВСЕ
    ДО ВСЯКОГО ЭФФЕКТА: фаза не пуста; фаза влезает в авторский бюджет; соло-оп
    в фазе один; ссылки, ведущие в другую фазу, названы меткой, а ведущие
    ВПЕРЁД — отказ.
    """

    __slots__ = ("_name", "_program", "_ledger", "_start", "_phase")

    def __init__(self, name: Any) -> None:
        if not isinstance(name, str) or not (1 <= len(name.strip()) <= 64):
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="name",
                expected="строка 1..64 символа", got=repr(name),
                message=("у фазы обязано быть ИМЯ: отказ и отчёт называют "
                         "фазу, на которой план встал, и безымянное звено "
                         "нечем назвать. phase(\"каркас первого этажа\")"))
        self._name = name.strip()
        self._program: Any = None
        self._ledger: _PhaseLedger | None = None
        self._start = 0
        self._phase: Phase | None = None

    def __enter__(self) -> Phase:
        from kukai.ir import dsl
        if _UNIT_DEPTH:
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="phase",
                message=("фаза внутри unit(): члены группы — это ОДИН оп "
                         "(`create_group`) внешней программы, и своей "
                         "транзакции у них нет. Значит и своей фазы быть не "
                         "может. СЛЕДУЮЩИЙ ХОД: открой фазу СНАРУЖИ блока "
                         "unit(), а единицу пиши внутри фазы"))
        program = dsl.current()
        ledger = _LEDGERS.get(program)
        if ledger is None:
            ledger = _PhaseLedger()
            _LEDGERS[program] = ledger
        if ledger.open_name is not None:
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="phase", got=self._name,
                message=(f"фаза «{self._name}» открыта внутри фазы "
                         f"«{ledger.open_name}». Фазы — ПОСЛЕДОВАТЕЛЬНОСТЬ, а "
                         f"не дерево: каждая исполняется своей транзакцией, и "
                         f"вложенной транзакции у плана нет. СЛЕДУЮЩИЙ ХОД: "
                         f"закрой одну фазу и открой следующую рядом"))
        twin = next((p for p in ledger.phases if p.name == self._name), None)
        if twin is not None:
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="name", got=self._name,
                candidates=[p.name for p in ledger.phases],
                message=(f"фаза {twin.at()} уже была: имя фазы — её АДРЕС в "
                         f"плане и в отчёте, и второе такое же имя делает "
                         f"адрес неоднозначным. Дописать опы в уже закрытую "
                         f"фазу тоже нельзя: порядок исполнения перестал бы "
                         f"совпадать с порядком в скрипте, и это была бы "
                         f"граница, которую ты не рисовал. СЛЕДУЮЩИЙ ХОД: "
                         f"назови новую фазу иначе"))
        stray = len(program.ops) - ledger.watermark
        if stray:
            loose = list(program.ops[ledger.watermark:])
            where = (f"после фазы {ledger.phases[-1].at()}"
                     if ledger.phases else "до первой фазы")
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="ops", got=stray,
                message=(
                    f"{stray} операций написано ВНЕ фазы ({where}): "
                    f"{_census(loose)}. Скрипт, нарисовавший хоть одну "
                    f"границу, обязан разнести по фазам ВСЁ: неразмеченный оп "
                    f"пришлось бы либо приписать к соседней фазе, либо завести "
                    f"ему фазу — и то и другое было бы границей, которую автор "
                    f"не рисовал, то есть транзакцией, о которой он не знает. "
                    f"СЛЕДУЮЩИЙ ХОД: оберни эти операции в свою фазу — либо "
                    f"убери phase() из скрипта вовсе (программа без фаз "
                    f"остаётся ровно тем, чем была)"))
        self._program = program
        self._ledger = ledger
        self._start = len(program.ops)
        self._phase = Phase(self._name, len(ledger.phases), _author_line())
        ledger.open_name = self._name
        return self._phase

    def __exit__(self, exc_type, exc, tb) -> bool:
        from kukai.ir import dsl
        ledger, self._ledger = self._ledger, None
        if ledger is None or self._phase is None:
            # Закрытие без открытия: контекст позвали руками. Голого
            # `AssertionError` тут быть не должно — наружу выходят только
            # типизированные отказы, и этот называет, что именно не сошлось.
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="phase", got=self._name,
                message=(f"фаза «{self._name}» закрывается, не будучи "
                         f"открытой. Фаза — это блок `with phase(...)`; "
                         f"звать её __enter__/__exit__ руками нельзя"))
        ledger.open_name = None               # закрываем ВСЕГДА, даже на отказе
        if exc_type is not None:
            return False                      # исключение автора идёт наружу
        program = self._program
        if dsl.current() is not program:
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="phase", got=self._name,
                message=(f"фаза «{self._name}» открыта на одной программе, а "
                         f"закрывается на другой: внутри блока осталась "
                         f"незакрытая program(). Фаза — кусок ОДНОЙ программы, "
                         f"и кусок двух программ сразу не существует"))
        ops = list(program.ops[self._start:])
        phase = self._phase
        if not ops:
            raise _refuse_phase(
                PLAN_PHASE_SHAPE, field_name="ops", got=0,
                message=(f"фаза {phase.at()} не собрала ни одной операции. "
                         f"Пустая фаза — это пустая транзакция и лишний "
                         f"чекпойнт: строить в ней нечего. Пиши опы ВНУТРИ "
                         f"блока with"))
        if len(ops) > MAX_OPS_PER_PROGRAM:
            raise _refuse_phase(
                PLAN_LIMIT, field_name="ops",
                expected=f"<={MAX_OPS_PER_PROGRAM}", got=len(ops),
                message=(
                    f"фаза {phase.at()} — {len(ops)} операций при авторском "
                    f"бюджете {MAX_OPS_PER_PROGRAM}. Под этим замыслом бюджет "
                    f"меряет ФАЗУ, а не скрипт: фаза и есть та программа, "
                    f"которую исполнит одна транзакция, и её размер — это "
                    f"размер того, что откатится целиком при первой же "
                    f"неудаче. СОБРАНО В ФАЗЕ: {_census(ops)}. СЛЕДУЮЩИЙ ХОД: "
                    f"режь эту фазу на две по этим числам — фаз в скрипте "
                    f"столько, сколько нужно"))
        # СОЛО-ОП — ПРАВИЛО ФАЗЫ, А НЕ СКРИПТА, И ИМЕННО ЭТО ДЕЛАЕТ
        # МНОГОЭТАЖНЫЙ ДОМ ВЫРАЗИМЫМ ОДНИМ СКРИПТОМ. До фаз соло-оп означал
        # ОТДЕЛЬНУЮ ПРОГРАММУ, то есть отдельный ход модели: здание с
        # лестницей нельзя было написать одним скриптом вообще (замер 04.08 —
        # лестница обязана быть единственным опом, значит многоэтажка одной
        # программой непригодна ПО ПОСТРОЕНИЮ). Теперь она — своя фаза внутри
        # того же скрипта, и план строит здание целиком.
        #
        # САМ ФАКТ («какие опы соло и почему») ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ: он живёт в
        # `spec.SOLO_OPS`, и spec.py:56-65 прямо предупреждает, что до 04.08
        # он был написан в трёх местах и разошёлся в двух из них.
        solo = [op for op in ops if op.get("op") in _spec.SOLO_OPS]
        if solo and len(ops) > 1:
            raise _refuse_phase(
                PLAN_SOLO_OP, field_name="ops", op_id=str(solo[0].get("id")),
                got=len(ops),
                message=(
                    f"фаза {phase.at()}: `{solo[0].get('op')}` обязан быть "
                    f"ЕДИНСТВЕННЫМ опом своей программы, а фаза — это и есть "
                    f"одна программа, и в ней {len(ops)} операций "
                    f"({_census(ops)}). СЛЕДУЮЩИЙ ХОД: заведи ему СВОЮ фазу — "
                    f"соседние опы уедут в фазу до или после, и здание "
                    f"останется одним скриптом"))
        # Ссылки размечаются ДО того, как опы этой фазы попадут в `owner`:
        # сосед по своей же фазе обязан остаться `by=ref`.
        for op in program.ops[self._start:]:
            for key in [k for k in op if k not in ("op", "id")]:
                op[key] = _mark_cross_phase(op[key], ledger.owner)
        phase.op_ids = [str(op.get("id")) for op in ops]
        for oid in phase.op_ids:
            ledger.owner[oid] = phase.index
        ledger.phases.append(phase)
        ledger.watermark = len(program.ops)
        _refuse_use_before_produce(program, ledger, phase, self._start)
        return False


def _refuse_use_before_produce(program: Any, ledger: _PhaseLedger,
                               phase: Phase, start: int) -> None:
    """ЗАКОН ПОРЯДКА, ПОДНЯТЫЙ НА ФАЗЫ (тот же KIR-L003, что внутри программы).

    Внутри программы ссылка обязана вести на БОЛЕЕ РАННИЙ оп. Между фазами то
    же самое и по той же причине, только жёстче: фазу N исполняет отдельная
    транзакция, и подставить в неё id из свидетеля фазы N+1 нельзя — той ещё не
    было. Проверка стоит на ЗАКРЫТИИ фазы-производителя, потому что раньше
    этого места факт неизвестен: пока оп не написан, ссылка на него неотличима
    от висячей.

    Ручкой (`Handle`) так промахнуться нельзя — ручка существует только после
    своего опа. Промахиваются ЯВНОЙ формой: `by_ref("level1")` или готовым
    словарём `{"by": "ref", "value": "level1"}`, где id угадан по
    детерминированной схеме имён (`Program._next_id`). Форма законная, и
    сегодня она — единственный способ сослаться назад по тексту скрипта.
    """
    produced = set(phase.op_ids)
    for op in program.ops[:start]:
        wrong = [target for target in _ref_targets(op) if target in produced]
        if not wrong:
            continue
        user = ledger.phases[ledger.owner[str(op.get("id"))]]
        raise _refuse_phase(
            "KIR-L003", field_name="by=ref", op_id=str(op.get("id")),
            got=wrong[0], candidates=sorted(produced),
            message=(
                f"оп `{op.get('id')}` из фазы {user.at()} ссылается на "
                f"`{wrong[0]}`, а тот производится ПОЗЖЕ — в фазе "
                f"{phase.at()}. Фазы исполняются по порядку, каждая своей "
                f"транзакцией: к моменту фазы {user.index} элемента "
                f"`{wrong[0]}` в модели ещё нет, и подставить его настоящий id "
                f"неоткуда — свидетеля фазы {phase.index} ещё не существует. "
                f"СЛЕДУЮЩИЙ ХОД: поменяй фазы местами — производитель обязан "
                f"стоять в плане РАНЬШЕ потребителя"))


def _refuse_tail(program: Any, ledger: _PhaseLedger) -> None:
    """Опы, написанные ПОСЛЕ последней фазы. Единственная проверка вне блока.

    Ей одной не досталось `with`: хвост становится хвостом только тогда, когда
    скрипт кончился, — и номера строки у этого отказа поэтому нет. Взамен он
    называет сами опы и последнюю фазу: этого хватает, чтобы найти место
    глазами, а угадывать строку по числу опов значило бы указать НЕ ТУ.
    """
    stray = len(program.ops) - ledger.watermark
    if not stray:
        return
    loose = list(program.ops[ledger.watermark:])
    raise _refuse_phase(
        PLAN_PHASE_SHAPE, field_name="ops", got=stray,
        candidates=[str(op.get("id")) for op in loose][:12],
        message=(
            f"{stray} операций написано ПОСЛЕ последней фазы "
            f"{ledger.phases[-1].at()}: {_census(loose)} (id: "
            f"{', '.join(str(op.get('id')) for op in loose[:6])}). Скрипт, "
            f"нарисовавший хоть одну границу, обязан разнести по фазам ВСЁ — "
            f"иначе этим опам пришлось бы выдумать фазу, которой автор не "
            f"писал. СЛЕДУЮЩИЙ ХОД: оберни хвост в свою фазу"))


def phase(name: str) -> _PhaseContext:
    """Одно звено ПЛАНА: написанное внутрь строится ОДНОЙ транзакцией.

        with phase("уровни и каркас"):
            lvl = create_level(elev_mm=0, name="Этаж 1")
            create_wall(p0_mm=(0, 0), p1_mm=(6000, 0), level=lvl,
                        height_mm=3000)

        with phase("лестница"):
            create_stairs(base_level="Этаж 1", top_level="Этаж 2", ...)

    ПЛАН — это последовательность фаз, а не одна большая программа. Транзакция
    на ФАЗУ, не на план: каждая фаза атомарна, между фазами — чекпойнт, и
    здания-наполовину не бывает ни в один момент. Провалилась фаза — план
    встал, УЖЕ ПОСТРОЕННЫЕ ФАЗЫ ОСТАЮТСЯ, и следующий ход продолжает с первой
    непройденной.

    ЧТО ЭТО МЕНЯЕТ ДЛЯ АВТОРА:
      * авторский бюджет (операций) меряет ФАЗУ, а не скрипт — здание перестало
        упираться в потолок одной программы;
      * соло-оп (`create_stairs`) — единственный в СВОЕЙ ФАЗЕ, а не в скрипте:
        многоэтажный дом стал выразим одним скриптом;
      * ссылка на элемент из ПРОШЛОЙ фазы законна и размечается сама (её
        подставит исполнитель по свидетелю той фазы); ссылка на элемент из
        БУДУЩЕЙ фазы — типизированный отказ;
      * ВСЕ операции скрипта обязаны лежать в фазах: нарисовал одну границу —
        размечай всё. Граница, которую автор не рисовал, не выдумывается.

    Скрипт, не зовущий `phase()` ни разу, не меняется НИ НА БАЙТ: программа и
    её дайджест те же, что были (`test_phases`: «отсутствие остаётся
    отсутствием»).
    """
    return _PhaseContext(name)


def take_ops() -> dict | None:
    """ДВЕРЬ ПЕСОЧНИЦЫ. Забрать программу — вместе с её фазами, если они есть.

    Песочница опрашивает язык именем `take_ops` первым (`_DRAIN_CANDIDATES`), и
    носителем этого имени в шиме (`language.py`) стоит ЭТА функция, а не
    `dsl.take_ops`. Причина ровно одна и она про место, а не про удобство:
    `dsl.py` не знает слова «фаза» и знать его не должен — фаза живёт в курсе,
    рядом с `unit()`. Слив остаётся дословно сливом языка: программу собирает и
    обнуляет `dsl.take_ops()`, здесь к ней только приписывается таблица.

    ТАБЛИЦА `phases` ЕДЕТ В КОНВЕРТЕ, А НЕ В ОПАХ. Опы остаются побайтово теми
    же — и это условие, а не вкус: их дайджест подписывает программу, и номер
    фазы, вписанный в каждый оп, сдвинул бы подпись у здания, которое не
    изменилось. Таблица же говорит то же самое один раз:

        [{"index": 0, "name": "каркас", "op_ids": ["level1", "wall1"]}, …]

    Фаз нет — ключа нет: отсутствие остаётся отсутствием.
    """
    from kukai.ir import dsl
    program = dsl.current()
    ledger = _LEDGERS.get(program)
    table = None
    if ledger is not None and ledger.phases:
        _refuse_tail(program, ledger)
        table = [p.as_dict() for p in ledger.phases]
    out = dsl.take_ops()
    if out is not None and table is not None:
        out["phases"] = table
    return out


