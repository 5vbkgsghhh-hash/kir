"""ВТОРАЯ ПОЛОВИНА ШВА: язык KIR плюс курс, одним модулем для песочницы.

Песочница кладёт в пространство скрипта публичные имена РОВНО ОДНОГО модуля
(`SandboxPolicy.dsl_module`) и отдаёт его же под алиасом `kir`. УМОЛЧАНИЕ этого
поля — ЭТОТ модуль, то есть шов проведён, а не запланирован: `preview` и
`design_check` лежат в пространстве каждого авторского скрипта прода. Способ
выбран второй из двух (`course.SEAM`) — он не трогает `dsl.py` вовсе.

ЧТО ЗДЕСЬ ЕСТЬ И ЧЕГО НЕТ.

* `from kukai.ir.dsl import *` — вся поверхность реестра, ТЕ ЖЕ объекты
  функций. Скрипт, написанный под `dsl`, работает здесь без единой правки.
* `take_ops` импортируется ИМЕНЕМ, потому что в `dsl.__all__` его намеренно
  нет: песочница ищет его на модуле (`_DRAIN_CANDIDATES`), а не в
  пространстве скрипта. Без этой строки программа собиралась бы, а наружу
  выходил бы ноль операций — самый тихий из возможных дефектов.
  НОСИТЕЛЬ ИМЕНИ — КУРС, А НЕ `dsl`: `course.take_ops` зовёт `dsl.take_ops`
  дословно и приписывает к конверту таблицу фаз, если автор их рисовал.
  `dsl.py` слова «фаза» не знает и знать не должен — фаза живёт рядом с
  `unit()`, у которого она структурный близнец. Выбор носителя — по-прежнему
  не семантика: этот файл ничего не решает, он только склеивает.
* `SANDBOX_NAMES` курса — 8 функций (`phase` и `spec` доехали последними,
  двумя разными волнами одного дня). Ни одного модуля: их песочница не
  инжектирует, и имя-модуль здесь молча пропало бы.
  Число здесь не литерал ради литерала — `test_course` сверяет состав словаря
  поимённо, поэтому расхождение этой строки с ним заметят, а не унаследуют.
* ИМЯ `spec` НЕ ЗАТИРАЕТ РЕЕСТР. `from kukai.ir.dsl import *` идёт по
  `dsl.__all__`, где `spec` нет (реестр там — импорт модуля, не экспорт), а
  `globals().update(SANDBOX_NAMES)` кладёт сюда ФУНКЦИЮ курса. Скрипту виден
  справочник; модуль реестра ему не виден вовсе — модули песочница не
  инжектирует.
* `warm_for_source` — ЕДИНСТВЕННОЕ, что этот файл решает сам, и решает он
  вопрос цены, а не смысла (см. ниже).
* Своей семантики нет НИ ОДНОЙ. Этот файл ничего не решает; он только
  склеивает два пространства имён, и на этом его обязанности кончаются.

ПОЧЕМУ ПРОГРЕВ УСЛОВНЫЙ, А НЕ БЕЗУСЛОВНЫЙ. `preview` и `design_check` зовут
модули, которые тянут shapely, numpy и networkx: ЗАМЕР 03.08 на прод-боксе —
+536 мс и +43 МБ к запуску. Песочница исполняет скрипт ДВАЖДЫ (`replay_check`),
значит безусловный прогрев стоил бы +1.1 с КАЖДОМУ ходу, включая те, что план и
вердикт не зовут вовсе, — при нынешнем счастливом пути 121 мс. Поэтому решает
ИСХОДНИК: имя, которого модель не написала, она вызвать не может (`globals`,
`eval`, `exec` и `__import__` скрипту закрыты), и подстрочный поиск здесь —
не эвристика, а точное условие.

ПОЧЕМУ ТЕСТЫ ГОНЯЮТСЯ ИМЕННО ЧЕРЕЗ НЕГО. Шов, который никто не прошёл целиком,
— обещание. Все рецепты курса исполняются настоящей песочницей с
`dsl_module="kukai.ir.course.language"`, то есть ровно тем составом имён,
который получит модель после переключения.
"""
from __future__ import annotations

from kukai.ir import dsl
from kukai.ir.dsl import *                        # noqa: F401,F403
from kukai.ir.course import SANDBOX_NAMES, take_ops  # noqa: F401

globals().update(SANDBOX_NAMES)

#: Имя курса -> модули, без которых оно не сработает В ПЕСОЧНИЦЕ.
#:
#: «Не сработает» здесь буквально: ребёнок ставит стража импортов
#: (`sandbox._MetaGuard`) перед исполнением скрипта, и любой модуль, которого к
#: этому моменту нет в `sys.modules`, поднимает KIR-B004 «импорт запрещён» — с
#: номером строки МОДЕЛИ и указанием чинить её исправный скрипт.
_WARM_BY_NAME: dict[str, tuple[str, ...]] = {
    "preview": ("kukai.ir.preview",),
    "design_check": ("kukai.ir.design_check",),
    # `spec()` печатает оглавление ПО РАЗДЕЛАМ ПРОЕКТА (09.08), а раздел опа
    # выводится, а не проставляется рукой: оп -> категория переписи (судья
    # приёмки, `kukai.ir.acceptance`) -> раздел (носители словаря
    # `registry_base.DISCIPLINES`, второй из них — таблица извлечения в
    # `kukai.ir.decompile.extract`). Оба модуля ленивы в `spec.py` нарочно:
    # их тянут все, а цепочка импорта у них тяжёлая и замкнулась бы на реестр.
    # ЗАМЕР, ВЫНУДИВШИЙ СТРОКУ: без прогрева `spec()` в песочнице отказывал
    # KIR-B004 «импорт kukai.ir.decompile запрещён» — то есть исправная
    # справка выглядела бы виной скрипта модели.
    "spec": ("kukai.ir.acceptance", "kukai.ir.decompile.extract"),
    # ЕДИНИЦА ЗАМЫСЛА С ПРЕДИКАТОМ (15.08). `unit(reads_as=…)` спрашивает
    # реестр прочтений у `assembly_view` ленивым импортом — и БЕЗ этой строки
    # он отказывал KIR-B004 «импорт kukai.ir.assembly_view запрещён» на живом
    # прогоне, с `blame: author`, то есть предикат обвинял автора за импорт,
    # которого автор не писал. ТРЕТЬЕ вхождение того же дефекта в этой самой
    # таблице: строка выше записывает его же со `spec()`. Ратчет заведён
    # затем, чтобы четвёртого не было
    # (`tests/test_sandbox_warm_covers_lazy_imports.py`).
    "reads_as": ("kukai.ir.assembly_view",),
}


def warm_for_source(source: str) -> tuple[str, ...]:
    """Догрузить то, что понадобится ИМЕННО ЭТОМУ исходнику. Вернуть загруженное.

    Зовётся песочницей ДО изоляции (`_child_main`, шаг «прогрев»), пока импорт
    ещё разрешён и корень ещё не пуст. Песочница грамматики языка не знает и
    знать не должна — поэтому решение «что грузить» принимается здесь, а не там.

    Молчит при любой неудаче намеренно: непрогретый модуль — это отсутствующая
    способность, о которой скажет сама функция курса в понятных словах, а
    исключение отсюда обвалило бы ВЕСЬ ход, включая программу, которая уже
    собралась бы без всякого вердикта.
    """
    import importlib

    loaded: list[str] = []
    for name, modules in _WARM_BY_NAME.items():
        if name not in source:
            continue
        for module in modules:
            try:
                importlib.import_module(module)
            except Exception:                     # pragma: no cover — см. выше
                continue
            loaded.append(module)
    return tuple(loaded)


__all__ = sorted(set(dsl.__all__) | set(SANDBOX_NAMES))
