"""Ожидание окна в тестах — НУЛЕВОЕ по умолчанию.

Задача #26 научила извлечение ждать возвращения окна: при исчерпании
ретраев страницы цикл делает паузу и повторяет, пока не вернётся мост или
не кончится общий запас прогона (``EXTRACT_WINDOW_WAIT_S``, боевое значение
300 с). В бою это правильно — мёртвое окно стоит пять минут ровно один раз
на прогон, и это дешевле, чем выбросить извлечение целой модели.

В тестах каждый прогон свой, и любой тест, который НАМЕРЕННО исчерпывает
бюджет ретраев (``timeout_probe_for`` в test_extract/test_pipeline), стал бы
ждать эти пять минут впустую: набор перестал укладываться в отведённое
время (замер: decompile-набор ушёл с ~190 с за 550 с и был убит).

Поэтому здесь запас обнуляется — часы не проверяются, проверяется логика.

ТЕСТУ, КОТОРЫЙ ПРОВЕРЯЕТ САМО ОЖИДАНИЕ, НАДО ВЕРНУТЬ ЗАПАС ЯВНО:
``mock.patch.multiple(extract, EXTRACT_WINDOW_WAIT_S=..., ...)`` —
см. ``test_extract_outage.py``. Обнуление здесь гасит ЧАСЫ, а не поведение:
все ветки ожидания покрыты там, с миллисекундными паузами.
"""
from __future__ import annotations

import pytest

from kukai.ir.decompile import extract as _extract


@pytest.fixture(autouse=True)
def _no_wall_clock_window_wait(monkeypatch):
    monkeypatch.setattr(_extract, "EXTRACT_WINDOW_WAIT_S", 0.0)
    monkeypatch.setattr(_extract, "EXTRACT_WINDOW_POLL_S", 0.0)
    # Паузы РЕТРАЕВ (боевые 5 и 20 с) НЕ трогаются: на них стоит
    # собственный страж dcf86ca7
    # (RetryBackoffWaitsForTheBridgeToComeBack), и глушить чужой предмет
    # проверки ради своей скорости — плохой размен. Здесь гасится ровно то,
    # что эта волна и добавила.
