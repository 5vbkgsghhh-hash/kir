#: Разделитель квалифицированного идентификатора операции пачки. РАВЕН
#: `clash_bundle._BUNDLE_SEP`, и равенство держится тестом: без него адрес
#: `p1/wall3` и адрес `p7/wall3` читались бы как один.
_BUNDLE_SEP = "/"

#: Состояния ребра хозяина. Закрытый список: состояние вне его — та самая
#: неподписанная ось, ради запрета которой весь этот учёт и заведён.
#: Источник, слова которого ОБЯЗЫВАЮТ АВТОРА. Только программа: всё
#: остальное — слова разбора, а разбор автору не начальник.
AUTHORED_SOURCE = "program_host_ref"

HOST_STATES: tuple[str, ...] = (
    "confirms", "contradicts", "host_out_of_scope", "absent", "unknown")

#: ПРОИСХОЖДЕНИЕ ПАРЫ — кто её внёс. Закрытый список.
#:
#: ЗАЧЕМ (замер 11.08.2026, `/tmp/wiring/m_delta.py`, пересборка
#: `snowdon_plumb_v4`, 129 чанков): на последнем ходу квитанция говорит
#: «СПОРОВ 45», и все 45 стояли ДО этого хода — ход не внёс НИ ОДНОГО.
#: Инженер, нажавший кнопку, читает 45 как свой вклад. Это то же самое
#: обвинение чужим, от которого только что вылечено ребро хозяина.
#:
#:   both_new   — обе стороны объявлены ЭТИМ ходом: спор целиком его;
#:   one_new    — одна сторона его, вторая стояла раньше. ТОЖЕ вклад хода:
#:                без него этой пары не существовало бы вовсе;
#:   both_prior — обе стороны стояли до хода. НЕ его работа, и складывать её
#:                с первыми двумя значит возвращать то самое число, которое
#:                нельзя прочитать;
#:   unknown    — границы хода не называли. Это НЕ `both_prior`: «не
#:                спрашивали» и «стояло раньше» — разные факты, и второй
#:                объявил бы чужим всё, о чём не спросили.
ORIGINS: tuple[str, ...] = ("both_new", "one_new", "both_prior", "unknown")


def origin_of(a_id: str, b_id: str,
              new_ids: frozenset[str] | None) -> str:
    """Происхождение пары. `None` -> `unknown` (границы хода не называли).

    Сторона относится к ходу по адресу СВОЕЙ ОПЕРАЦИИ: тело ребра графа
    (`p3/g#7`) принадлежит тому же ходу, что и породивший его оп `p3/g`.
    """
    if new_ids is None:
        return "unknown"
    a = a_id in new_ids or _op_key(a_id) in new_ids
    b = b_id in new_ids or _op_key(b_id) in new_ids
    if a and b:
        return "both_new"
    return "one_new" if (a or b) else "both_prior"


def _program_of(element_id: str) -> str:
    """Приставка ПРОГРАММЫ у адреса пачки (`p1/wall3` -> `p1`).

    Нужна затем, что `id` уникален внутри программы, а между программами
    совпадение ЗАКОННО — ровно поэтому `clash_bundle.bundle_oid`
    квалифицирует адрес ВСЕГДА. Сравнивать `host.value` с голым `id` соседа
    значит объявлять хозяином тёзку из чужой программы.
    """
    head, sep, _ = element_id.partition(_BUNDLE_SEP)
    return head if sep else ""


def _host_ref_of(op: Mapping[str, Any] | None) -> str | None:
    """Голый `id`, который операция назвала своим хозяином, либо `None`.

    Форма ссылки взята у самого языка: внутри программы автор ссылается на
    соседний оп через `{"by":"ref","value":<id>}`, и другого способа у него
    нет. Строка принимается как та же ссылка написанная короче.
    """
    if not isinstance(op, Mapping):
        return None
    host = op.get("host")
    if isinstance(host, Mapping):
        if str(host.get("by") or "") != "ref":
            return None
        value = host.get("value")
        return None if value is None else str(value)
    if isinstance(host, str) and host.strip():
        return host.strip()
    return None


def hosted_from_ops(ops: Mapping[str, Any]) -> dict[str, dict[str, Any]]:
    """`element_id -> операция` -> индекс хозяев СЛОВАМИ САМОЙ ПРОГРАММЫ.

    Ссылка разрешается ТОЛЬКО внутри своей программы (`KIR-V002`: ссылка через
    границу программы незаконна), поэтому кандидат ищется среди адресов с той
    же приставкой `p<N>/`. Не разрешившаяся ссылка остаётся в индексе с
    `host_element_id = None`: автор хозяина НАЗВАЛ, и молчать об этом нельзя —
    «хозяин назван, но не найден» ближе к `contradicts`, чем к `absent`, и
    именно так оно ниже и читается.
    """
    by_program: dict[str, dict[str, str]] = {}
    for element_id, op in ops.items():
        if not isinstance(op, Mapping):
            continue
        oid = op.get("id")
        if oid is None:
            continue
        by_program.setdefault(_program_of(str(element_id)), {}).setdefault(
            str(oid), str(element_id))
    out: dict[str, dict[str, Any]] = {}
    for element_id, op in ops.items():
        ref = _host_ref_of(op)
        if ref is None:
            continue
        program = _program_of(str(element_id))
        target = (by_program.get(program) or {}).get(ref)
        out[str(element_id)] = {
            "host_element_id": target,
            "host_ref": ref,
            "host_class": None if target is None else str(
                (ops.get(target) or {}).get("op") or "") or None,
            "source": "program_host_ref",
        }
    return out


def host_relation(a_id: str, b_id: str,
                  hosted: Mapping[str, Any] | None
                  ) -> tuple[str, str | None, str | None]:
    """Ребро хозяина для пары -> (состояние, адрес хозяина, чьи это слова).

    Состояние — одно из `HOST_STATES`. Адрес хозяина возвращается ТОЛЬКО у
    `contradicts`: там он и есть новость («дверь перекрывает стену, в которой
    не живёт, а живёт вот в этой»). У `confirms` хозяин — вторая сторона пары,
    и повторять её адрес значит печатать то, что уже напечатано.

    ОТСУТСТВИЕ НЕ ОПРАВДЫВАЕТ. `absent` возвращается только тогда, когда
    индекс ЕСТЬ и ни одна сторона хозяина не объявила; читатель обязан
    прочитать это как «про хозяина сказать нечего», а не как «хозяина нет,
    значит это узел».
    """
    if hosted is None:
        return "unknown", None, None
    a_key, b_key = _op_key(a_id), _op_key(b_id)
    #: Кандидаты в исход, СИЛЬНЕЙШИЙ ПЕРВЫМ. `contradicts` перевешивает
    #: `host_out_of_scope` потому, что это более сильное утверждение: там
    #: хозяин ИЗВЕСТЕН и это не вторая сторона, здесь хозяина мы просто не
    #: видели. Молчать о более сильном ради более слабого нельзя.
    found: dict[str, tuple[str, str | None]] = {}
    for me, other, other_key in ((a_id, b_id, b_key), (b_id, a_id, a_key)):
        edge = hosted.get(me) or hosted.get(_op_key(me))
        if not isinstance(edge, Mapping):
            continue
        target = edge.get("host_element_id")
        source = str(edge.get("source") or "") or None
        if target is not None:
            if _op_key(str(target)) in (other, other_key):
                return "confirms", None, source
            found.setdefault("contradicts", (str(target), source))
            continue
        # ХОЗЯИН НАЗВАН, НО НЕ НАЙДЕН — И ЭТО ДВА РАЗНЫХ ФАКТА, СМОТРЯ ЧЬИ
        # ЭТО СЛОВА. Слова ПРОГРАММЫ: автор сослался на оп, которого в его
        # программе нет, и чинит это он (`KIR-V002`). Слова РАЗБОРА: хозяина
        # не извлекли мы — замер по корпусу говорит, что он лежит в связанном
        # файле (1 010 из 1 263) или является датумом (86), и обвинять автора
        # 959 раз подряд за границу нашего чтения — дефект того же рода, что
        # молчащий прибор, только с обратным знаком.
        ref = str(edge.get("host_ref") or "") or "?"
        key = ("contradicts" if source == AUTHORED_SOURCE
               else "host_out_of_scope")
        found.setdefault(key, (ref, source))
    for state in ("contradicts", "host_out_of_scope"):
        if state in found:
            return state, found[state][0], found[state][1]
    return "absent", None, None


def _classify(finding: Mapping[str, Any], slack: tuple[str, ...],
              host_state: str) -> tuple[str, str]:
    """Пара -> (правило, отказанное правило либо пусто). Порядок ЗНАЧИМ."""
    a, b = finding["a"], finding["b"]
    role_a, role_b = role_of(a.get("label")), role_of(b.get("label"))
    roles = {role_a, role_b}
    relation = finding.get("hull_relation")

    # СНИМАЕТ ТОЛЬКО ПОДТВЕРЖДЕНИЕ. `contradicts`, `absent` и `unknown`
    # проваливаются дальше НАРОЧНО: снятая по отсутствию хозяина пара — это
    # оправдание молчанием, то есть ровно тот дефект, ради которого ребро
    # стало тристейтом.
    if host_state == "confirms":
        return "host_declared", ""
    if finding.get("pair_kind") == "coincident_duplicate":
        return "duplicate", ""
    if relation == "contact" and roles <= _STRUCTURE_ROLES:
        return "structure_contact", ""
    if slack:
        return "hull_over_approximation", ""
    if roles <= _RUN_ROLES:
        if relation == "contact":
            return "unclassified", "run_meets_run_clearance"
        return "run_meets_run", ""
    if roles & _RUN_ROLES:
        other = role_b if role_a in _RUN_ROLES else role_a
        if other == "envelope":
            return "run_through_envelope", ""
        if other == "bearing":
            return "run_through_bearing", ""
        if other == "equipment":
            return "run_meets_equipment", ""
        return "unclassified", ""
    if roles <= _STRUCTURE_ROLES:
        return "unclassified", "structure_meets_structure_overlap"
    if roles & {"equipment"} and roles & _STRUCTURE_ROLES:
        return "unclassified", "equipment_meets_structure"
    return "unclassified", ""


def _rung(kind: str, finding: Mapping[str, Any], proven: bool | None) -> str:
    """СТУПЕНЬ = (доказательность × род × глубина). Ни одного порога с потолка.

    Порог глубины здесь ровно один и он ЧУЖОЙ: `ranking_tol_mm` — допуск
    СОБСТВЕННОГО грейда оболочки из `hulls.TOL_GRADE_MM` (exact 0, conservative
    1, coarse 25 мм). Перекрытие мельче него лежит внутри числового шума самой
    оболочки, и утверждать по нему нечего.

    Своего «значимо/незначимо» этот модуль не заводит намеренно. Слой
    `clash/review.py` держит пороги 100 мм и 10 мм, у которых обоснования нет
    ни в его тексте, ни в замерах пакета; повторять их здесь значило бы
    удвоить выдумку. Глубина едет в находке ЧИСЛОМ, и читатель судит сам.
    """
    depth = float(finding.get("hull_overlap_depth_mm") or 0.0)
    tol = float(finding.get("ranking_tol_mm") or 0.0)
    if kind in ("adjacency",):
        return "note"
    if kind in ("unproven", "unclassified"):
        return "nothing"
    if kind == "penetration":
        # Узел, но по габаритному боксу и узла не видно.
        #
        # ЗДЕСЬ БЫЛО `proven is not False and proven is not None`, и первый
        # член НЕ МОГ БЫТЬ ЛОЖНЫМ. `_classify` возвращает `penetration` только
        # ПОСЛЕ ветки `if slack: return "hull_over_approximation"`, то есть у
        # проникания огрубление пусто ВСЕГДА, а `proven=False` ставится ровно
        # и только при непустом огрублении. Условие, которое не может не
        # выполниться, читается проверкой, не будучи ею, — тот же класс, что
        # убитый на этой же неделе вакуумный сертификат `_plate_can_miss`.
        return "agree" if proven is not None else "look"
    # collision | duplicate
    if proven is None:
        return "look"
    if depth <= tol:
        # Внутри собственного допуска грейда — смотреть, но не чинить.
        return "look"
    return "fix"


def _op_address(element_id: str, op: Mapping[str, Any] | None) -> str:
    name = str((op or {}).get("op") or "оп")
    return f"`{name} {element_id}`"


def _diameter_of(op: Mapping[str, Any] | None) -> float | None:
    value = (op or {}).get("diameter_mm")
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    return float(value)


def _next_move(rule_id: str, finding: Mapping[str, Any],
               slack: tuple[str, ...], op_a: Mapping[str, Any] | None,
               op_b: Mapping[str, Any] | None, safe_destructive: bool) -> str:
    """ХОД, ВЫВОДИМЫЙ ИЗ ПРОГРАММЫ. Ни одной догадки: либо адрес операции и её
    операнд, либо число, посчитанное детектором, либо честное «нечем»."""
    a, b = finding["a"], finding["b"]
    a_id, b_id = a["source_element_id"], b["source_element_id"]
    addr_a, addr_b = _op_address(a_id, op_a), _op_address(b_id, op_b)
    vector = finding.get("certified_separating_translation_mm")

    if rule_id == "duplicate":
        if safe_destructive:
            return (f"удалить ОДИН из двух: {addr_a} либо {addr_b} — тела "
                    f"совпали, а не только габариты")
        return (f"сверить {addr_a} и {addr_b} глазами: совпали ГАБАРИТЫ, а "
                f"хотя бы одна оболочка — габаритный бокс; удалять по такой "
                f"находке нельзя")
    if rule_id == "host_declared":
        return "ничего: автор сам объявил вмещение через `host`"
    if rule_id == "structure_contact":
        return "ничего: конструкции обязаны касаться"
    if rule_id == "hull_over_approximation":
        moves = []
        if "plate_z_doubling" in slack:
            moves.append(
                "программа не выражает, в какую сторону от отметки нарастает "
                "плита; пока не выражает — эта пара не судится")
        if "profile_convexified" in slack:
            moves.append(
                "объявленные контуры в плане НЕ встречаются: спор возможен "
                "только за пределами объявленного контура")
        return "; ".join(moves) or "дополнить заявление"
    if rule_id == "run_through_envelope":
        run_op, run_id = ((op_a, a_id) if role_of(a.get("label")) in _RUN_ROLES
                          else (op_b, b_id))
        host_id = b_id if run_id == a_id else a_id
        diameter = _diameter_of(run_op)
        size = f" под Ø{diameter:.0f} мм" if diameter else ""
        return (f"объявить проём: `create_opening` с `host` = {host_id}"
                f"{size} — либо подтвердить, что проём уже в модели")
    if rule_id in ("run_meets_run", "run_through_bearing",
                   "run_meets_equipment"):
        if isinstance(vector, (list, tuple)) and len(vector) == 3:
            v = ", ".join(f"{float(c):+.0f}" for c in vector)
            return (f"развести: сдвинуть {addr_a} на ({v}) мм — это "
                    f"сертифицированный разводящий перенос детектора")
        diameter = _diameter_of(op_a) or _diameter_of(op_b)
        if diameter:
            return (f"развести: сдвинуть {addr_a} или {addr_b}; объявленный "
                    f"размер трассы — Ø{diameter:.0f} мм")
        return f"развести: сдвинуть {addr_a} или {addr_b}"
    return "нечем: ни одно правило не применимо, пара оставлена с числами"


def _text(rule: Rule, finding: Mapping[str, Any], proven: bool | None,
          slack: tuple[str, ...]) -> str:
    a, b = finding["a"], finding["b"]
    an, bn = _label_ru(a.get("label")), _label_ru(b.get("label"))
    a_id, b_id = a["source_element_id"], b["source_element_id"]
    depth = float(finding.get("hull_overlap_depth_mm") or 0.0)
    grade = finding.get("hull_grade")
    tol = float(finding.get("ranking_tol_mm") or 0.0)
    disc_a, disc_b = (discipline_of(a.get("category")),
                      discipline_of(b.get("category")))
    disc = (f"раздел {disc_a}" if disc_a == disc_b
            else f"разделы {disc_a}↔{disc_b}")
    sure = {True: "доказано оболочками",
            False: "НЕ доказано",
            None: "сказать нечего: оболочка — габаритный бокс"}[proven]
    head = {
        "duplicate": f"ДУБЛИКАТ: {an} {a_id} и {bn} {b_id} стоят НА ОДНОМ МЕСТЕ",
        "collision": f"СТОЛКНОВЕНИЕ: {an} {a_id} и {bn} {b_id} делят объём",
        "penetration": (f"ПРОХОД СКВОЗЬ КОНСТРУКЦИЮ: {an} {a_id} в теле "
                        f"{bn} {b_id}"),
        "adjacency": f"ПРИМЫКАНИЕ: {an} {a_id} и {bn} {b_id} соприкасаются",
        "unproven": (f"НЕ ДОКАЗАНО: {an} {a_id} и {bn} {b_id} спорят только "
                     f"в оболочках"),
        "unclassified": f"БЕЗ СУЖДЕНИЯ: {an} {a_id} и {bn} {b_id}",
    }[rule.kind]
    line = (f"{head}; глубина {depth:.0f} мм, {sure} "
            f"(грейд {grade}, допуск грейда {tol:.0f} мм, {disc})")
    if rule.kind == "penetration":
        line += (". СКВОЗЬ ИЛИ ВДОЛЬ — по оболочкам не различается: "
                 "трасса, лежащая внутри конструкции по её длине, дала бы "
                 "ту же глубину")
    if slack and rule.kind == "unproven":
        # Огрубление печатается там, где оно и есть ответ. У примыкания
        # ответ другой, и вешать на него ту же простыню значит утопить его.
        line += ". ОГРУБЛЕНИЕ: " + "; ".join(SLACK_REASONS[s] for s in slack)
    return line


def _same_host(a_id: str, b_id: str,
               hosted: Mapping[str, Any] | None) -> str | None:
    """Общий хозяин обеих сторон, либо `None`.

    ЗАМЕР, ради которого этот случай разведён (10.08.2026,
    `/tmp/wiring/m_contra.py`): из 8 728 пар `contradicts` на
    `sob62_fas_r23_v19` **1 584 — БРАТЬЯ**, обе стороны объявили ОДНОГО
    хозяина (панель и импост одного витража, две панели одного витража). На
    `sob62_r23_v5` таких 15 из 588.

    Разница не косметическая: «дверь перекрывает стену, в которой не живёт» и
    «две панели ОДНОГО витража стоят на одном месте» чинятся в разных местах —
    первое переносом, второе удалением лишней панели. Читатель, получивший на
    оба случая одну фразу, вторую починку не найдёт.
    """
    if hosted is None:
        return None
    ea = hosted.get(a_id) or hosted.get(_op_key(a_id))
    eb = hosted.get(b_id) or hosted.get(_op_key(b_id))
    if not isinstance(ea, Mapping) or not isinstance(eb, Mapping):
        return None
    ha, hb = ea.get("host_element_id"), eb.get("host_element_id")
    if ha is None or hb is None or str(ha) != str(hb):
        return None
    return str(ha)


def _host_note(host_state: str, host_id: str | None,
               shared: str | None = None) -> str:
    """Приписка о хозяине — ТОЛЬКО там, где она новость.

    `confirms` молчит: пара и так снята правилом `host_declared`, и его текст
    уже всё сказал. `unknown` молчит: «индекса не было» — свойство ВЫЗОВА, а
    не этой пары, и печатать его в каждой строке значит платить контекстом за
    новость, которой нет; для него есть счётчик `by_host_state`.

    Говорит РОВНО `contradicts`, потому что это единственное состояние, в
    котором ребро меняет то, что читатель сделает: пара выглядит узлом по
    ярлыкам, а хозяин у элемента ДРУГОЙ.
    """
    if host_state == "host_out_of_scope":
        # НАЗЫВАЕТ ГРАНИЦУ, А НЕ ВИНОВНОГО. Замер по корпусу: 1 010 таких
        # хозяев из 1 263 лежат в СВЯЗАННОМ файле, 86 — датумы
        # (`ReferencePlane`), которые телом не бывают в принципе. Автор к
        # этому не имеет отношения ни в одном из случаев.
        return (f". ХОЗЯИН ОБЪЯВЛЕН, НО ЕГО НЕТ В ИЗВЛЕЧЕНИИ: разбор называет "
                f"хозяином `{host_id}`, а такого элемента мы не извлекали — "
                f"он за границей чтения (связанный файл либо датум). Это НЕ "
                f"ошибка автора и НЕ оправдание паре: про вмещение здесь "
                f"сказать нечего, находка остаётся")
    if host_state != "contradicts":
        return ""
    if shared is not None:
        return (f". ОБЕ СТОРОНЫ ЖИВУТ В ОДНОМ ХОЗЯИНЕ `{shared}`, а не одна в "
                f"другой: это БРАТЬЯ, и перекрытие между ними хозяином не "
                f"объясняется — узел здесь ни при чём")
    return (f". ХОЗЯИН ОБЪЯВЛЕН, И ЭТО НЕ ВТОРАЯ СТОРОНА: автор назвал хозяином "
            f"`{host_id}`, а перекрытие — с другим элементом. Снятие по "
            f"хозяину НЕ ПРИМЕНИМО, находка остаётся")


#: Приставка тела, порождённого ребром графа (`clash_bundle._SEGMENT_SEP`):
#: у всех рёбер одного графа операция ОДНА, и ход находки адресует именно её.
_SEGMENT_SEP = "#"


def _op_key(element_id: str) -> str:
    return element_id.split(_SEGMENT_SEP, 1)[0]


def judge(findings: Iterable[Mapping[str, Any]], *,
          hulls: Mapping[str, Any] | None = None,
          profiles: Mapping[str, Any] | None = None,
          slack: Mapping[str, Any] | None = None,
          ops: Mapping[str, Any] | None = None,
          hosted: Mapping[str, Any] | None = None,
          new_ids: frozenset[str] | None = None) -> Judgement:
    """Находки детектора -> суждения. Чистая функция, НИКОГДА не бросает.

    `hulls`   — `source_id -> HullRecord` уже построенного снапшота (читается
                только габарит по Z);
    `profiles`— объявленные контуры подошв (`BundleGeometry.profiles`);
    `slack`   — огрубление, внесённое `clash_bundle` (`{"z_mm": t, ...}`);
    `ops`     — `element_id -> операция`, из которой элемент родился: без неё
                ход можно только выдумать, а выдуманный ход хуже молчания;
    `hosted`  — ИНДЕКС ХОЗЯЕВ, `element_id -> {"host_element_id", "host_class",
                "source"}`. `None` значит РОВНО «не спрашивали» и даёт всем
                парам состояние `unknown`; ПУСТОЙ словарь значит «спросили,
                хозяев нет» и даёт `absent`. Эти два факта разные, и путать
                их нельзя ни в одну сторону — ровно так же, как `journal`
                различает `sections=None` и `sections={}`.

                Когда `hosted` не передан, а `ops` передан, индекс строится
                ЗДЕСЬ из слов самой программы (`hosted_from_ops`): ни один
                прежний вызывающий не теряет отношения хозяина, и вдобавок
                получает его КВАЛИФИЦИРОВАННЫМ по программе — см. дефект в
                шапке `hosted_from_ops`.
    """
    hulls = hulls or {}
    profiles = profiles or {}
    slack = slack or {}
    ops = ops or {}
    if hosted is None and ops:
        hosted = hosted_from_ops(ops)

    judged: list[Judged] = []
    by_kind: dict[str, int] = {}
    by_rung: dict[str, int] = {}
    filtered_rule: dict[str, int] = {}
    refused_rule: dict[str, int] = {}
    filtered_slack: dict[str, int] = {}
    by_host: dict[str, int] = {}
    by_origin: dict[str, int] = {}
    justifications: dict[str, str] = {}

    for finding in findings:
        a_id = finding["a"]["source_element_id"]
        b_id = finding["b"]["source_element_id"]
        op_a = ops.get(a_id) or ops.get(_op_key(a_id))
        op_b = ops.get(b_id) or ops.get(_op_key(b_id))
        explains = _slack_explains(finding, hulls, profiles, slack)
        host_state, host_id, host_source = host_relation(a_id, b_id, hosted)
        by_host[host_state] = by_host.get(host_state, 0) + 1
        origin = origin_of(a_id, b_id, new_ids)
        by_origin[origin] = by_origin.get(origin, 0) + 1
        rule_id, refused = _classify(finding, explains, host_state)
        rule = _RULE_BY_ID[rule_id]
        # ДОКАЗАТЕЛЬНОСТЬ ТРИСТЕЙТОМ, тем же законом, что `hulls_coincide`:
        # `None` значит «нечего сказать», и это НЕ «не доказано».
        if explains:
            proven: bool | None = False
        elif (_hull_is_a_box(finding["a"]) or _hull_is_a_box(finding["b"])
              or finding.get("hull_grade") == "coarse"):
            proven = None
        else:
            proven = True
        rung = _rung(rule.kind, finding, proven)
        safe = _destructive_is_safe(finding)
        why = rule.why_ru if not refused else REFUSED_RULES[refused]
        item = Judged(
            finding_id=str(finding.get("finding_id") or f"{a_id}~{b_id}"),
            a_id=a_id, b_id=b_id, kind=rule.kind,
            rule_id=refused or rule_id, rung=rung, proven=proven,
            depth_mm=float(finding.get("hull_overlap_depth_mm") or 0.0),
            relation=str(finding.get("hull_relation") or ""),
            pair_kind=str(finding.get("pair_kind") or ""),
            hull_grade=str(finding.get("hull_grade") or ""),
            a_label=str(finding["a"].get("label") or ""),
            b_label=str(finding["b"].get("label") or ""),
            slack=explains,
            text_ru=_text(rule, finding, proven, explains)
            + (f". ПРАВИЛО НЕ НАПИСАНО: `{refused}`" if refused else "")
            + _host_note(host_state, host_id,
                         _same_host(a_id, b_id, hosted)
                         if host_state == "contradicts" else None),
            next_move_ru=_next_move(rule_id, finding, explains, op_a, op_b, safe),
            why_ru=why,
            host_state=host_state, declared_host_id=host_id,
            host_source=host_source, origin=origin)
        judged.append(item)
        justifications[refused or rule_id] = why
        by_kind[rule.kind] = by_kind.get(rule.kind, 0) + 1
        by_rung[rung] = by_rung.get(rung, 0) + 1
        if refused:
            refused_rule[refused] = refused_rule.get(refused, 0) + 1
        elif _RUNG_ORDER[rung] > _RUNG_ORDER["look"]:
            filtered_rule[rule_id] = filtered_rule.get(rule_id, 0) + 1
        for name in explains:
            filtered_slack[name] = filtered_slack.get(name, 0) + 1

    # ПОРЯДОК ПОКАЗА. Внутри одной ступени первыми идут пары, у которых
    # правило ОТКАЗАНО: это единственные строки, отвечающие на вопрос «чего не
    # хватает языку», и утонуть в повторяющемся огрублении они не должны.
    # СВОЁ ВПЕРЕДИ ЧУЖОГО — ВНУТРИ ОДНОЙ СТУПЕНИ И ТОЛЬКО КОГДА СПРОСИЛИ.
    # Ступень остаётся старшим ключом: она договор о допустимом действии, и
    # менять её порядок происхождением значило бы прятать опасное за своим.
    # Без границы хода (`new_ids is None`) все пары `unknown`, ключ
    # тождественно нулевой, и порядок остаётся БАЙТ В БАЙТ прежним.
    _ORIGIN_FIRST = {"both_new": 0, "one_new": 0, "both_prior": 1,
                     "unknown": 0}
    judged.sort(key=lambda j: (_RUNG_ORDER[j.rung],
                               _ORIGIN_FIRST[j.origin],
                               0 if j.rule_id in REFUSED_RULES else 1,
                               -j.depth_mm, j.finding_id))
    # ИМЕНОВАННЫЕ, А НЕ ПОЗИЦИОННЫЕ: у `Judgement` семь счётчиков одного типа
    # `dict[str, int]`, и перепутанные местами два из них не поймал бы ни один
    # тип — только глаз на цифрах в квитанции.
    return Judgement(
        judged=tuple(judged),
        by_kind=dict(sorted(by_kind.items())),
        by_rung=dict(sorted(by_rung.items())),
        filtered_by_rule=dict(sorted(filtered_rule.items())),
        refused_by_rule=dict(sorted(refused_rule.items())),
        filtered_by_slack=dict(sorted(filtered_slack.items())),
        by_host_state=dict(sorted(by_host.items())),
        by_origin=dict(sorted(by_origin.items())),
        justifications=dict(sorted(justifications.items())))
