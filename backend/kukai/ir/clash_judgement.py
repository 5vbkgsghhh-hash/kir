# ── опровержение в плане: работает над ЧИСЛАМИ САМОЙ ПРОГРАММЫ ──────────────

#: Порог вырождения при сравнении контуров. Это НЕ допуск строительства и не
#: «мало миллиметров»: контуры приходят одними и теми же числами из одной и
#: той же программы, поэтому сравнивать их надо на точное совпадение, а
#: единственная неточность — двоичная. 1e-6 мм — это 1 пикометр; ни одно
#: настоящее расстояние в здании в него не попадает.
_DEGENERATE = 1e-6


def _cross(o: Sequence[float], a: Sequence[float], b: Sequence[float]) -> float:
    return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])


def loop_is_convex(loop: Sequence[Sequence[float]]) -> bool:
    """Выпуклый ли ОБЪЯВЛЕННЫЙ контур. Выпуклый контур равен своей выпуклой
    оболочке — значит для него огрубление `profile_convexified` НУЛЕВОЕ, и
    ссылаться на него нельзя."""
    n = len(loop)
    if n < 3:
        return True
    sign = 0
    for i in range(n):
        c = _cross(loop[i], loop[(i + 1) % n], loop[(i + 2) % n])
        if abs(c) < _DEGENERATE:
            continue
        s = 1 if c > 0 else -1
        if sign and s != sign:
            return False
        sign = s
    return True


def _on_segment(p: Sequence[float], a: Sequence[float],
                b: Sequence[float]) -> bool:
    """Лежит ли точка НА отрезке.

    Ревью №8 в `geom` уже ловило этот класс ошибки: «КВАДРАТ длины нельзя
    сравнивать с порогом длины». Здесь было ровно то же — `_cross` имеет
    размерность мм², а `_DEGENERATE` задан в мм, поэтому порог ЕХАЛ ВМЕСТЕ С
    МАСШТАБОМ: на ребре длиной 20 000 мм точка, отстоящая от прямой на 1e-10 мм,
    давала произведение 2e-6 > 1e-6 и объявлялась ВНЕ отрезка. Дальше её
    подхватывал `_strictly_inside`, и касание читалось как перекрытие.

    Замер 10.08.2026, ворота `loops_overlap` против shapely на 117 987
    настоящих парах контуров (7 зданий): 5 расхождений, все — касания,
    объявленные перекрытием, худшее у контура из 108 вершин (`k2_ar_rd_v15`,
    11840492) с площадью пересечения 0.0. После перехода на РАССТОЯНИЕ
    (произведение, делённое на длину ребра) расхождений 0.

    Вырожденное ребро (a == b) сравнивается как точка: делить не на что.
    """
    ex, ey = b[0] - a[0], b[1] - a[1]
    L = math.hypot(ex, ey)
    if L <= _DEGENERATE:
        return (abs(p[0] - a[0]) <= _DEGENERATE
                and abs(p[1] - a[1]) <= _DEGENERATE)
    if abs(_cross(a, b, p)) / L > _DEGENERATE:
        return False
    return (min(a[0], b[0]) - _DEGENERATE <= p[0] <= max(a[0], b[0]) + _DEGENERATE
            and min(a[1], b[1]) - _DEGENERATE <= p[1] <= max(a[1], b[1]) + _DEGENERATE)


def _properly_cross(p1, p2, p3, p4) -> bool:
    """СОБСТВЕННОЕ пересечение отрезков: общий конец и налегание не считаются.

    Так и надо: две замощающие плиты делят РЕБРО, и объявить это пересечением
    значило бы вернуть ровно тот шум, ради которого модуль написан."""
    d1, d2 = _cross(p3, p4, p1), _cross(p3, p4, p2)
    d3, d4 = _cross(p1, p2, p3), _cross(p1, p2, p4)
    return (((d1 > _DEGENERATE and d2 < -_DEGENERATE)
             or (d1 < -_DEGENERATE and d2 > _DEGENERATE))
            and ((d3 > _DEGENERATE and d4 < -_DEGENERATE)
                 or (d3 < -_DEGENERATE and d4 > _DEGENERATE)))


def _strictly_inside(p: Sequence[float],
                     loop: Sequence[Sequence[float]]) -> bool:
    n = len(loop)
    if any(_on_segment(p, loop[i], loop[(i + 1) % n]) for i in range(n)):
        return False
    inside = False
    for i in range(n):
        a, b = loop[i], loop[(i + 1) % n]
        if (a[1] > p[1]) != (b[1] > p[1]):
            x = a[0] + (p[1] - a[1]) * (b[0] - a[0]) / (b[1] - a[1])
            if x > p[0]:
                inside = not inside
    return inside


#: Потолок на произведение вершин пары контуров. Проверка стоит O(n·m); замер
#: 09.08 на `snowdon_plumb_v5`: 111 контуров, до 26 вершин, 76 пар — 8 мс на
#: всё. Потолок стоит не ради этих чисел, а ради того, чтобы контур в тысячу
#: вершин не превратил ДЕШЁВОЕ опровержение в дорогое; за потолком ответ
#: `None` — «не проверяли», и он отличается от «не пересекаются».
_MAX_LOOP_WORK = 250_000


def _ccw(loop):
    """Контур против часовой стрелки. Ориентация нужна, чтобы «выпуклая
    вершина» была фактом, а не следствием порядка обхода."""
    n = len(loop)
    area2 = sum(loop[i][0] * loop[(i + 1) % n][1]
                - loop[(i + 1) % n][0] * loop[i][1] for i in range(n))
    return list(loop) if area2 >= 0 else list(reversed(loop))


def _point_in_triangle(p, a, b, c) -> bool:
    d1, d2, d3 = _cross(a, b, p), _cross(b, c, p), _cross(c, a, p)
    neg = d1 < -_DEGENERATE or d2 < -_DEGENERATE or d3 < -_DEGENERATE
    pos = d1 > _DEGENERATE or d2 > _DEGENERATE or d3 > _DEGENERATE
    return not (neg and pos)


def _interior_witness(loop):
    """Точка СТРОГО внутри простого контура, либо `None`.

    Берётся «ухо»: выпуклая вершина, в треугольник которой не попала ни одна
    другая вершина; центр такого треугольника лежит внутри контура. Свидетель
    нужен затем, что у двух СОВПАДАЮЩИХ контуров ни одна точка границы
    свидетелем быть не может — вся граница одного лежит на границе другого.
    """
    pts = _ccw(loop)
    n = len(pts)
    if n < 3:
        return None
    for i in range(n):
        a, b, c = pts[(i - 1) % n], pts[i], pts[(i + 1) % n]
        if _cross(a, b, c) <= _DEGENERATE:
            continue
        blocked = False
        for k in range(n):
            q = pts[k]
            if q is a or q is b or q is c:
                continue
            if _point_in_triangle(q, a, b, c):
                blocked = True
                break
        if blocked:
            continue
        return ((a[0] + b[0] + c[0]) / 3.0, (a[1] + b[1] + c[1]) / 3.0)
    return None


def _sub_edge_midpoints(loop, other):
    """Середины кусков, на которые граница `other` режет рёбра `loop`.

    Ребро, целиком лежащее ВНУТРИ второго контура, не даёт ни собственного
    пересечения рёбер, ни строго внутренней вершины — и до этой правки не
    давало вообще ничего. Его середина и есть недостающий свидетель.
    """
    n, m = len(loop), len(other)
    for i in range(n):
        a, b = loop[i], loop[(i + 1) % n]
        dx, dy = b[0] - a[0], b[1] - a[1]
        ts = [0.0, 1.0]
        for j in range(m):
            c, d = other[j], other[(j + 1) % m]
            den = dx * (d[1] - c[1]) - dy * (d[0] - c[0])
            if abs(den) <= _DEGENERATE:
                continue
            t = ((c[0] - a[0]) * (d[1] - c[1])
                 - (c[1] - a[1]) * (d[0] - c[0])) / den
            if 0.0 < t < 1.0:
                ts.append(t)
        ts.sort()
        for k in range(len(ts) - 1):
            t = 0.5 * (ts[k] + ts[k + 1])
            yield (a[0] + dx * t, a[1] + dy * t)


