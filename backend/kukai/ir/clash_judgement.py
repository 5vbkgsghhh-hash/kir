def _plate_can_miss(sa, sb) -> bool:
    """∃ ЗАКОННОЕ прочтение, при котором срезы не встречаются по Z.

    Множество законных прочтений — НЕ произведение {вниз,вверх}²: сторона
    роста есть свойство СОГЛАШЕНИЯ, а не элемента, поэтому две операции
    ОДНОГО класса читаются одинаково. Перекрёстные прочтения (одна плита
    вниз, другая вверх при одном классе) физически невозможны, и именно они
    прежде удовлетворяли условие ТОЖДЕСТВЕННО: 2·min(tₐ,t_b) − tₐ − t_b
    = −|tₐ − t_b| ≤ 0 при любых толщинах. Сертификат, который не может не
    сработать, читается доказательством, не будучи им.
    """
    ta, tb = float(sa.get("z_mm") or 0.0), float(sb.get("z_mm") or 0.0)
    ra, rb = sa.get("z_ref_mm"), sb.get("z_ref_mm")
    if not (ta > 0.0 and tb > 0.0) or ra is None or rb is None:
        return False                      # нечем судить — НЕ рефутация
    ga, gb = sa.get("grow_class"), sb.get("grow_class")
    if ga is None or gb is None:
        return False                      # НЕ рефутация, а молчание
    readings = (("down", "down"), ("up", "up")) if ga == gb else (
        ("down", "down"), ("up", "up"), ("down", "up"), ("up", "down"))
    for da, db in readings:
        lo_a, hi_a = (ra - ta, ra) if da == "down" else (ra, ra + ta)
        lo_b, hi_b = (rb - tb, rb) if db == "down" else (rb, rb + tb)
        if min(hi_a, hi_b) - max(lo_a, lo_b) <= 0.0:
            return True
    return False


