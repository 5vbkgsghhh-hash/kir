#: Допуск сравнения двух чисел в мм, пришедших разными путями (программа
#: пишет 100.0, документ хранит футы и переводит обратно). См.
#: `open_model.TypeSection.outer_for_nominal_mm` — там же и обоснование.
_NOMINAL_TOL_MM = 0.5


@dataclass(frozen=True)
class SnapshotSections:
    """Геометрия типов и отметки уровней ОДНОГО снапшота открытой модели.

    Ключ строки — тот же короткий текст селектора, что печатает `_sel_text`
    (`name:Стена 200`, `element_id:273445`), поэтому поиск идёт ровно по тому,
    что программа НАПИСАЛА, без второго разрешения селекторов рядом с ground.
    Селектор, который ground разрешает правилом (`by:default`, `by:ref`), сюда
    не попадает и получает названную причину, а не тихий промах.
    """

    levels: Mapping[str, float]
    types: Mapping[str, Mapping[str, Mapping[str, Any]]]

    @classmethod
    def from_snapshot(cls, snapshot: Any) -> "SnapshotSections | None":
        """Снапшот ground -> индекс. `None` — снапшота нет вовсе.

        Пустой индекс и ОТСУТСТВУЮЩИЙ индекс — разные факты: первый значит
        «спросили, у типов сечения нет», второй — «не спрашивали». Квитанция
        печатает их разными словами, поэтому и здесь они разные значения.
        """
        if not isinstance(snapshot, Mapping):
            return None
        levels: dict[str, float] = {}
        types: dict[str, dict[str, Mapping[str, Any]]] = {}
        for pool, rows in snapshot.items():
            if not isinstance(pool, str) or not isinstance(rows, list):
                continue
            for row in rows:
                if not isinstance(row, Mapping):
                    continue
                keys = []
                if row.get("id") is not None:
                    keys.append(f"element_id:{row['id']}")
                if isinstance(row.get("name"), str) and row["name"]:
                    keys.append(f"name:{row['name']}")
                if pool == "levels":
                    elevation = _num(row.get("elevation_mm"))
                    if elevation is not None:
                        for key in keys:
                            levels.setdefault(key, elevation)
                    continue
                section = row.get("section")
                if isinstance(section, Mapping):
                    bucket = types.setdefault(pool, {})
                    for key in keys:
                        bucket.setdefault(key, section)
        return cls(levels, types)

    def level_mm(self, selector: Any) -> float | None:
        key = _sel_text(selector)
        return None if key is None else self.levels.get(key)

    def section(self, pool: str, selector: Any) -> Mapping[str, Any] | None:
        key = _sel_text(selector)
        if key is None:
            return None
        return (self.types.get(pool) or {}).get(key)

    def outer_for_nominal_mm(self, section: Mapping[str, Any],
                             nominal_mm: float) -> float | None:
        """Номинал -> НАРУЖНЫЙ по таблице ТИПА. Ни одного множителя: перевод
        существует потому, что его напечатал документ (`PipeSegment.GetSizes`),
        а не потому, что мы знаем сортамент."""
        for pair in (section.get("sizes") or ()):
            if (not isinstance(pair, (list, tuple)) or len(pair) != 2):
                continue
            nominal, outer = _num(pair[0]), _num(pair[1])
            if nominal is None or outer is None:
                continue
            if abs(nominal - float(nominal_mm)) <= _NOMINAL_TOL_MM:
                return outer
        return None


def _pool_for(op_name: str, param: str, op: Mapping[str, Any]) -> str | None:
    """Пул снапшота, против которого ground разрешает этот операнд.

    Спрашивается у РЕЕСТРА, а не выписывается сюда вторым списком: пул,
    разошедшийся с `spec.OPS`, читал бы сечение чужого рода вещей.
    """
    try:
        from kukai.ir import spec
    except Exception:  # noqa: BLE001 — реестр недоступен: сечений просто нет
        return None
    op_spec = spec.OPS.get(op_name)
    if op_spec is None:
        return None
    for name, pool, _required in op_spec.grounded:
        if name != param:
            continue
        if "{category}" in pool:
            return pool.format(
                category=str(op.get("category") or "structural"))
        return pool
    return None


