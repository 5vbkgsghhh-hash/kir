@dataclass(frozen=True)
class _Cached:
    key: str
    block: dict[str, Any]


#: Кэш на КАНОНИЧЕСКИХ БАЙТАХ пачки — тот же приём, что у подъёма схемы. Один
#: и тот же вход обязан стоить один раз: ход, повторно спросивший ту же пачку
#: (переигровка, две двери одного хода), не платит второй раз. Замер 09.08:
#: 116 мс холодным против 0.28 мс тёплым.
#:
#: Замка нет и не нужно: ключ — sha256 самой пачки, поэтому промах двух потоков
#: стоит лишнего счёта, но не может отдать ЧУЖОЙ ответ. Разные сессии имеют
#: разные пачки по построению.
_CACHE: list[_Cached] = []
_CACHE_MAX = 8


def _bundle_sha(pack: Sequence[Any]) -> str:
    payload = json.dumps(
        [[dict(op) for op in ((p.get("ops") if isinstance(p, Mapping) else p) or ())]
         for p in pack],
        ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def _sections_sha(snapshot: Any) -> str:
    """Отпечаток ровно ТОЙ части снапшота, которая меняет тела.

    Считать sha всего снапшота было бы дороже без пользы: `unique_id`,
    `version_guid` и счётчики экземпляров на оболочку не влияют, а пул
    `family_symbols` бывает в тысячи строк.
    """
    index = SnapshotSections.from_snapshot(snapshot)
    if index is None:
        return "none"
    payload = json.dumps(
        {"levels": index.levels,
         "types": {pool: dict(rows) for pool, rows in index.types.items()}},
        ensure_ascii=False, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


#: ВХОДЫ, КОТОРЫЕ МОГУТ ПРЕВРАТИТЬ ОТВЕТ В ОТКАЗ, И ПОТОМУ ОБЯЗАНЫ БЫТЬ В
#: КЛЮЧЕ КЭША. Список живёт ЗДЕСЬ, рядом с ключом, а не в памяти автора.
#:
#: ТРЕТИЙ СЛУЧАЙ ОДНОГО ДЕФЕКТА В ЭТОМ МОДУЛЕ ЗА НЕДЕЛЮ, и общее у них не
#: тема, а форма — ВЕЛИЧИНА, НЕ ПОКРЫВАЮЩАЯ ТОГО, ЧТО МЕНЯЕТ ОТВЕТ:
#:   * потолок с именем «число ТЕЛ», сравнивавший число ЭЛЕМЕНТОВ (отказывал
#:     при 171 теле из 3 000 названных);
#:   * ключ без `new_from`: та же пачка с другой границей хода — другой ответ
#:     («внесено 45» против «внесено 0»);
#:   * ключ без потолков — этот. Замер 11.08: `MAX_PAIRS=8` -> `over_cap`,
#:     поднят до 100 000 -> **тот же `over_cap` из кэша**, очистка кэша ->
#:     `ok, пар 219`. И бьёт он там, где ответу верят больше всего: потолок
#:     поднимают ИМЕННО потому, что здание отказало.
#:
#: ЗАМОК — В ОТСУТСТВИИ УМОЛЧАНИЯ. `tests/test_clash_cache_key` требует, чтобы
#: КАЖДАЯ функция `_max_*` этого модуля стояла здесь; пятый добавленный
#: потолок уронит тест, а не отдаст однажды оператору чужой ответ.
ANSWER_INPUTS: tuple[tuple[str, Any], ...] = (
    ("max_elements", _max_elements),
    ("max_bodies", _max_bodies),
    ("max_offers", _max_offers),
    ("max_pairs", _max_pairs),
)


def _cache_key(pack: Sequence[Any], snapshot: Any,
               new_from: int | None) -> str:
    """Ключ кэша — ЧИТАЕМАЯ строка, а не один непрозрачный отпечаток.

    ПОЧЕМУ НЕ SHA ЦЕЛИКОМ. Свёрнутые в хеш потолки стали бы невидимы, и
    следующий, кто добавит пятый, не узнал бы, что его надо туда положить, —
    то есть замок закрывал бы сегодняшний случай и пропускал завтрашний.
    Поэтому МАЛЫЕ входы стоят в ключе ИМЕНАМИ и значениями, а сворачивается
    только то, что велико: пачка бывает в тысячи операций, снапшот — в тысячи
    строк пула, и держать их в ключе целиком значило бы платить памятью за
    читаемость там, где она не нужна.

    `new_from=none` и `new_from=1` — РАЗНЫЕ ключи намеренно: первое значит «о
    дельте не спрашивали» (базис `none`), второе — «граница на первой
    программе» (базис `whole_bundle_new`), и это разные ответы.
    """
    parts = [f"bundle={_bundle_sha(pack)}",
             f"sections={_sections_sha(snapshot)}",
             f"new_from={'none' if new_from is None else int(new_from)}"]
    parts += [f"{name}={reader()}" for name, reader in ANSWER_INPUTS]
    return "|".join(parts)


def _cache_get(key: str) -> dict[str, Any] | None:
    for item in _CACHE:
        if item.key == key:
            return dict(item.block)
    return None


def _cache_put(key: str, block: dict[str, Any]) -> None:
    _CACHE.append(_Cached(key, dict(block)))
    while len(_CACHE) > _CACHE_MAX:
        _CACHE.pop(0)


def bundle_clash_report(pack: Sequence[Any], *, snapshot: Any = None,
                        new_from: int | None = None
                        ) -> dict[str, Any] | None:
    """Пачка программ -> блок квитанции о коллизиях. НИКОГДА не бросает.

    `snapshot` — снапшот открытой модели той же сессии (`ground`). Без него
    поведение прежнее буква в букву: тела строятся только из чисел самой
    программы, а «толщина живёт в типе» остаётся названной дырой. С ним у
    заявленных стен, плит и колонн ПОЯВЛЯЕТСЯ тело.

    `None` возвращается РОВНО в одном случае — флаг выключен. Всё остальное,
    включая перебор потолка и внутренний сбой, возвращается текстом: молчание
    читается как «коллизий нет», а это самое дорогое враньё из возможных.
    """
    if not clash_enabled():
        return None
    try:
        return _report(pack, snapshot=snapshot, new_from=new_from)
    except Exception as exc:  # noqa: BLE001 — квитанция не может стоить хода
        logger.debug("bundle clash check failed", exc_info=True)
        return {
            "schema": BUNDLE_CLASH_SCHEMA,
            "status": "unavailable",
            "message_ru": (
                f"ПРОВЕРКА НА КОЛЛИЗИИ НЕ ВЫПОЛНЕНА: "
                f"{type(exc).__name__}: {exc}. Это НЕ «коллизий нет» — "
                f"это «не смотрели»."),
        }


def _over_cap(key: str, snap: Any, phase: str, work: int, cap: int,
              seconds: float) -> dict[str, Any]:
    """Перебор потолка — НАЗВАННЫЙ отказ, а не тихий ноль находок."""
    block = {
        "schema": BUNDLE_CLASH_SCHEMA,
        "status": "over_cap",
        "phase": phase,
        "bodies": len(snap.records),
        "work": work,
        "cap": cap,
        "message_ru": (
            f"ПРОВЕРКА НА КОЛЛИЗИИ НЕ СЧИТАЛАСЬ: тел {len(snap.records)}, и "
            f"они стоят так плотно, что {phase} стоит {work} пар при потолке "
            f"хода {cap} (≈{seconds:.1f} с). Это НЕ «коллизий нет» — это «не "
            f"смотрели». Спроси проверку по интересующей части здания "
            f"отдельной пачкой."),
    }
    _cache_put(key, block)
    return block


