#: Разделитель квалифицированного идентификатора операции пачки. РАВЕН
#: `design_check._BUNDLE_SEP` намеренно и держится тестом: адрес находки о
#: коллизии и адрес находки вердикта обязаны вести в одну строку скрипта.
_BUNDLE_SEP = "/"

#: Приставка тела, порождённого ребром графа: один оп — много тел.
_SEGMENT_SEP = "#"


def bundle_oid(position: int, oid: str) -> str:
    """Идентификатор операции В МАСШТАБЕ ПАЧКИ: `p1/wall3`.

    Квалифицируется ВСЕГДА, а не при столкновении, — по той же причине, что и
    в `design_check._bundle_oid`: `id` уникален внутри программы, между
    программами совпадение законно, и адрес починки обязан зависеть только от
    того, к чему он ведёт.
    """
    return f"p{position}{_BUNDLE_SEP}{oid}"


def _num(value: Any) -> float | None:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    value = float(value)
    return value if value == value and abs(value) != float("inf") else None


def _pt3(value: Any) -> list[float] | None:
    if not isinstance(value, (list, tuple)) or len(value) < 3:
        return None
    out = [_num(c) for c in value[:3]]
    return None if any(c is None for c in out) else [float(c) for c in out]


def _sel_text(value: Any) -> str | None:
    """Селектор -> короткая строка адреса. Ничего не разрешает: адрес нужен
    находке, чтобы её было к чему привязать глазами."""
    if isinstance(value, Mapping):
        by, raw = value.get("by"), value.get("value")
        if by and raw is not None:
            return f"{by}:{raw}"
        return None
    if isinstance(value, str) and value.strip():
        return value.strip()
    return None


def _mesh_bbox(mesh: Any) -> tuple[list[float], list[float]] | None:
    if not isinstance(mesh, Mapping):
        return None
    verts = mesh.get("vertices_mm")
    if not isinstance(verts, (list, tuple)) or not verts:
        return None
    lo = [float("inf")] * 3
    hi = [float("-inf")] * 3
    for raw in verts:
        pt = _pt3(raw)
        if pt is None:
            return None
        for k in range(3):
            lo[k] = min(lo[k], pt[k])
            hi[k] = max(hi[k], pt[k])
    return lo, hi


def _type_name_of(op: Mapping[str, Any]) -> str | None:
    for field in ("duct_type", "pipe_type", "tray_type", "conduit_type",
                  "type", "symbol"):
        text = _sel_text(op.get(field))
        if text is not None:
            return text
    return None


def _graph_bodies(op: Mapping[str, Any]) -> list[tuple[list[float], list[float], float | None]]:
    """Рёбра графа -> оси тел. Форма узла/ребра взята у `connect.graph_validate`
    (`{"id", "xyz_mm"}` и `{"from", "to", "diameter_mm"?}`), а не угадана."""
    nodes: dict[str, list[float]] = {}
    for node in op.get("nodes") or ():
        if not isinstance(node, Mapping):
            continue
        nid, pt = node.get("id"), _pt3(node.get("xyz_mm"))
        if isinstance(nid, str) and pt is not None:
            nodes[nid] = pt
    default_dia = _num(op.get("diameter_mm"))
    out: list[tuple[list[float], list[float], float | None]] = []
    for seg in op.get("segments") or ():
        if not isinstance(seg, Mapping):
            continue
        a, b = nodes.get(str(seg.get("from"))), nodes.get(str(seg.get("to")))
        if a is None or b is None:
            continue
        dia = _num(seg.get("diameter_mm"))
        out.append((a, b, default_dia if dia is None else dia))
    return out


