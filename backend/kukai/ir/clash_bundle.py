def category_of(op: Mapping[str, Any]) -> str | None:
    """Категория Revit операции либо `None` — тела эта операция не создаёт.

    ОТВЕЧАЕТ РЕЕСТР (`spec.op_result_categories`), а не local-таблица. Своя
    таблица здесь была, дублировала реестровую и УЖЕ разошлась с ней —
    обоснование и числа в `REGISTRY_GAPS`. Реестр вдобавок умеет то, чего
    копия не умела: разрешает категорию по ЗАКРЫТОМУ перечислению самой
    операции (`category` у колонны и тела, `variety` у фундамента, проёма,
    рельефа), поэтому отдельных разрешателей здесь больше нет.

    ЧТО ЭТО ВСЁ-ТАКИ НЕ ОДНО ОТНОШЕНИЕ, и почему поэтому есть пересечение с
    `hulls.KIND_TABLE`, а не прямое присваивание. Реестр отвечает на вопрос
    ПЕРЕПИСИ — «какие категории оп создаёт в документе», и честно возвращает
    НЕСКОЛЬКО, когда программа не решает (ограждение: отдельное или на
    лестнице; фундамент-плита: перекрытие или фундамент). Этому модулю нужен
    другой ответ — «каким правилом `KIND_TABLE` судить тело», и он обязан
    быть один. Поэтому:

      * из ответа реестра выбрасывается `DirectShape` — ключ ПЕРЕПИСИ, а не
        категория Revit;
      * остаётся то, что `KIND_TABLE` знает: у ограждения из пары выживает
        ровно `OST_StairsRailing`, и прежняя догадка стала следствием;
      * если и после этого осталось больше одной — выбор НАЗВАН в
        `REGISTRY_GAPS`, а не сделан молча.
    """
    name = str(op.get("op") or "")
    try:
        cats = _REGISTRY_CATEGORIES(op) or ()
    except Exception:  # noqa: BLE001 — реестра нет: остаются названные строки
        logger.debug("registry category lookup failed", exc_info=True)
        cats = ()
    cats = tuple(c for c in cats if c not in _CENSUS_ONLY_KEYS)
    if len(cats) > 1:
        try:
            from kukai.clash import hulls as _hulls

            known = tuple(c for c in cats
                          if _hulls.KIND_TABLE.get(c) is not None)
            if known:
                cats = known
        except Exception:  # noqa: BLE001 — таблицы нет: сузить нечем
            logger.debug("kind table lookup failed", exc_info=True)
    # Ноль (реестр молчит) либо больше одной (реестр не решает) — оба случая
    # закрывает НАЗВАННАЯ строка `REGISTRY_GAPS`, и обе видны одним списком.
    chosen = cats[0] if len(cats) == 1 else REGISTRY_GAPS.get(name)
    if chosen is None:
        return None
    # ПОСЛЕДНЕЕ СЛОВО — У ТАБЛИЦЫ ТЕЛ, И ЭТО ОТВЕТ НА ДРУГОЙ ВОПРОС, ЧЕМ
    # РЕЕСТР. Реестр прав, что `create_room` создаёт `OST_Rooms`: помещение в
    # документе появляется. Но телом оно не бывает (`KIND_TABLE` -> eligible
    # False), и держать его в переписи ЭЛЕМЕНТОВ значило бы раздувать
    # знаменатель «без тела» вещами, у которых тела не бывает в природе, —
    # то есть врать ровно тем числом, ради честности которого весь этот учёт
    # и заведён. Такие операции остаются в `no_body` со своим ИМЕНЕМ.
    try:
        from kukai.clash import hulls as _hulls

        # НЕИЗВЕСТНАЯ таблице категория — тоже НЕ тело, и это не придирка:
        # `create_text` -> `OST_TextNotes` таблица не знает вовсе, и без этой
        # строки 130 текстовых примечаний `snowdon_plumb_v4` въехали бы в
        # перепись элементов, раздув знаменатель «без тела» на вещи, у
        # которой тела не бывает.
        rule = _hulls.KIND_TABLE.get(chosen)
        if rule is None or not rule.eligible:
            return None
    except Exception:  # noqa: BLE001 — таблицы нет: отдаём как есть
        logger.debug("kind table eligibility lookup failed", exc_info=True)
    return chosen


