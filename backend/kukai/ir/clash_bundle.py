#: Причины, собираемые из ИМЕНИ ОПЕРАЦИИ: перечислить поимённо нельзя, реестр
#: растёт. Суффикс -> класс; проверяется после точного совпадения.
_BLIND_SUFFIX: tuple[tuple[str, str], ...] = (
    ("_geometry_not_expressed", "op_expresses_no_body"),
    ("_graph_has_no_readable_segment", "not_declared_by_program"),
)


def blind_class(reason: str) -> str:
    """Причина безтелесности -> её КЛАСС, либо пусто.

    ГРАНИЦА ЗАМКА, И ОНА ЗАПИСАНА СЛОВАМИ, ПОТОМУ ЧТО МОЛЧАЩИЙ ЗАМОК ХУЖЕ
    ОТСУТСТВУЮЩЕГО. Тест `test_clash_coverage` вылавливает непричисленные
    причины РЕГЕКСПОМ по исходнику этого модуля, и он ловит ровно две формы:
    строковый литерал в `blame("...")` и в `return "..."`. Причина, собранная
    КОНКАТЕНАЦИЕЙ или пришедшая из чужого модуля, мимо него пройдёт.

    Поэтому динамические причины разрешены здесь ровно в одной форме —
    `f"{op_name}<суффикс>"` с суффиксом из `_BLIND_SUFFIX`, — и это не стиль,
    а условие работы замка: любая другая сборка имени обязана либо получить
    свой суффикс здесь, либо быть выписана литералом. Пока это правило
    держится, «пусто» означает дыру в таблице, а не дыру в проверке.

    Пусто значит «причина не отнесена», и это ОШИБКА, которую ловит тест, а не
    рабочее значение: безымянный класс в отчёте неотличим от отсутствия
    проблемы — ровно то, от чего этот модуль лечится с первой волны.
    """
    known = BLIND_CLASSES.get(reason)
    if known is not None:
        return known
    for suffix, name in _BLIND_SUFFIX:
        if reason.endswith(suffix):
            return name
    return ""


