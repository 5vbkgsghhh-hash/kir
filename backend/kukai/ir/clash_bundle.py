# 4. ТЕКСТ, КОТОРЫЙ ЧИТАЕТ МОДЕЛЬ
# ═════════════════════════════════════════════════════════════════════════

#: ПОТОЛОК ОБОСНОВАНИЯ В ТЕКСТЕ. Обоснования правил целиком лежат в `rules`
#: полезной нагрузки, и печатать их в тексте ВТОРОЙ раз — платить контекстом
#: дважды за одно. Замер 11.08: одно обоснование стоит 317 символов, а их в
#: квитанции бывает два (снятое правило + отказанное), то есть 634 из 2 700 —
#: почти два суждения. Здесь остаётся ЗАЧИН, которого хватает узнать правило,
#: а спорить с ним читатель идёт в данные.
_WHY_IN_TEXT = 170


def _why_brief(text: str) -> str:
    """Обоснование -> зачин для текста. Обрыв НАЗЫВАЕТСЯ, а не молчит."""
    text = str(text or "")
    if len(text) <= _WHY_IN_TEXT:
        return text
    return text[:_WHY_IN_TEXT].rsplit(" ", 1)[0] + "… (целиком в `rules`)"


def render_bundle_clash(block: Mapping[str, Any],
                        report: Mapping[str, Any]) -> str:
    """Блок -> строки квитанции. Публичная подпись прежняя: только текст."""
    return _render(block, report)[0]


def _render(block: Mapping[str, Any], report: Mapping[str, Any]
            ) -> tuple[str, dict[str, int]]:
    """Блок -> строки квитанции. ЗНАМЕНАТЕЛЬ ПЕРЕД УТВЕРЖДЕНИЕМ: сначала
    сколько тел вообще участвовало, и только потом находки. «Находок 0» без
    числа тел — это утверждение ни о чём, и читается оно как «всё чисто».

    ОБРЕЗАЕТСЯ ТОЛЬКО СЕРЕДИНА. Потолок текста режет СПИСОК НАХОДОК, а не
    учёт полноты: до этой волны обрезание шло по хвосту, и первым под нож
    уходило «БЕЗ ТЕЛА» — то самое, чего в квитанции не хватать не имеет права.
    """
    bodies = block["bodies"]
    # ТРИ ЧИСЛА В ОДНОЙ СТРОКЕ И НИ ОДНОГО СЛОЖЕНИЯ. «Спор», «снято правилом»
    # и «не видели» отвечают на три разных вопроса, и склеивать их в «находок
    # N» значит терять ровно тот факт, который дороже всего: не видели.
    head = [
        f"КОЛЛИЗИИ (ЗАЯВЛЕНО, не построено): тел в поиске {bodies}, "
        f"пар {block['total_findings']} — СПОРОВ {block.get('disputes', 0)}, "
        f"снято правилом {block.get('filtered', 0)}, "
        f"без суждения {block.get('unjudged', 0)}, "
        f"без тела (НЕ ВИДЕЛИ) {block['without_body']}"
    ]
    # ПЕРВОЙ СТРОКОЙ — ОТВЕТ НА ЗАДАННЫЙ ВОПРОС. Инженер перед кнопкой
    # спрашивает не «сколько пересечений в здании», а «что внёс Я». Замер
    # 11.08 на пересборке `snowdon_plumb_v4`: пар 45, внесено ходом 0 —
    # и до этой строки обе цифры выглядели одной.
    basis = str(block.get("delta_basis") or "none")
    if basis != "none":
        origins = block.get("by_origin") or {}
        prior = int(origins.get("both_prior", 0))
        whole = basis == "whole_bundle_new"
        head.append(
            f"ВНЕСЛА ЭТА ПАЧКА: {block.get('introduced', 0)} из "
            f"{block['total_findings']} — правило «новой хотя бы одна "
            f"сторона» ({origins.get('both_new', 0)}+"
            f"{origins.get('one_new', 0)}, см. `introduced_rule`); СТОЯЛО ДО "
            f"НЕЁ: {prior}"
            + (" — у первой пачки предшественника нет, новым считается ВСЁ"
               if whole else " — не работа этой пачки"))
    body: list[str] = []
    for row in block["findings"]:
        body.append(f"  [{row.get('rung_name', '')}] {row['text']}")
        move = str(row.get("next_move") or "")
        if move:
            body.append(f"      ХОД: {move}")
    rest = block["total_findings"] - len(block["findings"])
    if rest > 0:
        body.append(f"  … ещё {rest}")
    lines: list[str] = []
    why_of = block.get("rules") or {}

    def _ranked(counts: Mapping[str, int]) -> list[tuple[str, int]]:
        return sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))

    by_rule = block.get("filtered_by_rule") or {}
    if by_rule:
        # НИЧЕГО МОЛЧА. Правило, снявшее пару, обязано назваться: снятая
        # молча пара и ненайденная пара в квитанции неразличимы. Обоснование
        # печатается у ГЛАВНОГО правила дня — одно на все его находки, а не
        # по копии в каждой строке.
        ranked = _ranked(by_rule)
        lines.append("СНЯТО ПРАВИЛОМ: " + ", ".join(
            f"{name} ×{count}" for name, count in ranked))
        top_why = why_of.get(ranked[0][0])
        if top_why:
            lines.append(
                f"  ПОЧЕМУ `{ranked[0][0]}`: {_why_brief(top_why)}")
    # ХОЗЯИН — СТРОКОЙ, И ТОЛЬКО КОГДА ОН ЧТО-ТО ГОВОРИТ. Печатается ровно
    # `contradicts`: это состояние, в котором пара ВЫГЛЯДИТ узлом по ярлыкам
    # («дверь и стена — конечно узел»), а заявление автора говорит обратное.
    # `absent` и `unknown` в текст не идут — они свойство ЗАПРОСА, а не
    # здания, и живут числом в `by_host_state`.
    host_states = block.get("by_host_state") or {}
    contradicts = int(host_states.get("contradicts") or 0)
    if contradicts:
        lines.append(
            f"ХОЗЯИН ОБЪЯВЛЕН ДРУГОЙ (пар: {contradicts}): у этих пар автор "
            f"САМ назвал хозяина, и это не вторая сторона находки — "
            f"перекрытие с элементом, внутри которого элемент не живёт. "
            f"Такая пара НЕ снимается: снять её значило бы принять догадку "
            f"по паре ярлыков вместо заявления автора. Подтверждено хозяином "
            f"и снято: {int(host_states.get('confirms') or 0)}; рёбер хозяина "
            f"в пачке: {block.get('hosted_edges', 0)}.")
    outside = int(host_states.get("host_out_of_scope") or 0)
    if outside:
        # ГРАНИЦА ЧТЕНИЯ НАЗЫВАЕТСЯ ОТДЕЛЬНОЙ СТРОКОЙ И НИКОГДА НЕ ВИНИТ
        # АВТОРА. Замер по корпусу: у `snowdon_elec_v1` таких рёбер 959 из
        # 1 001, и все ведут в связанный файл. Строка, обвиняющая автора 959
        # раз в чужой границе, — это отчёт, который читатель выбросит вместе
        # с настоящими находками.
        lines.append(
            f"ХОЗЯИН ЗА ГРАНИЦЕЙ ИЗВЛЕЧЕНИЯ (пар: {outside}): разбор называет "
            f"хозяина, которого мы не извлекали — связанный файл либо датум. "
            f"Про вмещение у этих пар сказать НЕЧЕГО; это не ошибка автора и "
            f"не оправдание паре.")
    refused = block.get("refused_by_rule") or {}
    if refused:
        # «ПРАВИЛА НЕТ» — ОТДЕЛЬНАЯ СТРОКА, И С ОБОСНОВАНИЕМ ВСЕГДА. Это не
        # находка и не тишина: это список того, чего не хватает ЗАЯВЛЕНИЮ,
        # чтобы пару вообще можно было судить. Выдумать правило дешевле, чем
        # признаться, — и потому признание печатается целиком.
        ranked_refused = _ranked(refused)
        lines.append("БЕЗ СУЖДЕНИЯ, ПРАВИЛО ОТКАЗАНО: " + ", ".join(
            f"`{name}` ×{count}" for name, count in ranked_refused))
        # ОБОСНОВАНИЕ — ОДНО, У ГЛАВНОГО ПРАВИЛА ДНЯ, тем же приёмом, что и у
        # снятых правил строкой выше. Прежде оно печаталось по копии на
        # КАЖДОЕ отказанное правило (344 символа за строку), то есть росло
        # без потолка и вытесняло находки — а находки и есть то, ради чего
        # квитанцию читают. Остальные обоснования целиком лежат в `rules`.
        top_refused = why_of.get(ranked_refused[0][0])
        if top_refused:
            lines.append(
                f"  ПОЧЕМУ `{ranked_refused[0][0]}`: "
                f"{_why_brief(top_refused)}")

    if not bodies:
        lines.append(
            "НИ ОДНОГО ТЕЛА: программа не выражает ни одной оболочки, поиск "
            "не состоялся вовсе. Это НЕ «коллизий нет».")
    if block["without_body"]:
        by_cat = block["without_body_by_category"]
        who = ", ".join(f"{cat} {n}" for cat, n in sorted(by_cat.items())[:6])
        # ПРИЧИНА, А НЕ ТОЛЬКО ЧИСЛО. «Толщина живёт в типе» перестало быть
        # единственным ответом в тот день, когда снапшот начал её нести:
        # теперь квитанция обязана различать «не спрашивали у документа»,
        # «спросили, у типа нет» и «операция не выражает размер вовсе».
        why = block.get("no_geometry_reasons") or {}
        top = ", ".join(f"{name} ×{count}" for name, count
                        in sorted(why.items(), key=lambda kv: (-kv[1], kv[0]))[:4])
        tail = (
            "снапшот открытой модели этой проверке НЕ передан, поэтому "
            "толщины и сечения ТИПОВ не читались вовсе"
            if block.get("type_sections") != "read" else
            "геометрия типов прочитана, и у этих элементов её всё равно "
            "не хватило")
        # СЫРЫЕ ПРИЧИНЫ УБРАНЫ ИЗ ТЕКСТА НАМЕРЕННО: они целиком лежат в
        # `no_geometry_reasons`, а в тексте их место заняли КЛАССЫ — тот же
        # факт, но отвечающий на вопрос «где это чинить». Две строки на одну
        # тему стоили 521 символ из 2 000 неснимаемых (замер 11.08).
        classes = block.get("blind_by_class") or {}
        by_class = "; ".join(
            f"{BLIND_CLASS_RU.get(name, name).split(':')[0]} {count}"
            for name, count in sorted(classes.items(),
                                      key=lambda kv: (-kv[1], kv[0])))
        lines.append(
            f"БЕЗ ТЕЛА (НЕ ВИДЕЛИ): {block['without_body']}"
            + (f" — {who}" if who else "")
            + (f". ПОЧЕМУ: {by_class}" if by_class else "")
            + ". Пропущены ПО ПОСТРОЕНИЮ, а не по порогу.")
        # ПЯТЬ КЛАССОВ ОТДЕЛЬНОЙ СТРОКОЙ. Число «без тела» отвечает на пять
        # вопросов сразу и потому ни на один: «автор не объявил» чинит автор
        # следующим ходом, «знает живой документ» — стадия ground, «операция
        # тела не выражает» не чинится вовсе. Читатель, которому дали одно
        # число, прочтёт его как «прибор слеп» и выбросит весь отчёт.

    walls_hulled = ((report.get("census") or {}).get("by_category", {})
                    .get("OST_Walls", {}).get("hulled", 0))
    if walls_hulled:
        lines.append(
            "СТЫКИ СТЕН ВНЕ ПРОВЕРКИ: в углах примыкания Revit достраивает "
            "материал за концами объявленной оси, и программа его не "
            "выражает — оболочка стены его не содержит.")
    nominal = (report.get("census") or {}).get("sections", {})
    if nominal.get("nominal_only_total"):
        lines.append(
            f"ТОЛЬКО НОМИНАЛ: {nominal['nominal_only_total']} — капсула по "
            f"номиналу тела не содержит (ДУ100: 100 против 114.3), оболочки "
            f"нет.")
    blind = [f"{name} ×{n} ({_BLIND_OPS[name]})"
             for name, n in sorted(block["ops_without_body"].items())
             if name in _BLIND_OPS]
    if blind:
        lines.append("ВНЕ ПРОВЕРКИ, И ЭТО МОЖЕТ ПРЯТАТЬ КОЛЛИЗИЮ: "
                     + ", ".join(blind[:4]))
    # ПРЕДЕЛ ДЕЛЬТЫ НАЗЫВАЕТСЯ ВСЕГДА, а не только когда её спросили:
    # «внесено 0» без этой строки читается как «и ни с чем в документе не
    # столкнулись», а этого проверка не знает и знать не может.
    lines.append(
        "НЕ ВИДИТ ВООБЩЕ: только объявленное сессией. Стоящее в документе в "
        "поиск не входит никогда (ground даёт уровни и ТИПЫ, ни одного "
        "экземпляра) — столкновение с чужой стеной не «не найдено», а "
        "НЕВИДИМО.")
    lines.append(
        f"область `{block['scope_id']}` (ВСЕ физические пары), судит "
        f"`{block.get('judgement_schema', '')}`. СВИДЕТЕЛЬСТВО, не отказ.")
    # СЕРЕДИНА ЖЕРТВУЕТСЯ ПЕРВОЙ. Голова (три числа) и хвост (полнота) в
    # квитанции обязаны быть всегда; список находок — то, что можно спросить
    # ещё раз, поэтому режется он.
    fixed = len("\n".join(head + lines)) + 1
    room = max(0, _TEXT_CAP - fixed)
    kept: list[str] = []
    used = 0
    for index, line in enumerate(body):
        # ПЕРВОЕ СУЖДЕНИЕ ПРОХОДИТ ВСЕГДА, вместе со своим ХОДОМ. «СПОРОВ 3»
        # без единой показанной строки — это отчёт, который читатель обязан
        # выбросить, а выброшенный отчёт хуже отсутствующего.
        if index >= 2 and used + len(line) + 1 > room:
            kept.append(f"  … список суждений обрезан, показано {len(kept)}")
            break
        kept.append(line)
        used += len(line) + 1
    # БЮДЖЕТ ВОЗВРАЩАЕТСЯ ЧИСЛОМ ОТТУДА, ГДЕ ОН И СЧИТАЕТСЯ. Второй расчёт
    # «сколько заняла неснимаемая часть» рядом с тестом разошёлся бы с этим
    # на первой же новой строке, а замок, меряющий не то, что растёт, хуже
    # отсутствующего.
    budget = {"fixed": fixed, "cap": _TEXT_CAP, "room": room,
              "shown": len([x for x in kept if x.startswith("  [")]),
              "of": len([x for x in body if x.startswith("  [")])}
    return "\n".join(head + kept + lines), budget
