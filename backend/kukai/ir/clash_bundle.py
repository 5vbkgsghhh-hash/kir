def _new_ids(elements: Sequence[Mapping[str, Any]],
             new_from: int | None) -> frozenset[str] | None:
    """Адреса тел, объявленных ЭТИМ ходом, либо `None` — границы не называли.

    Граница приходит НОМЕРОМ ПОЗИЦИИ В ПАЧКЕ, а не `seq` журнала: пачку сюда
    отдаёт вызывающий, и только он знает, какая позиция соответствует какой
    записи после вытеснения головы. Перевод делает `verdict.clash_only`, у
    которого журнал под рукой; здесь считается уже позиция.
    """
    if new_from is None:
        return None
    out: set[str] = set()
    for el in elements:
        sid = str(el.get("element_id") or "")
        head, sep, _ = sid.partition(_BUNDLE_SEP)
        if not sep or not head.startswith("p"):
            continue
        try:
            position = int(head[1:])
        except ValueError:
            continue
        if position >= new_from:
            out.add(sid)
    return frozenset(out)


def _row_for_receipt(row: dict[str, Any], rules: Mapping[str, str],
                     rung_actions: Mapping[str, str]) -> dict[str, Any]:
    """Строка суждения -> строка КВИТАНЦИИ: без того, что блок уже несёт.

    ЧТО ЭТО ЧИНИТ (замер 11.08.2026, `snowdon_plumb_v4`, сериализация без
    пробелов): блок 9 931 символ, из них `findings` 5 586 (56%), а сам текст
    квитанции — 2 586 (26%). Внутри `findings` пяти строк:

        why        975 (195 на строку) — ОДНА строка на ПРАВИЛО
        action_ru  815 (163 на строку) — ОДНА строка на СТУПЕНЬ

    Пять `why`, РАЗНЫХ среди них одна: 772 символа из 975 — чистый повтор. И
    тот же текст уже лежит в блоке ОДИН раз, в `rules`.

    ЭТО НАРУШЕННОЕ СТАРОЕ ПРАВИЛО, А НЕ НОВОЕ. `clash_judgement.Judged.why_ru`
    объявляет его дословно — «обоснование одно на правило, а находок по нему
    бывает восемьдесят: печатать его в каждой строке значит утопить в нём и
    находки». Текст ему следовал, нагрузка — нет.

    ПОЛЕ НЕ ИСЧЕЗАЕТ И НЕ ПУСТЕЕТ. Молчаливое исчезновение хуже удаления:
    читатель получил бы `KeyError` в лучшем случае и `None` в худшем. Вместо
    текста едет УКАЗАТЕЛЬ на то место блока, где он лежит один раз.

    СЖАТИЕ ЖИВЁТ ЗДЕСЬ, А НЕ В `Judged.as_dict`. Судья пары — чистая функция с
    публичной формой, и её строка обязана быть самодостаточной: тот, кто зовёт
    `judge` напрямую, никакого блока рядом не имеет. Экономия на повторе — это
    забота КВИТАНЦИИ, и решается она там, где таблицы уже собраны.
    """
    out = dict(row)
    rule_id = str(out.get("rule_id") or "")
    if rule_id and str(out.get("why") or "") == str(rules.get(rule_id) or ""):
        out["why"] = f"см. rules[{rule_id}]"
    rung = str(out.get("rung") or "")
    if rung and str(out.get("action_ru") or "") == str(
            rung_actions.get(rung) or ""):
        out["action_ru"] = f"см. rung_actions[{rung}]"
    return out


def _blind_by_class(geometry: "BundleGeometry") -> dict[str, int]:
    """Причины безтелесности -> счёт ПО КЛАССАМ, включая операции без элемента.

    `never_a_body` считается по `no_body` (операция не создала элемента
    вовсе), остальные — по `no_geometry` (элемент есть, тела нет). Складывать
    их в одно число нельзя: у первых нечему быть телом, у вторых тело есть в
    натуре и нет у нас.

    Причина без класса НЕ ПРОПАДАЕТ: она уезжает под ключом `unclassified`,
    чтобы дыра в таблице была видна в отчёте, а не только в тесте.
    """
    out: dict[str, int] = {}
    if geometry.no_body:
        out["never_a_body"] = sum(geometry.no_body.values())
    for reason, count in geometry.no_geometry.items():
        name = blind_class(reason) or "unclassified"
        out[name] = out.get(name, 0) + count
    return dict(sorted(out.items()))


def _report(pack: Sequence[Any], *, snapshot: Any = None,
            new_from: int | None = None) -> dict[str, Any]:
    from kukai.clash import detect as _detect
    from kukai.clash import review as _review
    from kukai.ir import clash_judgement as _judgement

    # Ключ кэша считается по пачке И по снапшоту: одна и та же пачка против
    # ДРУГОГО документа — другой ответ, и отдать первый было бы враньём того
    # же рода, что и молчание.
    # КЛЮЧ СОБИРАЕТСЯ ОДНИМ МЕСТОМ И ПОКРЫВАЕТ КАЖДЫЙ ВХОД, СПОСОБНЫЙ
    # ПРЕВРАТИТЬ ОТВЕТ В ОТКАЗ, — см. `ANSWER_INPUTS` и `_cache_key`.
    # Прежде он собирался здесь тремя ветками, и потолки в него не входили
    # вовсе: поднявший потолок получал из кэша тот же отказ.
    key = _cache_key(pack, snapshot, new_from)
    cached = _cache_get(key)
    if cached is not None:
        return cached

    started = time.perf_counter()
    geometry = bundle_elements(pack, snapshot=snapshot)
    elements = geometry.elements
    no_body = geometry.no_body
    collisions = geometry.collisions
    # ПЕРВАЯ ЗАСТАВА — ПО ЭЛЕМЕНТАМ, и она называет ЭЛЕМЕНТЫ. Она держит
    # линейную цену разбора пачки; потолок ТЕЛ стоит ниже, ПОСЛЕ снапшота, и
    # меряет тела. Про то, почему осей две, — `_max_elements`.
    cap = _max_elements()
    if len(elements) > cap:
        block = {
            "schema": BUNDLE_CLASH_SCHEMA,
            "status": "over_cap",
            "phase": "разбор пачки",
            "elements": len(elements),
            "cap": cap,
            "message_ru": (
                f"ПРОВЕРКА НА КОЛЛИЗИИ НЕ СЧИТАЛАСЬ: элементов в пачке "
                f"{len(elements)} при потолке хода {cap}. Это НЕ «коллизий "
                f"нет» — это «не смотрели»."),
        }
        _cache_put(key, block)
        return block

    from kukai.clash import snapshot as _snapshot

    origin = {
        "source": "kir-program-bundle",
        "run_dir": "пачка программ сессии",
        "assertion": "self_reported",
        "programs": len(pack),
        # ОТПЕЧАТОК ПАЧКИ, А НЕ КЛЮЧ КЭША. Здесь стояло `key`, и это было
        # неверно ДО этой волны тоже: со снапшотом ключ был sha от
        # sha+секций, то есть поле с именем `bundle_sha256` держало не
        # отпечаток пачки. Волна читаемого ключа сделала расхождение видимым
        # (в поле поехали бы ещё и значения потолков), но не создала его.
        # Провенанс обязан называть ровно то, что называет: это отпечаток
        # ПАЧКИ, по нему находку сверяют с программой, а не с кэшем.
        "bundle_sha256": _bundle_sha(pack),
        "type_sections": "read" if snapshot is not None else "absent",
    }
    snap = _snapshot.build_from_elements(
        elements, origin=origin, profiles=geometry.profiles)
    # ВТОРАЯ ЗАСТАВА — ПО ТЕЛАМ, И ТЕПЕРЬ ОНА ИХ ДЕЙСТВИТЕЛЬНО СЧИТАЕТ. Стоит
    # ПОСЛЕ снапшота намеренно: раньше тел ещё нет, а считать их по элементам —
    # то самое подписывание чужой оси, которым эта застава и болела (замер и
    # числа — в `_max_elements`). Снапшот стоит 174 мс на 16 257 элементах, то
    # есть цена знания настоящего числа тел меньше цены ошибки в нём.
    if len(snap.records) > _max_bodies():
        return _over_cap(key, snap, "сборка тел", len(snap.records),
                         _max_bodies(),
                         len(snap.records) * _US_PER_OFFER / 1e6)
    # ТРЕТЬЯ ЗАСТАВА — ПО ПАРАМ, И ОНА БЕСПЛАТНА. Сетка строится тем же
    # `build_grid`, которым её построит `detect` (те же умолчания: ребро от
    # медианного габарита, slack=0), а верхняя оценка числа пар снимается с
    # её же раскладки: сумма C(k,2) по ячейкам плюс гиганты против всех.
    # Замер: сама оценка — 0.01 мс на 320 телах, сетка — 3 мс. `detect` ниже
    # построит сетку заново, и это осознанная плата: 3-20 мс за то, чтобы
    # решение «считать или отказать» принималось ДО узкой фазы, которая одна
    # и стоит секунды.
    grid = _detect.build_grid(snap.records)
    offers = sum(len(m) * (len(m) - 1) // 2 for m in grid.buckets.values())
    offers += len(grid.oversized) * len(snap.records)
    if offers > _max_offers():
        return _over_cap(
            key, snap, "широкая фаза", offers, _max_offers(),
            offers * _US_PER_OFFER / 1e6)
    # ЧЕТВЁРТАЯ ЗАСТАВА — ПО НАСТОЯЩИМ КАНДИДАТАМ. Оценка выше бывает щедра на
    # порядок (правдоподобная раскладка: 136 892 оффера -> 960 кандидатов), и
    # отказывать по ней значило бы отказывать исправному зданию. Настоящее
    # число стоит одной широкой фазы, которая уже ограничена предыдущей
    # заставой; `detect` ниже построит её ЗАНОВО, и эта двойная плата названа
    # здесь числом, а не спрятана: она и есть цена того, чтобы решение
    # «считать или отказать» принималось ДО узкой фазы.
    cands = _detect.candidate_pairs(
        snap.records, grid, pair_filter=_detect.any_physical_pair_filter)
    if len(cands) > _max_pairs():
        return _over_cap(
            key, snap, "узкая фаза", len(cands), _max_pairs(),
            len(cands) * _MS_PER_PAIR / 1e3)
    report = _detect.detect(snap, pair_filter=_detect.any_physical_pair_filter)
    view = _review.build_review(report, top=_TOP, max_elements=0)

    # ═════ СЛОЙ СУЖДЕНИЯ ═════
    # Детектор отдаёт ПАРЫ; проектировщику нужны СУЖДЕНИЯ. Замер 09.08 на
    # `snowdon_plumb_v5`: из 99 пар 66 стояли на верхней ступени, и все 66 —
    # плиты одного этажа, спорящие только в НАШЕМ огрублении. Слой живёт
    # отдельным модулем и НИЧЕГО не пересчитывает в геометрии пакета.
    # ГРАНИЦА ХОДА -> АДРЕСА ТЕЛ. Позиция в пачке уже зашита в адрес
    # (`p<N>/<id>`), поэтому второго учёта «что нового» не заводится.
    new_ids = _new_ids(elements, new_from)
    # ДВЕ ДВЕРИ — ДВА РАЗНЫХ ОТВЕТА, И ОДНИМ СЛОВОМ ИХ НАЗЫВАТЬ НЕЛЬЗЯ. У
    # чат-двери «до» есть: это то, что сессия объявила прежними ходами. У
    # первого хода сессии предшественника НЕТ ВОВСЕ — материализатор
    # пересборки строит здание с нуля, и «внесено 0» там было бы ровно
    # наоборот. Поэтому граница на первой программе называется отдельно.
    delta_basis = ("none" if new_from is None
                   else ("whole_bundle_new" if new_from <= 1
                         else "session_turn"))
    judgement = _judgement.judge(
        report["findings"], new_ids=new_ids,
        hulls={rec.source_id: rec for rec in snap.records},
        profiles=geometry.profiles, slack=geometry.declaration_slack,
        ops=geometry.op_by_id,
        # ИНДЕКС ПЕРЕДАЁТСЯ ВСЕГДА, даже пустой. Пустой значит «спросили,
        # хозяев не объявлено», отсутствующий — «не спрашивали»; на этом пути
        # второго не бывает никогда, и подменять первое вторым значило бы
        # печатать `unknown` там, где ответ есть.
        hosted=geometry.hosted)
    elapsed_ms = (time.perf_counter() - started) * 1000.0

    census = report["census"]
    completeness = report["search"]["completeness"]
    summary = view["summary"]
    # ТАБЛИЦЫ СОБИРАЮТСЯ ДО СТРОК: строка ссылается на них, а не копирует.
    # Как и `rules`, таблица ступеней несёт ТОЛЬКО сработавшее — печатать все
    # пять означало бы вернуть ту же плату с другой стороны.
    shown = judgement.judged[:_TOP]
    rung_actions = {row.rung: _judgement._RUNG_ACTION[row.rung]
                    for row in shown}
    findings = [_row_for_receipt(row.as_dict(), judgement.justifications,
                                 rung_actions)
                for row in shown]
    totals = census["totals"]
    block: dict[str, Any] = {
        "schema": BUNDLE_CLASH_SCHEMA,
        "status": "ok",
        "scope_id": report["search"]["scope_id"],
        "assertion": "self_reported",
        "bodies": report["search"]["hulls"],
        "elements_considered": totals["eligible"],
        # ЗНАМЕНАТЕЛЬ ЦЕЛИКОМ, а не только сторона MVP: дверь без оболочки —
        # тоже дыра в поиске, хотя в пары MVP она и не входит.
        "without_body": totals["eligible"] - totals["hulled"],
        "without_body_on_mvp_side": completeness["without_hull_on_mvp_side"],
        "search_complete": completeness["complete"],
        "without_body_by_category": {
            cat: row["missing_geometry"] + row["unsupported"]
            for cat, row in census["by_category"].items()
            if row["missing_geometry"] or row["unsupported"]},
        "ops_without_body": dict(sorted(no_body.items())),
        # ПОЧЕМУ У ЭЛЕМЕНТА НЕТ ГЕОМЕТРИИ — СЛОВАМИ. Без этого «тел 0» и
        # «сечение типа не прочиталось» выглядят одинаково, а чинятся в
        # разных местах: одно операндом операции, другое — снапшотом.
        "no_geometry_reasons": dict(sorted(geometry.no_geometry.items())),
        # ПЯТЬ ПРИЧИН, А НЕ ОДНО ЧИСЛО. «Автор не объявил», «знает только
        # живой документ», «операция тела не выражает», «отказал чужой замок»
        # и «операция тела не создаёт» чинятся в ПЯТИ разных местах; плоский
        # список причин заставлял читателя классифицировать их самому, а он
        # этого не сделает и решит, что не видели вообще ничего.
        "blind_by_class": _blind_by_class(geometry),
        "type_sections": "read" if snapshot is not None else "absent",
        "op_id_collisions": collisions,
        "total_findings": summary["total"],
        "duplicates": summary["duplicates"],
        "overlaps": summary["overlaps"],
        "touches": summary["touches"],
        # ТРИ РАЗНЫХ ЧИСЛА, И ОНИ НЕ СКЛАДЫВАЮТСЯ В ОДНО. Пара, снятая
        # ПРАВИЛОМ, пара, которую вообще НЕ ВИДЕЛИ (у элемента нет тела), и
        # «спор» — три разных факта; одно число вместо трёх врёт дважды.
        "judgement_schema": _judgement.JUDGEMENT_SCHEMA,
        # ЧТО ВНЁС ЭТОТ ХОД — отдельным числом от того, что в здании.
        # Замер 11.08: на последнем чанке пересборки `snowdon_plumb_v4` пар
        # 45, и ход не внёс НИ ОДНОЙ. Одно число на оба вопроса всегда
        # отвечает не на тот, который задали.
        "delta_basis": delta_basis,
        "delta_scope": DELTA_SCOPE,
        "by_origin": judgement.by_origin,
        "disputes": len(judgement.actionable),
        "filtered": sum(judgement.filtered_by_rule.values()),
        "unjudged": sum(judgement.refused_by_rule.values()),
        "filtered_by_rule": judgement.filtered_by_rule,
        "refused_by_rule": judgement.refused_by_rule,
        "filtered_by_slack": judgement.filtered_by_slack,
        # РЕБРО ХОЗЯИНА — ЧЕТЫРЬМЯ РАЗНЫМИ ЧИСЛАМИ, И ОНИ НЕ СКЛАДЫВАЮТСЯ.
        # «Хозяин подтвердил», «хозяин объявлен ДРУГОЙ», «хозяина не
        # объявляли» и «индекса не было» — четыре разных факта; одно число
        # вместо четырёх врёт трижды, и дороже всех врёт второе, потому что
        # именно оно — находка, которую догадка по ярлыкам снимала молча.
        "by_host_state": judgement.by_host_state,
        "hosted_edges": len(geometry.hosted),
        # ОБОСНОВАНИЯ ТЕХ ПРАВИЛ, ЧТО СЕГОДНЯ СРАБОТАЛИ — целиком и данными.
        # Правило, снявшее пару и не сказавшее почему, — это тихая фильтрация,
        # то есть ровно то, что этой волной запрещено.
        "rules": judgement.justifications,
        # ДЕЙСТВИЕ СТУПЕНИ — ОДНА СТРОКА НА СТУПЕНЬ, а не копия в каждой
        # находке. То же решение, что у `rules`, и по той же причине: замер
        # 11.08 — 815 символов из 5 586 в `findings` были пятью копиями двух
        # строк. Ступень у находки названа полем `rung`, оно и есть ключ.
        "rung_actions": dict(sorted(rung_actions.items())),
        "by_kind": judgement.by_kind,
        "by_rung": judgement.by_rung,
        "findings": findings,
        "elapsed_ms": round(elapsed_ms, 1),
    }
    if new_ids is not None:
        # «Внесено» СЧИТАЕТСЯ, а не выводится читателем: `both_new + one_new`.
        # Пара с одной новой стороной — тоже вклад хода: без него её не
        # существовало бы вовсе. Ключа НЕТ, когда границы не называли:
        # «внесено 0» и «не спрашивали» — разные ответы.
        block["introduced"] = (judgement.by_origin.get("both_new", 0)
                               + judgement.by_origin.get("one_new", 0))
        # ЧИСЛО НЕ ЕЗДИТ БЕЗ СВОЕГО ПРАВИЛА. Ключ появляется и исчезает
        # ВМЕСТЕ с `introduced`: правило без числа — украшение, число без
        # правила — тот самый невидимый выбор.
        block["introduced_rule"] = INTRODUCED_RULE_RU
    block["message_ru"], block["text_budget"] = _render(block, report)
    # СЧЁТ ЗА НАГРУЗКУ — ЧИСЛОМ И В САМОМ ОТВЕТЕ. Текст нормирован потолком,
    # а блок вокруг него был не нормирован ничем: замер 11.08 — текст 2 586
    # символов внутри блока в 9 931, то есть бюджет стерёг четверть счёта.
    #
    # ПОТОЛКА ЗДЕСЬ НЕ НАЗНАЧАЕТСЯ, и это то же решение, что у `_TEXT_CAP`:
    # сколько модель РЕАЛЬНО платит за эти символы, никто не мерил, а
    # назначить число вместо замера — ровно то, что здесь запрещено. Заперт
    # СТРУКТУРНЫЙ инвариант (строка не повторяет таблицу блока), которому
    # число не нужно, а сама величина едет наружу, чтобы дрейф был виден на
    # проде, а не только в тесте.
    block["text_budget"]["payload_chars"] = len(json.dumps(
        block, ensure_ascii=False, separators=(",", ":"), default=str))
    _cache_put(key, block)
    return block


