"""Тест, оставивший за собой глобальное состояние, называет себя сам.

ПОЧЕМУ ЭТО СТОИТ ЗДЕСЬ, А НЕ В ЧЕТЫРЁХ ПОЧИНЕННЫХ ВЫЗОВАХ. Починка жертвы
прячет производителя: следующая утечка будет ровно так же невидима, как эти
четыре были до замера. Сторож переносит отказ на того, кто мутировал.

ЧЕГО ЭТОТ СТОРОЖ НЕ ДОКАЗЫВАЕТ, названо здесь, потому что рядом ходила
красивая и НЕВЕРНАЯ причина. Считалось, что набор страдает «эпидемией
порядка»: 82 провала без `-p no:randomly` против 12 с ним. Замер 12.08.2026
это опроверг — `pytest-randomly` в venv НЕ УСТАНОВЛЕН (`pip show` →
«Package(s) not found»), поэтому `-p no:randomly` не выключает ничего, а
порядок сбора с флагом и без БАЙТ В БАЙТ одинаков. Порядок здесь
детерминирован сам по себе. Значит этот файл заведён НЕ ради эпидемии
порядка, а ради конкретного измеренного дефекта ниже — и не должен
цитироваться как её лекарство.

Сторож переносит отказ НА ПРОИЗВОДИТЕЛЯ. Тест, изменивший `os.environ` и не
вернувший его, падает сам — с именем ключа и оставленным значением, потому что
«тест утёк состоянием» это жалоба, а «этот тест оставил
`KIR_REJECTIONS_PATH=/tmp/…`, указывающий в удалённый tmpdir» это наряд на
работу.

ЧТО СТОРОЖИТСЯ И ПОЧЕМУ ИМЕННО ЭТО. `os.environ` — не единственное общее
состояние процесса, но единственное, которое ПЕРЕКЛЮЧАЕТ ПРОДОВОЕ ПОВЕДЕНИЕ
из теста: `coverage_feed._DEFAULT is None` означает «фид ВЫКЛЮЧЕН», поэтому
утёкший `KIR_REJECTIONS_PATH` не перенаправляет сток, а ВКЛЮЧАЕТ его для всего,
что запустится следом, — а читает его арм отказа `compile_program`, самый
хоженый путь набора. Модульные таблицы и кэши сюда не входят намеренно: у них
нет одного общего адреса, и сторож, притворяющийся полным, был бы хуже
отсутствующего.

ГРАНИЦА, названная вслух: сторож видит состояние ПОСЛЕ теста, поэтому мутация
внутри теста, восстановленная им же, для него невидима — и это правильно, она
никому не мешает. И он не ловит утечку, случившуюся на ИМПОРТЕ модуля: к
моменту первого теста она уже часть базовой линии. Такие места видны другим
прибором — обходом AST по голым мутациям.
"""
from __future__ import annotations

import os

import pytest

# ─── ПРОД-`.env` НЕ ДОЛЖЕН РЕШАТЬ, ЧТО ПРОВЕРЯЕТ ЭТОТ НАБОР ──────────────────
#
# ЧТО ПРОИСХОДИТ БЕЗ ЭТОГО БЛОКА (замер 12.08.2026). Любой тест, чья цепочка
# импортов доходит до `kukai.llm.client`, тянет litellm, а тот НА ИМПОРТЕ один
# раз зовёт `load_dotenv()`. python-dotenv ищет файл, поднимаясь вверх ОТ
# СОБСТВЕННОГО ФАЙЛА LITELLM, а litellm лежит внутри общего venv в дереве
# прода — значит поиск приходит в `/opt/kukai-rebuild1/backend/.env` и вливает
# в процесс **129 ключей боевой конфигурации**: `KUKAI_KIR_TOOL=stage2`,
# `KUKAI_TRUTH_GATE=enforce`, `KUKAI_WEAK_SANDBOX=1` — и живые учётные данные.
#
# ЭТО НЕ СВОЙСТВО ЭТОГО ДЕРЕВА. В рабочем дереве, где это писалось, файла
# `.env` НЕТ ВООБЩЕ, и ключи всё равно приезжают: venv общий и лежит внутри
# прода. То самое правило «интерпретатор только из прод-venv», которое держит
# нас честными насчёт `shapely`, и подаёт боевую конфигурацию в любой чекаут.
# Перейти в другое дерево не помогает — на этом боксе негде встать так, чтобы
# этого не происходило.
#
# ПОЧЕМУ СОСЕДНИЙ CONFTEST НЕ ГОДИТСЯ ОБРАЗЦОМ. `backend/tests/conftest.py`
# описан в каноне как «force-overrides the production .env to safe local
# defaults», но делает он другое: монкипатчит ПЯТЬ настроек
# (`KUKAI_AUTH_ENABLED`, `KUKAI_REMOTE_MODE`, `KUKAI_HOST`, `KUKAI_DEBUG`,
# `KUKAI_CORS_ORIGINS`) плюс переписывает адрес БД на `kukai_test`. Пять
# ключей из 129. Скопировать его значило бы оставить ~124 и обе учётки на
# месте и получить зелёную починку, не закрывающую ничего.
#
# МЕХАНИЗМ ВЗЯТ У `kukai/rag/benchmark/hermeticity.py`, А НЕ ВЫДУМАН. Там он
# доказан эмпирически и его порядок НЕСУЩИЙ: сначала форсировать импорт, чтобы
# однократная загрузка случилась, и только потом выталкивать —
# `load_dotenv(override=False)` вытолкнутое не воскрешает. Обратный порядок
# не работает вовсе.
#
# ПРОВЕНАНС ПО НАБЛЮДЕНИЮ, А НЕ ПО ПУТИ. Мы не читаем `.env` и не знаем, где
# он: снимаем окружение ДО форсированного импорта, форсируем, и убираем ровно
# то, что появилось, возвращая ровно то, что изменилось. Такой признак нельзя
# обмануть неверным путём, и он не трогает то, что разработчик выставил в
# своей оболочке сам. Фильтровать по происхождению, а не по виду.
#
# ИМЕНА, НИКОГДА ЗНАЧЕНИЯ — правило того же модуля: среди вытолкнутого есть
# токен администратора и ключ API.
_ENV_BEFORE_LITELLM = dict(os.environ)

try:
    import kukai.llm.client  # noqa: F401 — форсируем однократный load_dotenv СЕЙЧАС
except Exception as _exc:                                  # pragma: no cover
    # Импорт мог не состояться (нет зависимости, сломан модуль). Это НЕ повод
    # молча продолжить: тогда загрузка случится позже, из первого же теста, и
    # снимок окажется бесполезен. Говорим вслух, а не притворяемся чистыми.
    INJECTED_BY_DOTENV: tuple[str, ...] = ()
    DOTENV_NEUTRALISED = False
    _DOTENV_NOTE = f"litellm не импортировался ({type(_exc).__name__}): {_exc}"
else:
    _after = os.environ
    _appeared = [k for k in _after if k not in _ENV_BEFORE_LITELLM]
    _changed = {k: v for k, v in _ENV_BEFORE_LITELLM.items()
                if k in _after and _after[k] != v}
    for _k in _appeared:
        del os.environ[_k]
    os.environ.update(_changed)
    INJECTED_BY_DOTENV = tuple(sorted(_appeared))
    DOTENV_NEUTRALISED = True
    _DOTENV_NOTE = (
        f"убрано {len(_appeared)} ключей, восстановлено {len(_changed)}"
        if (_appeared or _changed) else "прод-.env не дотянулся: убирать нечего")


def pytest_report_header(config):
    """Сказать в шапке прогона, что именно было сделано с окружением.

    Молчаливая гигиена неотличима от её отсутствия: если однажды этот блок
    перестанет срабатывать, шапка изменится, и это увидят раньше, чем
    странные зелёные тесты.
    """
    return f"prod .env: {_DOTENV_NOTE}"


#: Ключи, которым разрешено меняться в течение прогона, — СПИСОК ЗАКРЫТ.
#: Пусто, и это замер, а не незаполненность: на 12.08.2026 ни один тест
#: `kukai/ir/tests` не имеет законной причины оставить переменную за собой.
#: Новая строка сюда обязана приехать с причиной, иначе сторож превратится
#: в место, куда сваливают неудобные падения.
ALLOWED_TO_CHANGE: frozenset[str] = frozenset()

#: Переменные, которые ставит не тест, а сам прогонщик или импортированная
#: библиотека. К порядку тестов они отношения не имеют.
#:
#: `PYTEST_CURRENT_TEST` — СОБСТВЕННЫЙ ШУМ ПРИБОРА, и он едва не стоил всей
#: находки. Pytest ведёт эту переменную сам и меняет её с `(setup)` на
#: `(teardown)` ровно между снимком и сверкой, поэтому первая версия сторожа
#: краснила КАЖДЫЙ тест, у которого нет своего восстановления, — то есть почти
#: весь набор, — и выдавала это за утечки. Прибор, написанный ловить чужое
#: состояние, сначала поймал своё.
_LIBRARY_NOISE: frozenset[str] = frozenset({
    "LITELLM_LOCAL_MODEL_COST_MAP",
    "PYTEST_CURRENT_TEST",
})


def _snapshot() -> dict[str, str]:
    return dict(os.environ)


def _describe(before: dict[str, str], after: dict[str, str]) -> list[str]:
    lines: list[str] = []
    for key in sorted(after.keys() - before.keys()):
        if key in ALLOWED_TO_CHANGE or key in _LIBRARY_NOISE:
            continue
        lines.append(f"  ПОСТАВЛЕНА {key}={after[key]!r}")
    for key in sorted(before.keys() - after.keys()):
        if key in ALLOWED_TO_CHANGE or key in _LIBRARY_NOISE:
            continue
        lines.append(f"  УДАЛЕНА    {key} (было {before[key]!r})")
    for key in sorted(before.keys() & after.keys()):
        if before[key] == after[key]:
            continue
        if key in ALLOWED_TO_CHANGE or key in _LIBRARY_NOISE:
            continue
        lines.append(
            f"  ИЗМЕНЕНА   {key}: {before[key]!r} -> {after[key]!r}")
    return lines


@pytest.fixture(autouse=True)
def _environment_is_returned_as_found(request):
    before = _snapshot()
    yield
    changes = _describe(before, _snapshot())
    if not changes:
        return
    raise AssertionError(
        f"тест оставил за собой окружение процесса — следующий тест увидит "
        f"чужое состояние, и его падение будет выглядеть его собственным:\n"
        + "\n".join(changes)
        + "\n\nВернуть на место: `monkeypatch.setenv/delenv`, "
          "`mock.patch.dict(os.environ, ...)` или `try/finally`. "
          "Если ключ обязан пережить тест — назвать его в "
          "`ALLOWED_TO_CHANGE` этого conftest с причиной."
    )
