def _plural_params() -> dict[str, tuple[str, ...]]:
    """Оп -> его плюральные параметры. Авторитет — реестр, не память."""
    out: dict[str, tuple[str, ...]] = {}
    for name, op in spec.OPS.items():
        ps = tuple(p.name for p in op.params if p.kind in PLURAL_KINDS)
        if ps:
            out[name] = ps
    return out


def _compared_goldens() -> set[str]:
    """Голдены, которые ДЕЙСТВИТЕЛЬНО сравниваются: каталог пересечь PROGRAMS.

    Спрашиваем `PROGRAMS`, а не каталог. 12.08 перепись спросила каталог и
    объявила два опа пришпиленными; четыре файла там — сироты, добавленные
    руками ещё 17.07 и не бывшие в `PROGRAMS` НИКОГДА.
    """
    on_disk = {p.name[: -len(".golden.cs")] for p in GOLDEN_DIR.glob("*.golden.cs")}
    return on_disk & set(PROGRAMS)


def cardinality(value) -> int:
    """Сколько элементов несёт плюральный параметр.

    Словарь считается наравне со списком НАМЕРЕННО: вид `filters` хранит
    предикаты словарём (`{"level_name": "Этаж 1"}`), и первая перепись,
    мерившая только `isinstance(v, list)`, объявила `query_list` нулём —
    собственный артефакт, пойманный печатью СЫРЫХ значений, а не разбором
    вывода. Отсутствие и `None` — честный ноль: `pts_list` считает `None`
    и `[]` одним и тем же «нет проёмов» (authoring_validation).
    """
    if isinstance(value, (list, tuple, dict)):
        return len(value)
    return 0


def _max_cardinality() -> dict[tuple[str, str], tuple[int, str | None]]:
    """(оп, параметр) -> (максимальная мощность, голден, где она достигнута)."""
    plural = _plural_params()
    best: dict[tuple[str, str], tuple[int, str | None]] = {
        (op, p): (0, None) for op, ps in plural.items() for p in ps}
    for gname in sorted(_compared_goldens()):
        for o in PROGRAMS[gname].get("ops", []):
            nm = o.get("op")
            for pname in plural.get(nm, ()):
                n = cardinality(o.get(pname))
                if n > best[(nm, pname)][0]:
                    best[(nm, pname)] = (n, gname)
    return best


def _unpinned() -> set[str]:
    """Оп непришпилен, если ХОТЬ ОДИН его плюральный параметр не дотянул.

    «Хоть один», а не «все»: у `create_group` два независимых плюральных
    параметра (`member_ops`, `placements`), у маршрутизаторов — узлы и
    сегменты, и каждый обходится СВОИМ рукописным циклом. Пин одного не
    говорит ничего о другом.
    """
    best = _max_cardinality()
    return {op for (op, _), (n, _g) in best.items() if n < PLURAL_FLOOR}


