from kukai.ir.tests.test_emitter_scope_contract import PROGRAMS

#: Цель, которой заведомо нет ни в одной программе.
MISSING = "__ZZZ_NOT_AN_OP__"

#: Порог непустоты. Меньше — значит корпус или обходчик разошлись с прибором, и
#: зелёный перестал что-либо утверждать. Замер 12.08: 41.
MIN_SITES = 30


def ref_sites(node: Any, path: tuple = ()) -> Iterator[tuple]:
    """(путь, узел) каждого ``{"by": "ref"}`` на ЛЮБОЙ глубине.

    Родовой обход — в этом вся суть: он НЕ знает списка законных глубин,
    поэтому глубина, добавленная завтра, попадает под проверку без правки.
    """
    if isinstance(node, dict):
        if node.get("by") == "ref" and isinstance(node.get("value"), str):
            yield path, node
        for key, value in node.items():
            yield from ref_sites(value, path + (key,))
    elif isinstance(node, list):
        for index, item in enumerate(node):
            yield from ref_sites(item, path + (index,))


def _at(root: Any, path: tuple) -> Any:
    cur = root
    for step in path:
        cur = cur[step]
    return cur


def _dag_refuses(program: Any) -> bool:
    """Отказала ли программа ИМЕННО по ссылке (L003/L004)."""
    try:
        plan_program(program, bulk=True)
    except KirRefusal as exc:
        return bool({"KIR-L003", "KIR-L004"} & {d.code for d in exc.diagnostics})
    return False


def _plans(program: Any) -> bool:
    try:
        plan_program(program, bulk=True)
    except Exception:  # noqa: BLE001 — здесь важен только факт отказа
        return False
    return True


def _programs() -> Iterator[tuple[str, dict]]:
    for name, raw in sorted(PROGRAMS.items()):
        prog = raw.get("program", raw) if isinstance(raw, dict) else raw
        yield name, prog


class EveryRefIsVisibleToTheDagCheck(unittest.TestCase):

    def test_every_ref_in_the_corpus_is_seen(self):
        """Сломанная цель обязана дать L003/L004 на КАЖДОЙ площадке.

        Молча построенный план с висячей ссылкой — это и есть тот дефект,
        ради которого тест написан: эмиттер сошлётся на несуществующую
        переменную C#, а компилятор промолчит.
        """
        checked = 0
        for name, prog in _programs():
            if not _plans(copy.deepcopy(prog)):
                continue  # отказ ДО мутации: мерили бы не то
            for path, _ in list(ref_sites(prog)):
                checked += 1
                with self.subTest(program=name, path=".".join(map(str, path))):
                    mutated = copy.deepcopy(prog)
                    _at(mutated, path)["value"] = MISSING
                    self.assertTrue(
                        _dag_refuses(mutated),
                        f"{name}: ссылка по пути {path} НЕ ВИДНА DAG-проверке — "
                        f"план строится с висячей целью")
        self.assertGreaterEqual(
            checked, MIN_SITES,
            f"площадок найдено {checked} — прибор ничего не мерил, "
            f"зелёный вакуумный")

    def test_the_probe_can_say_no_in_both_directions(self):
        """Контроль-FAIL и контроль-PASS у самой мутации.

        Мутация, ломающая ЛЮБУЮ программу, доказывает не больше, чем мутация,
        не ломающая никакую: важно, что зонд сделал ровно заявленное.
        """
        sample = None
        for _name, prog in _programs():
            if not _plans(copy.deepcopy(prog)):
                continue
            sites = list(ref_sites(prog))
            if sites:
                sample = (prog, sites[0][0])
                break
        self.assertIsNotNone(sample, "в корпусе не нашлось ни одной ссылки")
        prog, path = sample

        # контроль-PASS: немутированная программа планируется
        self.assertTrue(_plans(copy.deepcopy(prog)))
        # контроль-FAIL: сломанная цель — краснеет
        broken = copy.deepcopy(prog)
        _at(broken, path)["value"] = MISSING
        self.assertTrue(_dag_refuses(broken))
        # обратная сторона: ЗАКОННАЯ цель не должна давать L003 —
        # иначе проверка срабатывает безусловно и ничего не различает
        intact = copy.deepcopy(prog)
        self.assertFalse(
            _dag_refuses(intact),
            "L003 срабатывает на неповреждённой программе — проверка не "
            "различает верную ссылку от висячей")

    def test_the_schema_forbids_inventing_a_new_depth(self):
        """«Убрать возможность» стоит ВЫШЕ обхода: ключ вне схемы отвергнут.

        Машинный разворот не может положить ссылку под собственный ключ —
        отказ приходит на неизвестном поле, ДО вопроса о глубине. Это тот
        случай, когда сильнейшее лекарство уже применено; охрана обхода нужна
        ровно для ЗАКОННЫХ глубоких форм, а не для произвольных.
        """
        prog = {
            "ir_version": "1.0",
            "ops": [
                {"op": "create_level", "id": "L1", "name": "Э1", "elev_mm": 0},
                {"op": "create_wall", "id": "W1",
                 "p0_mm": [0, 0], "p1_mm": [4000, 0], "height_mm": 3000,
                 "level": {"by": "ref", "value": "L1"},
                 "type": {"by": "name", "value": "Стена",
                          "__nested__": {"by": "ref", "value": MISSING}}},
            ],
        }
