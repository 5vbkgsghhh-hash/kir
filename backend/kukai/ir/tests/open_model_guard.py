from __future__ import annotations


#: ЗАКРЫТЫЙ СПИСОК ИСКЛЮЧЕНИЙ К ПРАВИЛУ «`IntegerValue` НЕ УПОМИНАТЬ».
#:
#: Правило существует потому, что целочисленное свойство `ElementId` исчезло:
#: замерено компиляцией 16.08.2026 на живом Roslyn, все шесть версий —
#: `ElementId.IntegerValue` собирается на 2021-2025 и ОТКАЗЫВАЕТ на 2026
#: (CS1061). Поэтому запрет верен и нужен.
#:
#: 🔴 НО ДЕРЖАЛСЯ ОН ПОДСТРОКОЙ, А ПОДСТРОКА ЛОВИТ ЯРЛЫК, А НЕ ВЕТКУ. Волна
#: рабочих наборов законно написала `__w.Id.IntegerValue` — это `WorksetId`,
#: ДРУГОЙ тип, и переименование его не касалось: тем же замером 16.08.2026
#: `WorksetId.IntegerValue` собирается на ВСЕХ ШЕСТИ. Сторож покраснел на
#: исправном коде и два дня читался как дефект компилятора.
#:
#: Список ЗАКРЫТ и каждая строка несёт ЗАМЕР, а не довод. Новое исключение без
#: шестиверсионного замера добавлять запрещено: открытое правило вида «ну это
#: другой тип» превращает сторожа в глушилку на первом же настоящем отказе.
INTEGER_VALUE_EXCEPTIONS: dict[str, str] = {
    "__wr[\"id\"] = __w.Id.IntegerValue;":
        "WorksetId.IntegerValue — замер 16.08.2026: OK на 2021-2026. "
        "Переименование затронуло ElementId, не WorksetId.",
}


def integer_value_offenders(cs: str) -> list[str]:
    """Строки с `IntegerValue`, которых нет в закрытом списке исключений."""
    return [ln.strip() for ln in cs.split("\n")
            if "IntegerValue" in ln and ln.strip() not in INTEGER_VALUE_EXCEPTIONS
            and not ln.strip().startswith("//")]
