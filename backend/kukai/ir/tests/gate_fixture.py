from __future__ import annotations

import unittest

# ИМПОРТ НА УРОВНЕ МОДУЛЯ, И ЭТО НЕ СТИЛЬ. `kukai.llm` тянет litellm, а тот на
# импорте выполняет `load_dotenv()` и вливает ключи боевой конфигурации в
# процесс. Ленивый импорт внутри `setUp` делает это ВО ВРЕМЯ ТЕСТА — и сторож
# окружения из `conftest.py` справедливо объявляет утечку, обвиняя тест,
# который лишь позвал помощника. Замерено: первая редакция помощника дала
# 32 ошибки в паре файлов там, где до неё было 13 красных.
#
# На уровне модуля импорт происходит при СБОРЕ тестов, то есть внутри снимка,
# который conftest делает до прогона, и утечки не создаёт.
from kukai.llm.turn_context import kir_mode_active, publish_kir_mode


def enter_kir_mode(case: unittest.TestCase) -> None:
    """Объявить, что ходы ЭТОГО теста идут в режиме КИР; вернуть как было.

    Восстанавливается НАБЛЮДЁННОЕ значение, а не константа `False`: признак
    живёт в `ContextVar`, и тест, затёрший чужое состояние своей константой,
    чинит глобальное состояние как побочный эффект — ровно та подпорка, которую
    мы уже вынимали из `test_any_query`.
    """
    observed = kir_mode_active()
    publish_kir_mode(True)
    case.addCleanup(publish_kir_mode, observed)
