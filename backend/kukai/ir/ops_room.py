#: То же самое для пространства ОВК: одна строка на эмиттер, свидетеля,
#: реестр категорий результата и приёмку.
MEP_SPACE_CATEGORY = "OST_MEPSpaces"

#: КАТЕГОРИИ ПРОСТРАНСТВЕННЫХ ЭЛЕМЕНТОВ, чьё создание разрешает объемлющую
#: область В МОМЕНТ ВЫЗОВА (`NewRoom`/`NewSpace`), а потому требует, чтобы
#: всё созданное раньше уже было регенерировано. Список — КАТЕГОРИИ, а не
#: опы: оп, который завтра начнёт строить помещение другим вызовом, попадёт
#: под правило по своей категории результата, а не по имени.
SPATIAL_ENCLOSURE_CATEGORIES = ("OST_Rooms", "OST_MEPSpaces")

OPS = [
    OpSpec(
        name="create_room_separator",
        effect=EffectKind.CREATE,
        # МНОГО личностей — см. «РЕЗУЛЬТАТ» в шапке модуля. Спека объявлена
        # здесь, а не в registry_base.py: заводить общий RESULT_* ради одного
        # потребителя значило бы тронуть общий файл без нужды.
        result=ResultSpec(IdentityCardinality.MANY, "segment_ids"),
        family="authoring",
        params=(
            # Открытая ломаная 2..64 точек. Отдельный род от `pts` — см.
            # «ФОРМА ОПА» в шапке модуля.
            ParamSpec("path", "path", required=True),
            ParamSpec("level", "sel", required=True,
                      ref_kinds=(ReferenceKind.LEVEL,)),
        ),
        capability=(("create", "room_separator"),),
        # ТОЧКА С ЗАПЯТОЙ РАЗДЕЛЯЕТ ОБЯЗАТЕЛЬСТВА: translation_cert.py бьёт
        # post именно по ней и требует свидетеля на КАЖДЫЙ кусок. Обещано
        # ровно то, что проверяется, и ни словом больше.
        post=("room separator segments exist (materialized or typed refusal); "
              "созданных сегментов ровно на один меньше, чем точек path "
              "(identity); "
              "каждый созданный сегмент лежит в категории "
              "OST_RoomSeparationLines, а не в обычных модельных линиях "
              "(topology); "
              "level binding == resolved level у каждого сегмента (topology); "
              "концы каждого сегмента == соседняя пара точек path (±5mm) "
              "(geometry)"),
        writes_model=True,
        grounded=(("level", "levels", True),),
        # Тот же допуск концов, что у стены, трубы, оси и балки: это одно и
        # то же обещание об одной и той же величине, и разное число здесь
        # означало бы двух судей о том, что такое «тот же конец».
        tolerances={"endpoint_mm": 5.0},
    ),
    OpSpec(
        name="create_space",
        effect=EffectKind.CREATE,
        # ОДНА личность, и она ССЫЛАЕМА — в отличие от разделителя выше.
        # `NewSpace` возвращает ровно один `Space` (тип доказан CS0029 на
        # всех шести версиях), значит следующий оп вправе на него сослаться.
        result=RESULT_ELEMENT,
        family="authoring",
        params=(
            # Ровно то, что принимает выбранная перегрузка, и ни поля
            # больше. `name`/`number`/`type` — см. шапку модуля: первые два
            # стоили create_room отката ВЕРНОЙ комнаты, третьего у API нет.
            ParamSpec("xy", "pt_xy", required=True),
            ParamSpec("level", "sel", required=True,
                      ref_kinds=(ReferenceKind.LEVEL,)),
        ),
        # Тот же словарь способностей, что у create_room: для модели это
        # один и тот же вопрос «чем описать помещение/пространство».
        capability=(("create", "room_space"),),
        # ТОЧКА С ЗАПЯТОЙ РАЗДЕЛЯЕТ ОБЯЗАТЕЛЬСТВА: translation_cert.py режет
        # `post` именно по ней и требует свидетеля на КАЖДЫЙ кусок. Обещано
        # ровно то, что проверяется.
        #
        # КАТЕГОРИИ В ЭТОМ СПИСКЕ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ПРОПУСК.
        # У разделителя свидетель категории — сердце операции: там
        # `NewRoomBoundaryLines` отдаёт ModelCurve, и «разделитель это или
        # обычная модельная линия» — вопрос открытый. Здесь возвращаемый тип
        # ЕСТЬ `Space` (CS0029, 6/6), а соответствие класса Space категории
        # OST_MEPSpaces — инвариант самого Revit. Проверка, которая не может
        # не сойтись, — это `plate_z_doubling` в другой одежде: она проходит
        # всегда и не доказывает ничего, зато раздувает вид доказанности.
        # Категория при этом НЕ БЕЗ НАДЗОРА: её сверяет ПРИЁМКА по переписи
        # (`spec.OP_RESULT_CATEGORIES["create_space"]`), то есть независимый
        # судья на независимом чтении — там она и стоит.
        post=("space exists and is placed (materialized or typed refusal); "
              "LevelId == resolved level (topology); "
              "LocationPoint == xy (±5mm) (geometry); "
              "Area > 0 — пространство замкнуто, а не создано впустую "
              "(geometry); "
              "GetBoundarySegments даёт хотя бы одну непустую петлю границы "
              "(topology)"),
        writes_model=True,
        grounded=(("level", "levels", True),),
        # Тот же допуск, что у create_room: это одно и то же обещание об
        # одной и той же величине (точка посадки пространственного
        # элемента), и разное число здесь означало бы двух судей.
        tolerances={"location_mm": 5.0},
    ),
]
