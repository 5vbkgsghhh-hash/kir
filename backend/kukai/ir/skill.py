def _render_program(program: dict) -> str:
    """JSON здесь оплачивается токенами — поэтому компактно."""

    return json.dumps(program, ensure_ascii=False, separators=(",", ":"))


#: ДВЕРЬ К ВЫТЕСНЕННЫМ ЛИТЕРАЛАМ. Стоит в §5 одной строкой; без неё программы
#: разборов стали бы тёмными ровно тем же способом, каким пять недель лежал
#: недостижимым `sdk.py`.
WALKTHROUGH_PROGRAMS_TOPIC = "разборы"
_PROGRAMS_POINTER = (
    f"    ПРОГРАММЫ ЭТИХ РАЗБОРОВ ЦЕЛИКОМ — course(\"{WALKTHROUGH_PROGRAMS_TOPIC}\") "
    f"из своего же скрипта: JSON приедет в квитанцию ЭТОГО ЖЕ хода. Здесь "
    f"цепочка рассуждения, потому что она и есть предмет разбора.")


def build_walkthrough_programs_text() -> str:
    """Литералы программ разборов — ПО ЗАПРОСУ, а не в каждом ходу.

    ЗАМЕР, ВЫНУДИВШИЙ ПЕРЕЕЗД (09.08.2026). Шесть литералов §5 весили 2 496
    символов постоянно загружаемого текста при потолке описания 30 000 — то
    есть 8% всего бюджета уходило на JSON, из которого две программы разбора 2
    отличаются РОВНО ОДНИМ ключом `defaults` и печатались по 400 символов
    каждая. Ценность разбора — цепочка рассуждения; JSON её иллюстрирует, и
    иллюстрация не обязана ехать в каждом запросе.

    ПЕРЕЕЗД, А НЕ УДАЛЕНИЕ, И ЭТО ДЕРЖИТ ТЕСТ. Объекты остались теми же
    (`ALL_PROGRAMS`/`REFUSING_PROGRAMS` компилируются и отказывают в
    `test_skill.py`), храповик «показанное = проверенное» переписан на этот
    адрес, а §5 несёт строку, называющую дверь. Показать программу, которой
    никто не запускал, этот пакет по-прежнему не может.
    """
    out = [
        "ПРОГРАММЫ РАЗБОРОВ — то, что в §5 описано словами, здесь целиком.",
        "Сами разборы (зачем каждый шаг) стоят в описании инструмента.",
    ]
    for title, _steps, programs in WALKTHROUGHS:
        out.append("")
        out.append(f"  {title.split(' — ')[0]}")
        for label, program in programs:
            out.append(f"    {label}:")
            out.append(f"      {_render_program(program)}")
    return "\n".join(out)


def build_skill_text() -> str:
    """Курс одним блоком — для склейки в описание инструмента `revit_ir`."""

    out: list[str] = [
        "КРАТКИЙ КУРС: КАК РАБОТАЮТ НА KIR ТЕ, КТО УМЕЕТ.",
        "(Справочник — в схеме инструмента; здесь только то, чего в ней нет.)",
    ]

    def block(title: str, items: tuple[str, ...]) -> None:
        out.append("")
        out.append(f"{title}:")
        out.extend(f"  • {item}" for item in items)

    block(SECTION_TITLES[0], SYSTEM_MODEL)
    block(SECTION_TITLES[1], HOW_A_PRO_STARTS)
    block(SECTION_TITLES[2], SHAPE_OF_REPETITION)

    out.append("")
    out.append(f"{SECTION_TITLES[3]}:")
    for situation, advice in TECHNIQUES:
        out.append(f"  • {situation} — {advice}")

    out.append("")
    out.append(SECTION_TITLES[4])
    # ЛИТЕРАЛЫ ВЫТЕСНЕНЫ 09.08 (см. `build_walkthrough_programs_text`): здесь
    # остаётся цепочка рассуждения — то, ради чего разбор существует, — а JSON
    # приезжает по запросу. Постоянная цена 2 496 символов заменена одной
    # строкой указателя.
    for title, steps, _programs in WALKTHROUGHS:
        out.append("")
        out.append(f"  {title}")
        out.extend(f"    - {step}" for step in steps)
    out.append(_PROGRAMS_POINTER)

    out.append("")
    out.append(f"{SECTION_TITLES[5]}:")
    out.extend(f"  • {item}" for item in GOOD_VS_BAD)
    # ЭТА ПАРА ОСТАЁТСЯ В ПОСТОЯННОМ ТЕКСТЕ, И ЭТО НЕ НЕПОСЛЕДОВАТЕЛЬНОСТЬ.
    # Литералы §5 иллюстрируют ЦЕПОЧКУ РАССУЖДЕНИЯ и без неё бессмысленны —
    # поэтому уехали к ней в `course("разборы")`. Здесь программы и ЕСТЬ
    # предмет: суждение «состав, а не счётчик» проверяется только сравнением
    # двух текстов, и вынести один из них значило бы вынести само сравнение.
    out.append("  ПЛОХАЯ (компилируется, цель по числу закрыта, здания нет):")
    out.append(f"    {_render_program(BAD_ONE_OP_BUILDING)}")
    out.append("  ХОРОШАЯ (состав, а не счётчик):")
    out.append(f"    {_render_program(GOOD_COMPOSED_STOREY)}")

    out.append("")
    out.append(f"{SECTION_TITLES[6]}:")
    for what, meaning in REFUSAL_PLAYBOOK:
        out.append(f"  • {what} — {meaning}")

    block(SECTION_TITLES[7], COSTLY_MISTAKES)
    return "\n".join(out)


