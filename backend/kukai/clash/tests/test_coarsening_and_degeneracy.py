from kukai.clash import geom as G
from kukai.clash import hulls as H


# ═══════════════════════════════════════════════════════════════════════════
# 1. ПРАВИЛО ВЫРОЖДЕННОЙ ВЕТВИ
#
# Когда точный тест пересечения сделали ПЛОЩАДНЫМ — чтобы соседние плитки
# мощения не читались как коллизия, — отрезок и точка получили нулевую площадь
# ПО ОПРЕДЕЛЕНИЮ, и оракул объявил их непересекающимися ни с чем. Вырожденных
# оболочек 9.7–38.2 % НА ЗДАНИЕ, так что это класс, а не четыре пары.
#
# Правило после починки: ПОЛОЖИТЕЛЬНАЯ ПЛОЩАДЬ там, где обе стороны
# полномерны, ТЕОРЕТИКО-МНОЖЕСТВЕННОЕ ПЕРЕСЕЧЕНИЕ там, где хоть одна вырождена.
# Обе половины обязательны: без первой соседи по мощению становятся клешами,
# без второй балка внутри стены объявляется «чисто».
# ═══════════════════════════════════════════════════════════════════════════

_SOLID = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 0.0, 1000.0)


def test_a_degenerate_hull_inside_a_solid_is_an_overlap_not_clear():
    """Случай `aabb_line` из `ORACLE_LIMITS`: балка ВНУТРИ стены.

    Оракул до починки отвечал «чисто», `geom` — −100.0 мм, и `geom` был прав
    во всех четырёх разобранных руками парах. Здесь та же форма, собранная из
    чистой геометрии: отрезок-подошва с нулевой площадью, целиком внутри тела.
    """
    line = G.Prism(((400, 500), (600, 500)), 400.0, 600.0)
    assert H.hull_degeneracy(line) == "prism_degenerate_footprint"
    assert G.signed_distance(_SOLID, line) < 0.0, (
        "вырожденная оболочка внутри тела прочитана как непересекающаяся — "
        "ровно тот дефект, из-за которого оракул был слеп к 9.7–38.2 % "
        "оболочек на здание")


def test_a_point_degenerate_hull_inside_a_solid_is_an_overlap():
    """Случай `aabb_point` из `ORACLE_LIMITS` (две пары из четырёх, −15.0 мм).

    Точка — предельная вырожденность: у неё нулевая и площадь, и длина.
    """
    point = G.Prism(((500, 500),), 400.0, 600.0)
    assert H.hull_degeneracy(point) == "prism_degenerate_footprint"
    assert G.signed_distance(_SOLID, point) < 0.0


def test_a_degenerate_hull_outside_a_solid_stays_clear():
    """ВТОРАЯ СТОРОНА, без которой первая ничего не значит.

    Правило «вырожденное пересекает по множеству» обязано уметь сказать НЕТ:
    тест, который зелен и когда вырожденное всегда пересекает всё, не отличает
    починку от противоположной поломки.
    """
    outside = G.Prism(((4000, 500), (6000, 500)), 400.0, 600.0)
    assert G.signed_distance(_SOLID, outside) > 0.0


def test_full_dimensional_neighbours_sharing_a_face_are_contact_not_overlap():
    """ПЕРВАЯ ПОЛОВИНА ПРАВИЛА, и она же причина, по которой ввели площадь.

    Две плитки мощения, соприкасающиеся гранью, обязаны дать РОВНО ноль:
    касание, а не перекрытие. Если бы полномерные пары судили теоретико-
    множественным пересечением, общая грань дала бы непустое пересечение и
    каждое мощение здания приехало бы как поле коллизий.
    """
    a = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 0.0, 100.0)
    b = G.Prism(((1000, 0), (2000, 0), (2000, 1000), (1000, 1000)), 0.0, 100.0)
    assert G.signed_distance(a, b) == 0.0


def test_the_degeneracy_is_named_by_the_census_not_silently_ok():
    """Вырожденность обязана быть НАЗВАНА, а не проглочена: оболочка нулевого
    объёма ничего не может доказать, и число таких оболочек — часть честного
    знаменателя, а не служебная мелочь."""
    plane = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 300.0, 300.0)
    assert H.hull_degeneracy(plane) == "prism_zero_height"
    assert "prism_zero_height" in H.DEGENERACIES
    assert H.hull_degeneracy(_SOLID) == "ok"


# ═══════════════════════════════════════════════════════════════════════════
# 2. МЕХАНИЗМ ПЕРВЫЙ: ВЫПУКЛАЯ ОБОЛОЧКА ЗАЛИВАЕТ ДЫРЫ
#
# Один из двух механизмов, которыми объяснились ВСЕ 66 «критичных» находок:
# споров с оператором на настоящем здании — ноль, а 62 из 76 плит не
# пересекались по объявлению вовсе. Заливка дыры — не погрешность числа, она
# СОЗДАЁТ пару, которой в здании нет.
# ═══════════════════════════════════════════════════════════════════════════

def _slab_with_a_hole():
    el = {"element_id": "f0", "category": "OST_Floors",
          "bbox_min_mm": [0, 0, 3000], "bbox_max_mm": [1000, 1000, 3200]}
    profile = {
        "profile_available": True,
        "exterior_loop": [[0, 0], [1000, 0], [1000, 1000], [0, 1000]],
        "curve_kinds": [["line"] * 4, ["line"] * 4],
        "arc_midpoints": [[None] * 4, [None] * 4],
        "holes": [[[300, 300], [700, 300], [700, 700], [300, 700]]]}
    rec, refusal = H.build_hull(el, profile=profile)
    assert rec is not None, refusal
    return rec


#: Тело, стоящее В ДЫРЕ плиты: шахта, стояк, лестничный проём.
_IN_THE_HOLE = G.Prism(((450, 450), (550, 450), (550, 550), (450, 550)),
                       3000.0, 3200.0)


def test_the_carved_hull_says_clear_where_the_convex_cover_fabricates_an_overlap():
    """ЗАМЕР МЕХАНИЗМА, ОДНОЙ ПАРОЙ И ДВУМЯ ЧИСЛАМИ.

    Одна и та же плита, одно и то же тело в её проёме:

        подошва с вырезанной дырой   ->  +150.0 мм, ЧИСТО
        выпуклое накрытие той же     ->  −200.0 мм, ПЕРЕКРЫТИЕ

    350 мм размаха на одной паре, и знак разный. Никакого порога тут не
    трогали: разницу целиком создаёт форма подошвы. Отсюда и правило зоны —
    прежде чем объявлять коллизию, спроси, не твоя ли аппроксимация её
    создала.
    """
    carved = _slab_with_a_hole()
    convex = G.Prism(
        G.convex_footprint([(0, 0), (1000, 0), (1000, 1000), (0, 1000)]),
        3000.0, 3200.0)
    carved_sd = G.signed_distance(carved.hull, _IN_THE_HOLE)
    convex_sd = G.signed_distance(convex, _IN_THE_HOLE)
    assert carved_sd > 0.0, "тело в проёме прочитано как коллизия"
    assert convex_sd < 0.0, (
        "выпуклое накрытие перестало заливать дыру — механизм, на котором "
        "стоит вывод о 66 находках, больше не воспроизводится, и вывод надо "
        "перепроверять, а не радоваться зелёному")
    assert carved_sd - convex_sd > 300.0


def test_a_hole_is_carved_and_the_shape_of_the_footprint_is_published():
    """ОГРУБЛЕНИЕ ОБЪЯВЛЯЕТСЯ, А НЕ ПОДРАЗУМЕВАЕТСЯ — прецедент
    `arc_outward_slack_mm`: оболочка, ставшая тоньше или толще молча, ничем не
    отличается от неверной."""
    rec = _slab_with_a_hole()
    assert rec.extra["holes_declared"] == 1
    assert rec.extra["holes_carved"] == 1
    assert rec.extra["footprint_form"] == "decomposed"
    assert rec.extra["footprint_cells"] > 1
    pieces = G.footprint_pieces(rec.hull)
    assert pieces is not None and len(pieces) == rec.extra["footprint_cells"]


def test_a_concave_outline_is_decomposed_rather_than_convex_hulled():
    """L-образная плита: вогнутость обязана пережить построение оболочки.

    Выпуклая оболочка L залила бы вырез целиком — тот же механизм, что у дыры,
    только снаружи контура.
    """
    el = {"element_id": "f1", "category": "OST_Floors",
          "bbox_min_mm": [0, 0, 3000], "bbox_max_mm": [1000, 1000, 3200]}
    profile = {"profile_available": True,
               "exterior_loop": [[0, 0], [1000, 0], [1000, 300], [300, 300],
                                 [300, 1000], [0, 1000]],
               "curve_kinds": [["line"] * 6], "arc_midpoints": [[None] * 6],
               "holes": []}
    rec, refusal = H.build_hull(el, profile=profile)
    assert rec is not None, refusal
    assert rec.extra["footprint_form"] == "decomposed"
    in_the_notch = G.Prism(((600, 600), (700, 600), (700, 700), (600, 700)),
                           3000.0, 3200.0)
    assert G.signed_distance(rec.hull, in_the_notch) > 0.0
    convex = G.Prism(G.convex_footprint(profile["exterior_loop"]),
                     3000.0, 3200.0)
    assert G.signed_distance(convex, in_the_notch) < 0.0


def test_no_hull_source_claims_to_be_exact():
    """Ни один источник оболочки не выдаёт грейд `exact`, и это НЕ придирка к
    слову: `confirmed` читается только из `exact`, поэтому обещание точности
    здесь превратило бы огрубление в подтверждённую коллизию."""
    assert "exact" not in set(H.GRADE_BY_SOURCE.values())


