# 3. МЕХАНИЗМ ВТОРОЙ: ИНТЕРВАЛ [z − t, z + t] ФАБРИКУЕТ 2t
#
# Второй из двух. Толщина, взятая как «отметка плюс-минус допуск», создаёт 2t
# перекрытия ИЗ НИЧЕГО — у двух плит, объявленных на соседних отметках, из
# воздуха появляется общая толща. Ниже — храповик: объявленный интервал по z
# обязан доезжать до оболочки БЕЗ расширения, а нулевая толщина обязана
# остаться нулевой и НАЗВАННОЙ.
# ═══════════════════════════════════════════════════════════════════════════

def test_a_zero_thickness_declaration_stays_zero_and_is_named():
    """Плита, объявленная одной отметкой, не получает тела.

    Раздуть её до `[z − t, z + t]` значило бы выдать 2t толщи, которой в
    объявлении нет; вместо этого пролёт остаётся нулевым, а вырожденность
    получает ИМЯ и попадает в перепись.
    """
    el = {"element_id": "f2", "category": "OST_Floors",
          "bbox_min_mm": [0, 0, 3000], "bbox_max_mm": [1000, 1000, 3000]}
    rec, refusal = H.build_hull(el)
    assert rec is not None, refusal
    assert G.z_span(rec.hull) == (3000.0, 3000.0)
    assert H.hull_degeneracy(rec.hull) == "aabb_plane"


def test_the_declared_z_span_reaches_the_hull_unwidened():
    el = {"element_id": "f3", "category": "OST_Floors",
          "bbox_min_mm": [0, 0, 3000], "bbox_max_mm": [1000, 1000, 3200]}
    rec, refusal = H.build_hull(el)
    assert rec is not None, refusal
    assert G.z_span(rec.hull) == (3000.0, 3200.0)


def test_slabs_that_only_share_a_plane_do_not_overlap():
    """ХРАПОВИК НА САМ МЕХАНИЗМ. Две плиты, стоящие одна на другой, делят
    ровно плоскость. Любое расширение интервала по z — хоть на допуск, хоть на
    полтолщины — немедленно даст здесь отрицательное число, то есть
    сфабрикованное перекрытие там, где здание его не содержит.
    """
    lower = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 0.0, 200.0)
    upper = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 200.0, 400.0)
    assert G.signed_distance(lower, upper) == 0.0
    apart = G.Prism(((0, 0), (1000, 0), (1000, 1000), (0, 1000)), 250.0, 450.0)
    assert G.signed_distance(lower, apart) == 50.0
